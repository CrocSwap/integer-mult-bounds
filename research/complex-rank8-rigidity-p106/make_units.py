#!/usr/bin/env python3
"""Census of 5- and 6-subsets of P112 under verify.py's generators, a PR1560 pivot per orbit, and the generator
words of COVER.json.gz; regenerates UNITS.json and COVER.json.gz, which verify.py rechecks (needs numpy;
verify.py does not).

    python3 -I -B research/complex-rank8-rigidity-p106/make_units.py --out-dir /new/dir

Method, extending the P107 pivots package (PR1568) by one level: enumerate the group H generated by the 8
generators (172032 elements) with a BFS tree, so each element has a word. Label all quadruples by H-orbit with a
transporter from the orbit's first member in colex order. A k-subset c (k = 5, 6) gets the key (j, m): j is the
least (k-1)-orbit label among its sub-(k-1)-subsets s, and m is the least Stab(rep_j)-orbit point among the
images g^-1(c \\ s) over the s with label j, where g carries rep_j onto s. Two k-subsets are H-equivalent iff
their keys agree; the canonical member of a key's orbit is rep_j + {m}, and the units are these canonical
members. The orbit sizes are checked to sum to C(112, k). Pivot: the first live frame, in verify.py's frame order,
that passes the criterion (float ranks here; verify.py redoes them exactly).
"""
import argparse
import gzip
import itertools
import json
import sys
from math import comb
from multiprocessing import Pool
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import verify as V  # noqa: E402

GA = np.array(V.G, dtype=np.int64)
FM = np.zeros((len(V.FRAMES), V.NL), dtype=bool)
for _n, _F in enumerate(V.FRAMES):
    FM[_n, list(_F)] = True


def components(n, edges):
    par = list(range(n))

    def f(a):
        while par[a] != a:
            par[a] = par[par[a]]
            a = par[a]
        return a

    for a, b in edges:
        par[f(a)] = f(b)
    return len({f(a) for a in range(n)})


def passes(live, F):
    """Float-rank version of verify.criterion, used only to propose pivots."""
    LF = FM[~(FM[:, ~live].any(axis=1))]
    non = np.array([i for i in np.nonzero(live)[0] if i not in F])
    blocks = {}
    for i in non:
        t = tuple(f for f in F if GA[i, f])
        blocks.setdefault(t, [0, 0])[sum(1 for f in t if GA[i, f] < 0) % 2] += 1
    if len(blocks) < 14:
        return False
    cov = {p for t, c in blocks.items() if (c[0] == 4 and c[1]) or (c[1] == 4 and c[0])
           for p in itertools.combinations(t, 2)}
    if len(cov) < 28:
        return False
    for k, l in itertools.combinations(F, 2):
        I = non[(GA[non, k] != 0) & (GA[non, l] != 0)]
        sub = LF[:, I]
        if components(len(I), [tuple(np.nonzero(r)[0]) for r in sub[sub.sum(axis=1) == 2]]) != 1:
            return False
    for k in F:
        I = non[GA[non, k] != 0]
        if np.linalg.matrix_rank(np.unique(LF[:, I], axis=0).astype(float)) != len(I) - 7:
            return False
    return True


def pivot(X):
    live = np.zeros(V.NL, dtype=bool)
    live[V.P112] = True
    live[list(X)] = False
    for n in np.nonzero(~(FM[:, ~live].any(axis=1)))[0]:
        if passes(live, V.FRAMES[n]):
            return V.FRAMES[n]
    return None


def closure(gens):
    gs = [np.array(g, dtype=np.uint8) for g in gens]
    e = np.arange(V.NL, dtype=np.uint8)
    seen, elems, parent, pgen, frontier = {e.tobytes(): 0}, [e], [-1], [-1], [0]
    while frontier:
        nxt = []
        for n in frontier:
            for gi, g in enumerate(gs):
                q = g[elems[n]]  # apply elems[n], then g
                if q.tobytes() not in seen:
                    seen[q.tobytes()] = len(elems)
                    elems.append(q)
                    parent.append(n)
                    pgen.append(gi)
                    nxt.append(len(elems) - 1)
        frontier = nxt
    return np.array(elems), parent, pgen


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-dir', required=True)
    ap.add_argument('--jobs', type=int, default=8)
    args = ap.parse_args()
    out = Path(args.out_dir)
    for f in ('UNITS.json', 'COVER.json.gz'):
        if (out / f).exists():
            print(f'refusing to overwrite {out / f}')
            return 2
    gens = V.stabiliser(V.FRAME0)[::V.GEN_STEP]
    E, parent, pgen = closure(gens)
    NH = len(E)
    pos = np.full(V.NL, -1)
    pos[V.P112] = np.arange(112)
    P112 = np.array(V.P112)
    EP = pos[E[:, V.P112]].astype(np.int16)  # H on positions 0..111 of P112
    INV = np.argsort(EP, axis=1).astype(np.int16)
    elem = {EP[n].tobytes(): n for n in range(NH)}
    assert len(elem) == NH
    INVIDX = np.array([elem[INV[n].tobytes()] for n in range(NH)])

    def word(n):
        w = []
        while parent[n] >= 0:
            w.append(pgen[n])
            n = parent[n]
        return ''.join(map(str, w[::-1]))

    tab = np.array([[comb(x, j + 1) for j in range(6)] for x in range(112)], dtype=np.int64)

    def rank(a):
        a = np.sort(a, axis=1)
        return sum(tab[a[:, j], j] for j in range(a.shape[1]))

    subs4 = np.array(list(itertools.combinations(range(112), 4)), dtype=np.int64)
    byrank = np.empty(len(subs4), dtype=np.int64)
    byrank[rank(subs4)] = np.arange(len(subs4))
    lab = np.full(len(subs4), -1, dtype=np.int64)
    tr = np.full(len(subs4), -1, dtype=np.int64)
    reps4 = []
    while (lab < 0).any():
        q = subs4[byrank[np.nonzero(lab < 0)[0][0]]]
        rr = rank(EP[:, q].astype(np.int64))
        _, first = np.unique(rr, return_index=True)
        lab[rr[first]], tr[rr[first]] = len(reps4), first
        reps4.append(tuple(int(x) for x in np.sort(q)))

    def stab(R):
        R = np.array(R)
        cand = np.nonzero(np.isin(EP[:, R[0]], R))[0]
        ok = cand[(np.sort(EP[cand][:, R], axis=1) == np.sort(R)).all(axis=1)]
        sub = EP[ok]
        return len(ok), sub.min(axis=0), ok[sub.argmin(axis=0)]

    def tables(reps):
        OM = np.zeros((len(reps), 112), np.int16)
        TO = np.zeros((len(reps), 112), np.int64)
        sizes = []
        for j, R in enumerate(reps):
            st, OM[j], TO[j] = stab(R)
            sizes.append(NH // st)
        return OM, TO, sizes

    def canon(C, lab_of, OM, TO):
        """Keys of the rows of C and, for each, an element index carrying the row onto its canonical member."""
        best = np.full(len(C), np.iinfo(np.int64).max)
        bg = np.zeros(len(C), np.int64)
        bs = np.zeros(len(C), np.int64)
        for r in range(C.shape[1]):
            j, g = lab_of(np.delete(C, r, axis=1))  # EP[g] carries rep_j onto the sub-subset
            y = INV[g, C[:, r]]
            key = j.astype(np.int64) * 112 + OM[j, y]
            better = key < best
            best[better], bg[better], bs[better] = key[better], g[better], TO[j, y][better]
        H = EP[bs[:, None], INV[bg]]
        return best, np.array([elem[h.tobytes()] for h in H])

    def lab4(S):
        k = rank(S)
        return lab[k], tr[k]

    OM4, TO4, sizes4 = tables(reps4)
    assert sum(sizes4) == comb(112, 4)

    def level(cands, lab_of, OM, TO, k):
        keys = np.empty(len(cands), np.int64)
        hs = np.empty(len(cands), np.int64)
        for a in range(0, len(cands), 20000):
            keys[a:a + 20000], hs[a:a + 20000] = canon(cands[a:a + 20000], lab_of, OM, TO)
        uk, first = np.unique(keys, return_index=True)
        reps = [tuple(int(x) for x in np.sort(EP[hs[i]][cands[i]])) for i in first]
        order = sorted(range(len(reps)), key=lambda n: reps[n])
        reps = [reps[n] for n in order]
        index = {int(uk[n]): m for m, n in enumerate(order)}
        OMk, TOk, sizes = tables(reps)
        assert sum(sizes) == comb(112, k), (k, sum(sizes))
        # cover: candidate -> (unit index, word for the element carrying the unit onto the candidate)
        cover = [[index[int(key)], word(int(INVIDX[h]))] for key, h in zip(keys, hs)]
        print(f'{len(cands)} candidates, {len(reps)} orbits of {k}-subsets; sizes sum to C(112,{k})', flush=True)
        return reps, index, cover, OMk, TOk

    cand5 = np.array(sorted({tuple(sorted(q + (x,))) for q in reps4 for x in range(112) if x not in q}))
    reps5, index5, cover5, OM5, TO5 = level(cand5, lab4, OM4, TO4, 5)

    def lab5(S):
        keys, h = canon(S, lab4, OM4, TO4)
        return np.array([index5[int(k)] for k in keys]), INVIDX[h]

    cand6 = np.array(sorted({tuple(sorted(R + (x,))) for R in reps5 for x in range(112) if x not in R}))
    reps6, _, cover6, _, _ = level(cand6, lab5, OM5, TO5, 6)
    # Level 1 words: triple-orbit representative + one line -> quadruple representative.
    c4 = sorted({tuple(sorted(o[0] + (x,))) for o in V.triple_orbits(gens) for x in V.P112 if x not in o[0]})
    cover4 = []
    for c in c4:
        k = int(rank(np.array([sorted(int(pos[x]) for x in c)]))[0])
        cover4.append([int(lab[k]), word(int(tr[k]))])
    L = lambda Y: tuple(int(P112[x]) for x in Y)  # positions are increasing in line ID
    with Pool(args.jobs) as pool:
        piv5 = pool.map(pivot, [L(r) for r in reps5], chunksize=8)
        piv6 = pool.map(pivot, [L(r) for r in reps6], chunksize=16)
    if any(F is None for F in piv5 + piv6):
        raise SystemExit('a unit has no passing pivot')
    units = {'p107': [list(L(r)) + list(F) for r, F in zip(reps5, piv5)],
             'p106': [list(L(r)) + list(F) for r, F in zip(reps6, piv6)]}
    (out / 'UNITS.json').write_text('{"p107": [\n' + ',\n'.join(json.dumps(u) for u in units['p107'])
                                    + '\n], "p106": [\n' + ',\n'.join(json.dumps(u) for u in units['p106'])
                                    + '\n]}\n')
    data = json.dumps({'reps4': [list(L(r)) for r in reps4], 'cover4': cover4, 'cover5': cover5,
                       'cover6': cover6}, separators=(',', ':')).encode()
    (out / 'COVER.json.gz').write_bytes(gzip.compress(data, mtime=0))
    print(f'{len(units["p107"])} + {len(units["p106"])} units with pivots; '
          f'{len(cover4)} + {len(cover5)} + {len(cover6)} cover words')
    return 0


if __name__ == '__main__':
    sys.exit(main())
