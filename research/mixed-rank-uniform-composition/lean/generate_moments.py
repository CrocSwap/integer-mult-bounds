"""Generate proposed dyadic endpoints from the immutable paid and target histograms."""

import argparse
import json
import subprocess
from decimal import Decimal, localcontext
from fractions import Fraction as Q
from pathlib import Path

HEAD = "87fbf4f7b35b0f18ab12b5767775a9a424cf0b15"
PKG = "research/p104-mixed-rank-supplier"
S = 160
BITS = 352


def artifact(name):
    return json.loads(subprocess.check_output(["git", "show", f"{HEAD}:{PKG}/{name}.json"]))


def enclosure(r, a):
    with localcontext() as ctx:
        ctx.prec = 90
        candidate = int(Decimal(r) ** (Decimal(a.numerator) / Decimal(a.denominator)) * (1 << S))
    # These are proposals. The Lean proof checks both sides using only integers.
    return candidate-2, candidate+3


def claim(r, a):
    lower, upper = enclosure(r,a)
    return f"⟨{r}, {a.numerator}, {a.denominator}, {lower}, {upper}⟩"


def table(name, a, p, t):
    rows = []
    for rank in sorted(set(p) | set(t)):
        rows.append(f"  ⟨{claim(rank,a)}, {p.get(rank,0)}, {t.get(rank,0)}⟩")
    return f"def {name} : List Row := [\n" + ",\n".join(rows) + "]\n"


def counts(raw):
    return {int(rank): qty for rank,qty in raw.items()}


def generate():
    bit, complex_report = (artifact(name) for name in ("BIT","AUDIT"))
    btc = Q(bit["separation"]["trial"])
    cpc = Q(complex_report["outer"]["finite_compiler"]["tested"])
    p,t = (counts(bit["native"][key]) for key in ("paid","targets"))
    pc,tc = (counts(complex_report["signed"][key]) for key in ("paid","productive"))
    caps = {k:Q(v) for k,v in bit["separation"]["upper_caps"].items()}
    start = """import DyadicRoot

/-! Dyadic enclosures for the complete pinned BIT and complex rank histograms.
Generated by generate_moments.py. Root certificates use integer arithmetic. -/
namespace RankMoments

open DyadicRoot

structure Row where
  power : Claim
  paid : Nat
  target : Nat

set_option maxRecDepth 65536
set_option maxHeartbeats 40000000
"""
    blocks = [start, f"def bits : Nat := {BITS}\ndef frac : Nat := {S}\ndef grid : Nat := 2^frac\n"]
    blocks += [table("bitMain",1-btc,p,t), table("bitLow",1-btc+Q(11,50),p,{}),
               table("bitHigh",1-btc+Q(13,50),p,{}),table("bitDrop",1-btc-Q(17,50),{},t),
               table("complexMain",1-cpc,pc,tc),table("complexTilt",1-cpc+Q(1,7),pc,{})]
    scalar = [("lowCut",10,Q(11,50)),("highCut",11,Q(13,50)),("floorCost",16,Q(17,50)),
              ("complexCut",11,Q(1,7)),("complexCost",11,cpc)]
    for name,r,a in scalar:
        blocks.append(f"def {name} : Claim := {claim(r,a)}\n")
    names = ["bitMain","bitLow","bitHigh","bitDrop","complexMain","complexTilt"]
    blocks.append("def scalarRows : List Claim := [" + ", ".join(name for name,_,_ in scalar) + "]\n")
    for name in names:
        blocks.append(f"theorem {name}_ok : ({name}.map Row.power).all (valid bits frac) = true := by decide +kernel\n")
    blocks.append("theorem scalars_ok : scalarRows.all (valid bits frac) = true := by decide +kernel\n")
    blocks.append("""
def tables : List (List Row) := [bitMain, bitLow, bitHigh, bitDrop, complexMain, complexTilt]
def claims : List Claim := tables.flatMap (fun xs => xs.map Row.power) ++ scalarRows

theorem table_sound (c : Claim) (hc : c ∈ claims) :
    0 < c.den ∧ c.lo^c.den ≤ c.rank^c.num * 2^(frac*c.den) ∧
      c.rank^c.num * 2^(frac*c.den) ≤ c.hi^c.den := by
  apply valid_sound bits
  apply List.all_eq_true.mp _ c hc
  simp only [claims, tables, List.flatMap_cons, List.flatMap_nil, List.all_append,
    List.all_nil, Bool.and_true, bitMain_ok, bitLow_ok, bitHigh_ok, bitDrop_ok,
    complexMain_ok, complexTilt_ok, scalars_ok]

def upperPaid (xs : List Row) (select : Nat → Bool := fun _ => true) : Nat :=
  (xs.map (fun row => if select row.power.rank then row.paid * row.power.hi else 0)).sum

def lowerTarget (xs : List Row) : Nat := (xs.map (fun row => row.target * row.power.lo)).sum
def upperTarget (xs : List Row) : Nat := (xs.map (fun row => row.target * row.power.hi)).sum
def targetCount (xs : List Row) : Nat := (xs.map Row.target).sum

def ratioBelow (x y num den : Nat) : Prop := 0 < y ∧ x*den < num*y
instance (x y num den : Nat) : Decidable (ratioBelow x y num den) :=
  inferInstanceAs (Decidable (0 < y ∧ x*den < num*y))
""")
    ratios=[
        ("bit_alpha","upperPaid bitMain","lowerTarget bitMain",caps["alpha"]),
        ("bit_first_low","upperPaid bitLow (fun r => r ≤ 4) * grid","lowCut.lo * lowerTarget bitMain",caps["grades_1_to_4_first"]),
        ("bit_rest_low","upperPaid bitLow * grid","lowCut.lo * lowerTarget bitMain",caps["grades_1_to_4_rest"]),
        ("bit_first_high","upperPaid bitHigh (fun r => 4 < r) * grid","highCut.lo * lowerTarget bitMain",caps["grades_above_4_first"]),
        ("bit_rest_high","upperPaid bitHigh * grid","highCut.lo * lowerTarget bitMain",caps["grades_above_4_rest"]),
        ("bit_discard","floorCost.hi * upperTarget bitDrop","grid * lowerTarget bitMain",caps["discarded_targets"]),
        ("complex_alpha","upperPaid complexMain","lowerTarget complexMain",1-Q(1,10**27)),
        ("complex_gamma","upperPaid complexTilt * grid","complexCut.lo * lowerTarget complexMain",Q(31,32)),
        ("complex_delta","12 * targetCount complexMain * grid^2","complexCost.lo * lowerTarget complexMain",Q(31,32)),
    ]
    for name, x,y,a in ratios:
        blocks.append(f"theorem {name} : ratioBelow ({x}) ({y}) {a.numerator} {a.denominator} := by decide +kernel\n")
    blocks.append("\nend RankMoments\n\n#print axioms RankMoments.table_sound\n")
    for name,_,_,_ in ratios:
        blocks.append(f"#print axioms RankMoments.{name}\n")
    return "\n".join(blocks)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check",action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().with_name("RankMoments.lean")
    output = generate()
    if args.check:
        if path.read_text() != output:
            raise ValueError("generated source bindings differ")
    else:
        path.write_text(output)
