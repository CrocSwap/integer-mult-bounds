"""Read-only exact corroboration; --write writes a source-bound receipt once."""
import argparse
import hashlib
import itertools
import json
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parent
sys.path.insert(0, str(PACKAGE))
from library import compile_library, feasible, recover_slacks


def need(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def fixture() -> dict:
    bases = (2,)
    levels = ((3, ((0, 1),)), (5, ((0, 2), (1, 4))),
              (2, ((1, 3), (2, 5))))
    least = compile_library(bases, levels, (1, 1, 1))
    enlarged = compile_library(bases, levels, (2, 3, 2))
    need(least == (2, 6, 15, 12), "first working fixture")
    need(enlarged == (2, 12, 45, 144), "enlarged fixture")
    need(feasible(bases, levels, least), "least fixture feasible")
    need(feasible(bases, levels, enlarged), "enlarged fixture feasible")
    return {"bases": bases, "levels": levels, "least": least, "enlarged": enlarged}


def exhaustive_libraries() -> dict:
    """Enumerate widths directly, so candidates are not generated by the theorem."""
    systems = libraries = admitted = normalizations = 0
    for base, s1, s2, q1, q2, q3 in itertools.product(range(1, 4), repeat=6):
        bases = (base,)
        levels = ((s1, ((0, q1),)), (s2, ((0, q2), (1, q3))))
        least = compile_library(bases, levels, (1, 1))
        systems += 1
        for a, b in itertools.product(range(1, 37), repeat=2):
            widths = (base, a, b)
            libraries += 1
            if not feasible(bases, levels, widths):
                continue
            admitted += 1
            need(all(big % small == 0 for small, big in zip(least, widths)),
                 "global divisibility")
            slacks = recover_slacks(bases, levels, widths)
            need(compile_library(bases, levels, slacks) == widths, "slack bijection")
            # Normalize one rank, retaining all later widths exactly.
            current = list(widths)
            for rank in range(1, 3):
                current[rank] = least[rank]
                need(feasible(bases, levels, tuple(current)), "normalization remains feasible")
                normalizations += 1
    return {"systems": systems, "candidate_libraries": libraries,
            "feasible_libraries": admitted, "normalization_steps": normalizations}


def larger_libraries() -> dict:
    """Deterministic finite families with repeated edges, empty cuts and nonunit bases."""
    systems = libraries = coordinates = 0
    for seed in range(1, 129):
        bases = (1 + seed % 7, 1 + (seed * 3) % 11)
        levels = []
        for rank in range(2, 12):
            batches = tuple(((seed + j * 7) % rank, 1 + (seed * j + rank) % 13)
                            for j in range(seed % 6))
            levels.append((1 + (seed + rank * 5) % 17, batches))
        levels = tuple(levels)
        least = compile_library(bases, levels, (1,) * len(levels))
        systems += 1
        for trial in range(1, 17):
            slacks = tuple(1 + (seed * trial + j * 3) % 7 for j in range(len(levels)))
            widths = compile_library(bases, levels, slacks)
            need(feasible(bases, levels, widths), "generated library literal feasibility")
            need(recover_slacks(bases, levels, widths) == slacks, "slack inversion")
            need(all(big % small == 0 for small, big in zip(least, widths)),
                 "larger global divisibility")
            libraries += 1
            coordinates += len(widths)
    return {"systems": systems, "libraries": libraries, "coordinates": coordinates}


def expect_rejected(bases: tuple, levels: tuple, slacks: tuple, message: str) -> None:
    try:
        compile_library(bases, levels, slacks)
    except ValueError as error:
        need(str(error) == message, "wrong rejection cause")
    else:
        raise AssertionError("invalid system accepted")


def controls() -> dict:
    bases, levels = (1,), ((2, ()), (1, ((1, 1),)))
    least = compile_library(bases, levels, (1, 1))
    need(least == (1, 2, 2), "small control fixture")
    need(not feasible(bases, levels, (1, 6, 2)), "mere coordinate multiples fail")
    need(feasible(bases, levels, (1, 6, 6)), "propagated enlargement works")
    # Removing the source-count divisibility would accept this width.
    need(not feasible((1,), ((3, ()),), (1, 2)), "source multiple is mandatory")
    # Aggregating two separate unit cuts loses their individual constraint.
    cuts = ((1, ((0, 1), (0, 1))),)
    pooled = ((1, ((0, 2),)),)
    need(compile_library((2,), cuts, (1,)) == (2, 2), "separate cuts")
    need(compile_library((2,), pooled, (1,)) == (2, 1), "pooling changes the system")
    # Gcd savings cannot be deleted; conversely a product is not an LCM.
    need(compile_library((6,), ((1, ((0, 3),)),), (1,)) == (6, 2), "gcd cancellation")
    need(compile_library((2, 4), ((1, ((0, 1), (1, 1))),), (1,)) == (2, 4, 4),
         "LCM is not product")
    invalid = [
        ((), (), (), "bases must be a nonempty bounded tuple"),
        ((True,), (), (), "base widths must be bounded positive integers"),
        ((0,), (), (), "base widths must be bounded positive integers"),
        ((65536,), (), (), "base widths must be bounded positive integers"),
        ((1,), ((0, ()),), (1,), "source count must be a bounded positive integer"),
        ((1,), ((1, ((1, 1),)),), (1,), "child rank must strictly descend"),
        ((1,), ((1, ((-1, 1),)),), (1,), "child rank must strictly descend"),
        ((1,), ((1, ((0, 0),)),), (1,), "batch count must be a bounded positive integer"),
        ((1,), ((1, ()),), (), "one slack is required per nonbase rank"),
        ((1,), ((1, ()),), (0,), "slacks must be bounded positive integers"),
        ((1,), ((1, ()),) * 32, (1,) * 32, "too many levels or wrong container"),
        ((1,), ((1, ((0, 1),) * 33),), (1,), "batches must be a bounded tuple"),
    ]
    for b, rows, slacks, message in invalid:
        expect_rejected(b, rows, slacks, message)
    need(compile_library((3, 5), (), ()) == (3, 5), "base-only library")
    # Largest accepted rank and scalar limits exercise the memory bound.
    big = tuple((65535, ((rank - 1, 1),)) for rank in range(1, 32))
    widths = compile_library((65535,), big, (65535,) * 31)
    need(feasible((65535,), big, widths), "capacity boundary")
    need(widths[-1].bit_length() == 1008, "growing integer capacity")
    full = ((1, ((0, 1),) * 32),)
    need(compile_library((2,), full, (1,)) == (2, 2), "maximum batch count")
    # Literal feasibility is intentionally broader than the constructor's slack domain.
    need(feasible((1,), ((1, ()),), (1, 65536)), "larger feasible slack")
    need(recover_slacks((1,), ((1, ()),), (1, 65536)) == (65536,), "larger slack recovery")
    expect_rejected((1,), ((1, ()),), (65536,),
                    "slacks must be bounded positive integers")
    return {"semantic_controls": 8, "invalid_inputs": len(invalid) + 1,
            "capacity_controls": 3, "maximum_width_bits": widths[-1].bit_length()}


def rebuild() -> dict:
    sources = {name: hashlib.sha256((PACKAGE / name).read_bytes()).hexdigest()
               for name in ("library.py", "verify.py", "README.md", "TASK.json", "SOURCES.json", "VERIFY.json")}
    return {"schema": "global-batch-library-minimum/v1", "claim_type": "scoped proof",
            "source_sha256": sources, "fixture": fixture(), "exhaustive": exhaustive_libraries(),
            "larger": larger_libraries(), "controls": controls()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", type=Path, help="new receipt path; existing files are never overwritten")
    args = parser.parse_args()
    result = rebuild()
    serialized = json.dumps(result, sort_keys=True, indent=2) + "\n"
    if args.write:
        with args.write.open("x", encoding="utf-8") as stream:
            stream.write(serialized)
    else:
        need(serialized == (PACKAGE / "RESULT.json").read_text(), "source-bound receipt mismatch")
    print("PASS_GLOBAL_BATCH_LIBRARY_MINIMUM", json.dumps(result["exhaustive"], sort_keys=True))
    print(json.dumps({"larger": result["larger"], "controls": result["controls"]}, sort_keys=True))


if __name__ == "__main__":
    main()
