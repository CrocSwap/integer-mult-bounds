# Step 5 of verify.sh: turns every CHECKED assertion of the README into a PASS/FAIL line.   usage: python check_logs.py LOGDIR
import ast, os, re, sys
L = sys.argv[1]
def rd(n):
    p = os.path.join(L, n)
    return open(p).read() if os.path.isfile(p) else ''
bad = 0
def chk(name, cond, detail=''):
    global bad
    print(('PASS ' if cond else 'FAIL ') + name + (('  [' + detail + ']') if detail else ''))
    bad += (not cond)
# data regeneration and E8 data facts
g = rd('gen.log')
chk('data.txt and gens.txt regenerated byte-identical to data/', 'IDENTICAL' in rd('gen_cmp.log'))
chk('gen: group on lines has order 172032, generators linear on labels', 'group order on lines 172032' in g and 'gens ok, linear on labels' in g)
chk('gen: 3888 directions with |Off|<=77 and 1120 A2 planes (896 at generic |Off| 78, 224 at 80)', 'wrote 3888 finite 0 pencils' in g and '((36, 78), 896), ((36, 80), 224)' in g)
chk('gen: Aut(Hamming [8,4,4]) of order 1344', 'Aut(Hamming) order 1344' in g)
# Parity Lemma (ii): no quadruple
q = rd('quad.log'); chk('Parity Lemma (ii), rank-4 quadruples: 0 pairwise non-orthogonal quadruples with label sum 0', 'quadruples (pairwise nonorth, label sum 0, rank 4): 0' in q)
# s66.c
for name, mode, dim, rk, nd, r8 in (('s66_m0', 0, 6, 3, 6, 0), ('s66_m1', 1, 6, 3, 6, 0)):
    o, e = rd(name + '.out'), rd(name + '.err')
    chk('%s: Lemma S66%s, all 159 orbit reps: max real rank %d, <= %d directions, 0 rank-8 pairs' % (name, '' if mode == 0 else '+t', rk, nd),
        ('OVERALL mode %d dim %d: max real rank %d, max #directions %d, rank-8 pairs %d' % (mode, dim, rk, nd, r8)) in o
        and len(re.findall(r'^rep \d+ lines', o, re.M)) == 159 and 'orbits: 159' in e and 'distinct line sets: 776805' in e)
o, e = rd('s66_ctl.out'), rd('s66_ctl.err')
chk('control: two 7-dim flats reach real rank 8 (152 pairs): the test is not vacuous', 'OVERALL mode 0 dim 7: max real rank 8' in o and 'rank-8 pairs 152' in o)
# indep.py, chunked
for mode in (0, 1):
    got, ok = [], True; mr = 0; mn = 0; chunks = set()
    for c in range(6):
        t = rd('indep_m%d_c%d.out' % (mode, c))
        m = re.search(r'DONE REPS (\[.*?\])', t); s = re.search(r'INDEP OVERALL mode (\d) chunk (\d) (\d) : max real rank (\d+) max #directions (\d+)', t)
        if not m or not s or int(s.group(1)) != mode or int(s.group(2)) != c or int(s.group(3)) != 6 or 'orbits 159' not in t or 'distinct nonempty line sets 776805' not in t or 'directions with |Off|<=76: 1200' not in t:
            ok = False; continue
        reps = ast.literal_eval(m.group(1)); ok &= reps == list(range(c, 159, 6)); got += reps
        mr = max(mr, int(s.group(4))); mn = max(mn, int(s.group(5))); chunks.add(c)
    chk('indep.py mode %d (%s): 6 chunks, all 159 orbit reps covered exactly once' % (mode, 'S66' if mode == 0 else 'S66+t'), ok and sorted(got) == list(range(159)) and len(chunks) == 6, 'covered %d' % len(set(got)))
    chk('indep.py mode %d: max real rank 3, <= 6 directions (agrees with s66.c)' % mode, ok and mr == 3 and mn == 6, 'rank %d, #dirs %d' % (mr, mn))
print('check_logs: %d failing' % bad); sys.exit(1 if bad else 0)
