# impl B (numpy): E8 from Cartan matrix (coefficient vectors), own labels, dedupe masks, vectorised pair OR; orbits under Stab(h) via reflections
import numpy as np, sys, itertools
K=int(sys.argv[1]); typ=sys.argv[2]
# Bourbaki E8 Cartan: chain 1-3-4-5-6-7-8, 2-4
edges=[(1,3),(3,4),(4,5),(5,6),(6,7),(7,8),(2,4)]
C=2*np.eye(8,dtype=int)
for a,b in edges: C[a-1,b-1]=C[b-1,a-1]=-1
def refl(x,i):
    y=x.copy(); y[i]-= int(x@C[:,i]); return y
roots={tuple(np.eye(8,dtype=int)[i]) for i in range(8)}
fr=list(roots)
while fr:
    nf=[]
    for r in fr:
        for i in range(8):
            y=tuple(refl(np.array(r),i))
            if y not in roots: roots.add(y); nf.append(y)
    fr=nf
roots=sorted(roots); assert len(roots)==240
RA=np.array(roots)
lines=[]; seen=set()
for r in roots:
    if tuple(-np.array(r)) in seen: continue
    seen.add(r); lines.append(np.array(r))
LA=np.array(lines); assert len(LA)==120
G=LA@C@LA.T   # inner products between lines
lab=np.array([1+sum(int(LA[t][k]%2)<<(k+1) for k in range(8)) for t in range(120)])
if typ=='root': hv=LA[0]
else:
    s=[t for t in range(120) if G[0,t]==0][0]; hv=LA[0]+LA[s]
ipH=LA@C@hv
assert (hv@C@hv)==(2 if typ=='root' else 4)
T=np.array([t for t in range(120) if ipH[t]!=0]); nz=len(T)
print('|Off|',nz, '|orth lines|',120-nz)
bit=lambda a: np.array([(bin(a&int(l)).count('1')&1)==0 for l in lab])
Zs=np.array([bit(a) for a in range(1,512)])[:,T]   # 511 x nz bool
idx=[(a,b) for a in range(511) for b in range(a+1,511)]
Mk=np.unique(np.packbits(np.array([Zs[a]&Zs[b] for a,b in idx]),axis=1),axis=0)
M=np.unpackbits(Mk,axis=1)[:,:nz].astype(bool)
print('masks',len(M))
pcs=M.sum(1); order=np.argsort(-pcs); M=M[order]; pcs=pcs[order]
need=nz-K
res=set()
Mu=np.packbits(M,axis=1)
def popc(x): return np.unpackbits(x,axis=1).sum(1)
for i in range(len(M)):
    if pcs[i]*2<need: break
    # j>=i with pcs[j]>=need-pcs[i]
    lo=i; hi=np.searchsorted(-pcs,-(need-pcs[i]),side='right')
    if hi<=lo: continue
    U=Mu[lo:hi]|Mu[i]
    c=popc(U)
    ok=np.nonzero(c>=need)[0]
    for o in ok:
        u=np.unpackbits(U[o])[:nz].astype(bool)
        if typ=='root' and not u[list(T).index(0)] and False: pass
        res.add(tuple(T[~u]))
# root covered: line 0 is the root itself (in Off? yes, ip=2); covered means not in leftover
if typ=='root': res={s for s in res if 0 not in s}
res=sorted(res,key=len); sets=[frozenset(s) for s in res]
mins=[]
bysize={}
for s in sets:
    if not any(m<=s for m in mins): mins.append(s)
from collections import Counter
print('minimal leftovers',Counter(len(s) for s in mins))
# label rank (F2^9)
def rk(vs):
    b=[]
    for x in vs:
        for y in b: x=min(x,x^y)
        if x: b.append(x)
    return len(b)
print('size,rank,#roots-in-leftover-types', sorted(Counter((len(s),rk([int(lab[t]) for t in s])) for s in mins).items()))
# orbits under stabilizer generated by reflections in lines orthogonal (and h itself if root)
def perm(v):  # reflection in line v (coefficient vector)
    out=[]
    for t in range(120):
        x=LA[t]-int(LA[t]@C@v)*v   # roots norm 2, s_v(x)=x-(x,v)v
        k=tuple(x) ; kk=tuple(-x)
        out.append(None)
    return out
pos={tuple(LA[t]):(t,1) for t in range(120)}; pos.update({tuple(-LA[t]):(t,-1) for t in range(120)})
gens=[]
for v in range(120):
    if G[v,0]==0 if typ=='root' else ipH[v]==0 or (typ=='root' and v==0):
        pass
gl=[v for v in range(120) if (ipH[v]==0) or (typ=='root' and v==0)]
for v in gl:
    gens.append([pos[tuple(LA[t]-int(LA[t]@C@LA[v])*LA[v])][0] for t in range(120)])
seen=set(); orbs=Counter(); orbsize={}
for s in mins:
    if s in seen: continue
    orb={s}; fr=[s]
    while fr:
        nf=[]
        for x in fr:
            for g in gens:
                y=frozenset(g[t] for t in x)
                if y not in orb: orb.add(y); nf.append(y)
        fr=nf
    seen|=orb; orbs[len(s)]+=1; orbsize[(len(s),len(orb))]=orbsize.get((len(s),len(orb)),0)+1
print('orbits under Stab(h) by size',dict(orbs)); print('orbit (size,|orbit|):count',orbsize)
import pickle; pickle.dump([sorted(int(t) for t in s) for s in mins],open('B_%s%d.pkl'%(typ,K),'wb'))
