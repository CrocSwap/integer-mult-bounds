#!/usr/bin/env python3
"""Checks of the p104-certkit-pricekit-to-lean package (standard library only; Lean is NOT run here).

Static: file pins (MANIFEST.sha256, both directions); REGEN.json = the closure modules not stored here; no
sorry/admit/native_decide/axiom/opaque/unsafe/implemented_by/extern/ofReduceBool outside comments and strings;
build-order.txt is a topological order of the Nov15 import graph (regenerated modules through their pinned imports)
and equals the import closure of All.lean; every Check.lean name is declared; the two headline statements have no
hypotheses and conclude `lo ≤ kword ∧ kword ≤ hi`; CHECK-axioms.txt lists exactly the Check.lean names, each within
{propext, Classical.choice, Quot.sound}; toolchain and Mathlib pins; no local paths.
Python side (the PRICEKIT -> Lean step, both words): PRICEKIT prices data/<word>.json.gz under data/7113_CALLER.json,
the bracket [lo, hi] is re-chosen to 10 significant digits, the piece certificate is re-checked exactly in Python, and the
emitted Cert<N>Tab/Part*/Num and Cert<N> link modules are regenerated BYTE-IDENTICAL to the shipped Lean files; the
caller modules CertCaller7113Data/Facts are regenerated from the caller file (identical up to the source-path line).
The kernel check itself is verify.sh (tools/regen.py + lean/check.sh; needs Lean and the pinned Mathlib).

DreamingOfClouds with Claude Opus 5.5 (Anthropic), via Claude Code. Apache-2.0.
"""
import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

sys.dont_write_bytecode = True
PKG = Path(__file__).resolve().parent
LEAN = PKG / "lean"
NOV = LEAN / "Nov15"
STD = {"propext", "Classical.choice", "Quot.sound"}
MATHLIB_REV = "55b7917b472489c7c56a0fa6393af05cfd536599"
TOOLCHAIN = "leanprover/lean4:v4.33.0-rc1"
FORBIDDEN = ["sorry", "admit", "native_decide", "axiom", "opaque", "unsafe", "implemented_by", "extern",
             "ofReduceBool"]
WORDS = [  # (name, word file, chain tag, slot)
    ("T7669", "t7669.json.gz", "7669"),
    ("Ws4", "w_s4.json.gz", "Ws4"),
]
IMP = re.compile(r"^\s*import\s+Nov15\.(\S+)", re.M)


def fail(msg):
    print("FAIL: " + msg)
    sys.exit(1)


def strip_lean(src):
    """Remove (nested) block comments, line comments and string literals."""
    out, i, n, depth = [], 0, len(src), 0
    while i < n:
        if src.startswith("/-", i):
            depth += 1; i += 2; continue
        if depth:
            if src.startswith("-/", i):
                depth -= 1; i += 2
            else:
                i += 1
            continue
        if src.startswith("--", i):
            j = src.find("\n", i); i = n if j < 0 else j; continue
        if src[i] == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append('""'); i = j + 1; continue
        out.append(src[i]); i += 1
    if depth:
        fail("unterminated block comment")
    return "".join(out)


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def check_manifest(regen):
    rows = {}
    for line in (PKG / "MANIFEST.sha256").read_text(encoding="utf-8").splitlines():
        digest, name = line.split("  ", 1)
        rows[name] = digest
    skip = {"lean/Nov15/%s.lean" % m for m in regen}
    present = set()
    for p in PKG.rglob("*"):
        rel = p.relative_to(PKG).as_posix()
        if (not p.is_file() or ".lake" in p.parts or "logs" in p.parts or "__pycache__" in p.parts
                or rel in skip or rel in ("MANIFEST.sha256", "lean/logs-Check.txt")):
            continue
        present.add(rel)
    if set(rows) != present:
        fail("MANIFEST.sha256 file set differs: missing %s, extra %s"
             % (sorted(present - set(rows))[:5], sorted(set(rows) - present)[:5]))
    for name, digest in rows.items():
        if sha(PKG / name) != digest:
            fail("sha256 mismatch: " + name)
    return len(rows)


def check_lean(regen):
    order = (LEAN / "build-order.txt").read_text(encoding="utf-8").split()
    shipped = sorted(p.stem for p in NOV.glob("*.lean") if p.stem not in regen)
    if len(set(order)) != len(order) or sorted(set(order) - set(regen)) != shipped:
        fail("lean/Nov15 (shipped) + REGEN.json differ from build-order.txt")
    if not set(regen) <= set(order):
        fail("REGEN.json lists modules outside build-order.txt")
    imports, decls, seen = {}, set(), set()
    for m in order:
        if m in regen:
            imports[m] = regen[m]["imports"]
            p = NOV / (m + ".lean")
            if p.exists() and sha(p) != regen[m]["sha256"]:
                fail("regenerated module differs from its pin: " + m)
        else:
            code = strip_lean((NOV / (m + ".lean")).read_text(encoding="utf-8"))
            imports[m] = IMP.findall(code)
            for tok in FORBIDDEN:
                if re.search(r"(?<![\w.'])" + re.escape(tok) + r"(?![\w'])", code):
                    fail("forbidden token %r outside comments in %s" % (tok, m))
            ns = re.findall(r"^namespace\s+(\S+)", code, re.M)
            for name in re.findall(r"(?:theorem|lemma|def|abbrev|structure|inductive|instance)\s+([^\s(:{\[]+)", code):
                decls.add(name); decls.update(n + "." + name for n in ns)
        for d in imports[m]:
            if d not in seen:
                fail("build-order.txt is not topological: %s imports %s" % (m, d))
        seen.add(m)
    for f in ("All.lean", "Check.lean"):
        code = strip_lean((LEAN / f).read_text(encoding="utf-8"))
        for tok in FORBIDDEN:
            if re.search(r"(?<![\w.'])" + re.escape(tok) + r"(?![\w'])", code):
                fail("forbidden token %r in %s" % (tok, f))
    closure, stack = set(), IMP.findall((LEAN / "All.lean").read_text(encoding="utf-8"))
    while stack:
        m = stack.pop()
        if m in closure:
            continue
        if m not in imports:
            fail("All.lean closure needs missing module " + m)
        closure.add(m); stack.extend(imports[m])
    if closure != set(order):
        fail("build-order.txt != import closure of All.lean (extra %s)" % sorted(set(order) - closure)[:5])
    names = re.findall(r"^#print axioms (\S+)", (LEAN / "Check.lean").read_text(encoding="utf-8"), re.M)
    for nm in names:
        if nm not in decls and nm.split(".")[-1] not in decls:
            fail("Check.lean name not declared: " + nm)
    got = {}
    for line in (PKG / "CHECK-axioms.txt").read_text(encoding="utf-8").splitlines():
        m1 = re.match(r"^'(\S+)' depends on axioms: \[(.*)\]$", line)
        m2 = re.match(r"^'(\S+)' does not depend on any axioms$", line)
        if m1:
            got[m1.group(1)] = {x.strip() for x in m1.group(2).split(",")}
        elif m2:
            got[m2.group(1)] = set()
        else:
            fail("unparsed CHECK-axioms.txt line: " + line)
    if sorted(got) != sorted(names):
        fail("CHECK-axioms.txt names differ from Check.lean")
    for nm, ax in got.items():
        if not ax <= STD:
            fail("non-standard axioms for %s: %s" % (nm, sorted(ax - STD)))
    # headline signatures: no binders, conclusion contains the bracket
    for mod, tr, rows in (("CertT7669Rows", "tr7669", "Rows7669"), ("CertWs4Rows", "trWs4", "RowsWs4")):
        code = strip_lean((NOV / (mod + ".lean")).read_text(encoding="utf-8"))
        mm = re.search(r"theorem certified\s*:(.*?):=", code, re.S)
        if not mm:
            fail("no headline in " + mod)
        stmt = " ".join(mm.group(1).split())
        want = "Legal (pub caller7113) %s ∧ %s ∧ Word caller7113 (exec %s) ∧ lo ≤ kword ∧ kword ≤ hi" % (tr, rows, tr)
        if not stmt.startswith(want):
            fail("headline statement changed in %s: %s" % (mod, stmt[:200]))
    tc = (LEAN / "lean-toolchain").read_text(encoding="utf-8").strip()
    if tc != TOOLCHAIN or MATHLIB_REV not in (LEAN / "lakefile.toml").read_text(encoding="utf-8") \
            or MATHLIB_REV not in (LEAN / "lake-manifest.json").read_text(encoding="utf-8"):
        fail("toolchain / Mathlib pin")
    return len(order), len(names)


def check_python():
    sys.path.insert(0, str(PKG / "tools"))
    import certkit as ck
    import certnum as cn
    from fractions import Fraction as Q
    caller = str(PKG / "data" / "7113_CALLER.json")
    out = []
    for name, wf, chain in WORDS:
        W, Nn, cs, klo, khi, Pp = ck.price(str(PKG / "data" / wf), caller)
        lo, hi = ck.choose_bracket(klo, khi, 10)
        if not (lo < klo <= khi < hi):
            fail("bracket does not contain PRICEKIT kappa for " + name)
        C = cn.Cert(cs)
        gup = cn.up_pieces(C, hi); glo = cn.lo_pieces(C, lo)
        if not (all(C.lbP(x, y) > 0 and x < y for x, y in zip(glo, glo[1:]))
                and all(C.ubP(x, y) < 0 and x < y for x, y in zip(gup, gup[1:])) and C.tailP(gup[-1]) < 0):
            fail("Python piece certificate for " + name)
        files = ck.emit_num(name, cs, C, lo, hi, glo, gup, (klo, khi), 10, 8, 3)
        tabs = NOV / ("UniInhabitTabs.lean" if chain == "7669" else "UniInhabit%sTabs.lean" % chain)
        if tabs.exists():
            ckl = int(re.search(r"def NSEG : Nat := (\d+)", tabs.read_text(encoding="utf-8")).group(1))
        else:
            ckl = 26   # both chains have 26 checkpointed segments (pinned in REGEN.json)
        files["Cert" + name] = ck.emit_link(name, chain, 10, ckl)
        for m, txt in files.items():
            if (NOV / (m + ".lean")).read_text(encoding="utf-8") != txt:
                fail("emitted module differs from the shipped file: " + m)
        out.append("%s kappa=%.15f lo=%s hi=%s (%d modules byte-identical)" % (name, float(klo), lo, hi, len(files)))
    import callerfacts as cf
    with tempfile.TemporaryDirectory() as td:
        os.mkdir(os.path.join(td, "Nov15"))
        cf.LEAN = td
        argv = sys.argv
        sys.argv = ["callerfacts.py", caller, "--name", "7113", "--bind7113"]
        try:
            import contextlib, io
            with contextlib.redirect_stdout(io.StringIO()):
                cf.main()
        finally:
            sys.argv = argv
        for m in ("CertCaller7113Data", "CertCaller7113Facts"):
            a = Path(td, "Nov15", m + ".lean").read_text(encoding="utf-8").split("\n")
            b = (NOV / (m + ".lean")).read_text(encoding="utf-8").split("\n")
            if m.endswith("Data"):
                a, b = a[1:], b[1:]   # line 1 names the caller file's path in the authors' tree
            if a != b:
                fail("caller module differs: " + m)
    out.append("caller 7113: CertCaller7113Data/Facts regenerated")
    return out


def main():
    regen = json.loads((PKG / "REGEN.json").read_text(encoding="utf-8"))["modules"]
    nfiles = check_manifest(regen)
    nmod, nnames = check_lean(regen)
    for p in PKG.rglob("*"):
        if p.is_file() and p.suffix in (".py", ".md", ".json", ".sh", ".lean", ".txt", ".toml", ".tpl") \
                and ".lake" not in p.parts:
            t = p.read_text(encoding="utf-8", errors="replace")
            if re.search(r"/(?:Users|home)/|claude[.]ai/code", t):
                fail("local path in " + p.relative_to(PKG).as_posix())
    lines = check_python()
    for ln in lines:
        print(ln)
    print("PASS_CERTKIT_PACKAGE %d pinned files, %d modules (%d regenerated), %d headline names"
          % (nfiles, nmod, len(regen), nnames))


if __name__ == "__main__":
    main()
