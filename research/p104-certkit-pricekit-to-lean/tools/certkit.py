def qlit(q):
    q = Q(q)
    if q.denominator == 1:
        return f'({q.numerator} : ℚ)'
    return f'({q.numerator} / {q.denominator} : ℚ)'


def qr(q):
    return f'(({qlit(q)} : ℚ) : ℝ)'


def sig_prefix(x, d):
    with localcontext() as c:
        c.prec = 200
        s = format(Decimal(x.numerator) / Decimal(x.denominator), '.120e')
        mant = s.split('e')[0].replace('.', '').lstrip('-')
        return mant[:d], s.split('e')[1]


def choose_bracket(klo, khi, digits):
    """lo < klo ≤ khi < hi, both sharing the first `digits` significant digits with κ (truncation)."""
    k = (klo + khi) / 2
    e = 0
    while k * 10 ** e < Q(1, 10):
        e += 1
    for extra in range(2, 30):
        den = 10 ** (e + digits + extra)
        lo = Q((klo * den).__floor__(), den)
        if lo == klo:
            lo -= Q(1, den)
        hi = Q(-((-khi * den).__floor__()), den)
        if hi == khi:
            hi += Q(1, den)
        if sig_prefix(lo, digits) == sig_prefix(k, digits) == sig_prefix(hi, digits):
            return lo, hi
    raise RuntimeError('could not choose a bracket')


def price(word, caller):
    W = pk.load(word)
    N = pk.native_from_word(W)
    R = pk.run(caller, N, digits=60)
    inv = R['invoice']
    ranks = sorted(set(inv['T']) | set(inv['P']))
    cs = [(int(inv['T'].get(r, 0) - inv['P'].get(r, 0)), r) for r in ranks]
    cs = [(c, r) for c, r in cs if c != 0]
    assert all(r >= 1 for c, r in cs), 'rank-0 invoice entries are not supported'
    kp = R['price']['kappa']
    assert kp['status'] == 'OK' and kp['unique'], kp
    return W, N, cs, Q(kp['lo']), Q(kp['hi']), R['price']


def chunks(g, size):
    """split grid g0..gm into consecutive chunks sharing endpoints."""
    out = []; i = 0
    while i < len(g) - 1:
        j = min(i + size, len(g) - 1)
        out.append(g[i:j + 1]); i = j
    return out


def emit_num(name, cs, C, lo, hi, glo, gup, kp, digits, chunk, per_file=3):
    """returns {module: text}: Cert<N>Tab (invoice, log table, lo/hi), Cert<N>Part<k> (piece chunks, ≤ per_file decides
    each: the kernel's per-file memory grows with every decide), Cert<N>Num (joins + bracket)."""
    tb = C.tb; files = {}; ns = 'Cert' + name
    hdr = lambda what: (f'/- {ns}{what} (GENERATED by toolkit/certkit/certkit.py, lane CERTKIT; word {name}).  Kernel only: '
                        'no sorry, no native_decide, no new axioms. -/\n')
    T = [hdr('Tab') + 'import Nov15.CertKitCore\n\nnamespace ' + ns + '\nopen CertKit\n']
    T.append('/-- the invoice: (T_r - P_r, r), PRICEKIT. -/')
    T.append('def cs : List (ℤ × ℕ) := [' + ', '.join(f'({c}, {r})' for c, r in cs) + ']\n')
    T.append('/-- certified log table: entry k bounds log (k+1). -/')
    T.append('def tbRest : List (ℚ × ℚ × ℕ) := [' + ',\n  '.join(f'({qlit(x)}, {qlit(y)}, {n})' for x, y, n in tb[1:]) + ']')
    T.append(f'def tb : List (ℚ × ℚ × ℕ) := (0, 0, {tb[0][2]}) :: tbRest\n')
    T.append(f'theorem tb_ok : LogTab tb := logsOK_sound0 {tb[0][2]} tbRest (by decide +kernel)')
    T.append('theorem cs_ok : csOK tb cs = true := by decide +kernel\n')
    T.append(f'/-- the lower end: lo = {lo}. -/\nnoncomputable def lo : ℝ := {qr(lo)}')
    T.append(f'/-- the upper end: hi = {hi}. -/\nnoncomputable def hi : ℝ := {qr(hi)}\n')
    T.append('theorem hi_lt_one : hi < 1 := by unfold hi; norm_num')
    T.append('theorem lo_pos : 0 < lo := by unfold lo; norm_num')
    T.append('theorem lo_lt_hi : lo < hi := by unfold lo hi; norm_num\n')
    T.append(f'end {ns}')
    files[ns + 'Tab'] = '\n'.join(T) + '\n'
    thms = []
    for i, ch in enumerate(chunks(glo, chunk)):
        a, b, mid = ch[0], ch[-1], ch[1:-1]
        thms.append(f'theorem pos_{i} : ∀ t : ℝ, {qr(a)} ≤ t → t ≤ {qr(b)} → 0 < F cs t :=\n'
                    f'  pos_chunk tb tb_ok cs cs_ok {qlit(a)} {qlit(b)} [' + ', '.join(qlit(x) for x in mid) +
                    '] (by norm_num) (by decide +kernel)')
    npos = len(thms)
    for i, ch in enumerate(chunks(gup, chunk)):
        a, b, mid = ch[0], ch[-1], ch[1:-1]
        thms.append(f'theorem neg_{i} : ∀ t : ℝ, {qr(a)} ≤ t → t ≤ {qr(b)} → F cs t < 0 :=\n'
                    f'  neg_chunk tb tb_ok cs cs_ok {qlit(a)} {qlit(b)} [' + ', '.join(qlit(x) for x in mid) +
                    '] (by norm_num) (by decide +kernel)')
    nneg = len(thms) - npos
    thms.append(f'theorem neg_tl : ∀ t : ℝ, {qr(gup[-1])} ≤ t → F cs t < 0 :=\n'
                f'  neg_tail tb tb_ok cs cs_ok {qlit(gup[-1])} (by norm_num) (by decide +kernel)')
    parts = []
    for k in range(0, len(thms), per_file):
        m = f'{ns}Part{k // per_file}'; parts.append(m)
        files[m] = (hdr(f'Part{k // per_file}') + f'import Nov15.{ns}Tab\n\nnamespace {ns}\nopen CertKit\n\n' +
                    '\n'.join(thms[k:k + per_file]) + f'\n\nend {ns}\n')
    pj = 'pos_0'
    for i in range(1, npos):
        pj = f'join ({pj}) pos_{i}'
    nj = 'neg_0'
    for i in range(1, nneg):
        nj = f'join ({nj}) neg_{i}'
    N = [f'/-\n{ns}Num (GENERATED by toolkit/certkit/certkit.py, lane CERTKIT).  PRICEKIT κ of word {name} = '
         f'{float(kp[0]):.20g}...;\ncertified here lo = {lo} < κ < hi = {hi} ({digits} significant digits).\n'
         f'Pieces: {len(glo) - 1} positive on [0, lo], {len(gup) - 1} negative on [hi, {float(gup[-1]):.4g}] + tail.  '
         'Kernel only: no sorry, no native_decide, no new axioms.\n-/']
    N += [f'import Nov15.{m}' for m in parts]
    N.append(f'\nnamespace {ns}\nopen CertKit\n')
    N.append('theorem pos_all : ∀ t : ℝ, 0 ≤ t → t ≤ lo → 0 < F cs t :=')
    N.append(f'  fun t h0 h1 => ({pj}) t (by simpa using h0) h1')
    N.append('theorem neg_all : ∀ t : ℝ, hi ≤ t → F cs t < 0 :=')
    N.append(f'  join_tail ({nj}) neg_tl\n')
    N.append("/-- **bracket**: PRICEKIT's κ (the last crossing of the invoice form F cs) lies in [lo, hi], F vanishes there,")
    N.append('and every root of F on [0, ∞) lies in (lo, hi). -/')
    N.append('theorem bracket : lo ≤ kroot cs ∧ kroot cs ≤ hi ∧ F cs (kroot cs) = 0 ∧')
    N.append('    ∀ t, 0 ≤ t → F cs t = 0 → lo < t ∧ t < hi :=')
    N.append('  kroot_bracket cs (csOK_ge tb cs cs_ok) lo hi lo_pos.le pos_all neg_all\n')
    N.append(f'end {ns}\n\n#print axioms {ns}.bracket')
    files[ns + 'Num'] = '\n'.join(N) + '\n'
    return files


