def wait_lean_idle():
    r = subprocess.run(['pgrep', '-x', 'lean'], capture_output=True, text=True)
    return r.stdout.strip() == ''


def build(mod):
    if not wait_lean_idle():
        print('lean is running; not building', mod); return None
    src = os.path.join('Nov15', mod + '.lean'); out = os.path.join('.lake', 'build', 'lib', 'lean', 'Nov15', mod + '.olean')
    r = subprocess.run([RUNLEAN, src, out], capture_output=True, text=True, cwd=LEAN)
    print(mod, r.stdout.strip().splitlines()[0] if r.stdout else r.stderr[-300:])
    return r.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('word'); ap.add_argument('--name', required=True)
    ap.add_argument('--caller', default=C7113); ap.add_argument('--digits', type=int, default=10)
    ap.add_argument('--chain', default=None); ap.add_argument('--chunk', type=int, default=8); ap.add_argument('--per-file', type=int, default=3)
    ap.add_argument('--build', action='store_true')
    ap.add_argument('--slot', type=int, default=128, help='trace slot width of the chain (96 for t7669, 128 for gen_chain words)')
    ap.add_argument('--cap', type=int, default=2500); ap.add_argument('--rows-w', type=int, default=0); ap.add_argument('--rows-kb', type=int, default=0)
    ap.add_argument('--rows-opens', default='UniFold7113'); ap.add_argument('--rows-asm', action='store_true', help='re-emit only the assembly (Defs..Main), keep Ck/Seg files'); ap.add_argument('--rows-d', type=int, default=0, help='row scale D (0 = gen_rowsp searches)')
    ap.add_argument('--rows', default=None, help='MODULE:THEOREM proving the chain Rows clause (lane ROWS); closes crossing_lo')
    a = ap.parse_args()
    t0 = time.time()
    W, N, cs, klo, khi, P = price(a.word, a.caller)
    lo, hi = choose_bracket(klo, khi, a.digits)
    print(f'PRICEKIT κ = {P["kappa"]["lo"]:.40f}\n  S = {P["S"]}  cs = {cs}')
    print(f'bracket lo = {lo} = {float(lo):.17g}\n        hi = {hi} = {float(hi):.17g}  (prefix {sig_prefix(lo, a.digits)[0]})')
    C = cn.Cert(cs)
    gup = cn.up_pieces(C, hi); glo = cn.lo_pieces(C, lo)
    # exact re-check of the whole certificate in Python (the kernel repeats it)
    assert all(C.lbP(x, y) > 0 and x < y for x, y in zip(glo, glo[1:]))
    assert all(C.ubP(x, y) < 0 and x < y for x, y in zip(gup, gup[1:])) and C.tailP(gup[-1]) < 0
    print(f'pieces: {len(glo) - 1} low, {len(gup) - 1} high, tail from {float(gup[-1]):.4g}; python {time.time() - t0:.1f}s')
    files = emit_num(a.name, cs, C, lo, hi, glo, gup, (klo, khi), a.digits, a.chunk, a.per_file)
    mods = []
    for m, txt in files.items():
        open(os.path.join(NOV, m + '.lean'), 'w').write(txt); mods.append(m)
    if a.chain:
        import re
        tabs = os.path.join(NOV, 'UniInhabitTabs.lean' if a.chain == '7669' else f'UniInhabit{a.chain}Tabs.lean')
        ckl = int(re.search(r'def NSEG : Nat := (\d+)', open(tabs).read()).group(1))
        txt = emit_link(a.name, a.chain, a.digits, ckl)
        if a.rows and ':' in a.rows:
            rm, rt = a.rows.split(':')
            txt = txt.replace(f'import Nov15.Cert{a.name}Num\n', f'import Nov15.Cert{a.name}Num\nimport Nov15.{rm}\n')
            txt += (f'\n/-- premise-free: the Rows clause discharged by {rt} (lane ROWS). -/\n'
                    f'theorem Cert{a.name}.crossing_lo_closed : UniUniversal.Crossing .w7113 Cert{a.name}.lo :=\n'
                    f'  Cert{a.name}.crossing_lo {rt}\n\n#print axioms Cert{a.name}.crossing_lo_closed\n')
        open(os.path.join(NOV, f'Cert{a.name}.lean'), 'w').write(txt)
        mods.append(f'Cert{a.name}')
    if a.chain and a.rows in ('gen', 'link'):
        rmods = rows_step(a, a.name, a.chain, ckl, a.digits)
        mods += rmods
    json.dump(dict(word=a.word, caller=a.caller, kappa_lo=str(P['kappa']['lo']), kappa_hi=str(P['kappa']['hi']),
                   lo=str(lo), hi=str(hi), cs=cs, pieces=[len(glo) - 1, len(gup) - 1], modules=mods),
              open(os.path.join(HERE, f'cert_{a.name}.json'), 'w'), indent=1)
    print('emitted', ', '.join('Nov15/' + m + '.lean' for m in mods))
    if a.build:
        import build as B
        t = time.time()
        if a.chain and a.chain != '7669' and not B.build(json.load(open(os.path.join(HERE, f'chain_{a.chain}.json')))['modules']):
            sys.exit(1)
        ok = B.build(mods)
        print(f'build wall {time.time() - t:.0f}s'); sys.exit(0 if ok else 1)

if __name__ == '__main__':
    main()
