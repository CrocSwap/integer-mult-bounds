#!/usr/bin/env python3
"""ROWS lane: make the generic row-certificate library for another UNI-INHABIT chain namespace.
UNI-INHABIT chains are namespace copies (UniInhabit = t7669 96-bit, UniInhabitWs4 = CERTKIT 128-bit, ...);
this copies UniRows{Defs,Meta,Sound,Tgt,Chain,PDefs,PMeta,PMath,PSound}.lean to UniRows<Sfx>*.lean with UniInhabit -> UniInhabit<Sfx>.
usage: mk_rows_ns.py Sfx      (run in Nov15/)"""
import sys
sfx = sys.argv[1]
for m in ['Defs', 'Meta', 'Sound', 'Tgt', 'Chain', 'PDefs', 'PMeta', 'PMath', 'PSound']:
    t = open('UniRows%s.lean' % m).read()
    t = t.replace('UniInhabit', 'UniInhabit' + sfx).replace('UniRows', 'UniRows' + sfx)
    t = t.replace('UniInhabit%sDefs' % sfx, 'UniInhabit%sDefs' % sfx)
    open('UniRows%s%s.lean' % (sfx, m), 'w').write('-- GENERATED by unigen/mk_rows_ns.py from UniRows%s.lean (namespace copy for UniInhabit%s).\n' % (m, sfx) + t)
print('ok')
