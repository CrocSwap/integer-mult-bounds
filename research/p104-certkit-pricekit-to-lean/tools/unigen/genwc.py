#!/usr/bin/env python3
"""UNI-L4 generator: fold a P104 word (bank.fold, COPY shim as um1/um3), emit Nov15/<Name>Data.lean with
packed base-16 height tables (banks: src/dst, fields: initial/final) and the descent chains (bank index, src chart, dst chart).
usage: genwc.py word.json.gz Name out.lean   (pure Python, 1 proc)"""
import sys, os
from collections import defaultdict
H = os.path.dirname(os.path.abspath(__file__))
G = os.path.join(H, '..')   # tools/ (bank.py, pricekit.py)
sys.path.insert(0, G)
import bank
p, name, outp = sys.argv[1:4]
W = bank.load(p); n = W['public']
prog = []
for e in W['program']:
    if e[0] == 'COPY': prog += [['SCALE', e[1], '0', e[-1]], ['ADD', e[1], e[2], e[3], e[-1]]]
    else: prog.append(e)
W['program'] = prog
dimB = [len(f) for f in W['frames']]
net = bank.fold(W); bank.schedule(net)
ks = sorted(net.moves)
idx = {k: i for i, k in enumerate(ks)}
hs = [dimB[net.moves[k][0]] for k in ks]; hd = [dimB[net.moves[k][1]] for k in ks]
fi = [dimB[W['initial'][r]] for r in range(n)]; ff = [dimB[W['final'][r]] for r in range(n)]
assert all(x < 16 for x in hs + hd + fi + ff)
def pack(l):
    v = 0
    for x in reversed(l): v = v * 16 + x
    return v
span = lambda b: frozenset(__import__('functools').reduce(lambda S, v: S | {x ^ v for x in S}, b, {0}))
fr = [span(f) for f in W['frames']]
dset = [k for k in ks if fr[net.moves[k][1]] < fr[net.moves[k][0]]]
assert all(hd[idx[k]] < hs[idx[k]] for k in dset) and len(dset) == sum(1 for i in range(len(ks)) if hs[i] > hd[i])
nxt = defaultdict(list); prv = defaultdict(list)
for k in dset:
    for j in dset:
        if j != k and net.moves[j][0] == net.moves[k][1] and k in net.forms[j]:
            nxt[k].append(j); prv[j].append(k)
heads = [k for k in dset if not prv[k]]
chains = []
for h in heads:
    c = [h]
    while len(nxt[c[-1]]) == 1: c.append(nxt[c[-1]][0])
    chains.append(c)
assert sum(len(c) for c in chains) == len(dset)
chains.sort(key=lambda c: -len(c))
D = sum(max(a - b, 0) for a, b in zip(hs, hd)); A = sum(max(b - a, 0) for a, b in zip(hs, hd))
cl = sum(b - a for a, b in zip(fi, ff))
print(name, 'banks', len(ks), 'fields', n, 'D', D, 'A', A, 'climb', cl, 'excess', D + A - cl, 'chains', [len(c) for c in chains])
NB = len(ks)
out = [f'/- {name}Data (lane UNI-L4, Nov 19). GENERATED by Nov15/unigen/genwc.py from the folded word (bank.fold, COPY shim):',
       'packed base-16 height tables (bank k: src/dst chart dimension; public field f: initial/final frame dimension) and the descent chains',
       '(trace-order bank index, src chart id, dst chart id), chart id = word frame index. DATA. -/', f'namespace {name}Data', '',
       f'def NB : Nat := {NB}', f'def NF : Nat := {n}', '',
       f'def HS : Nat := 0x{pack(hs):x}', f'def HD : Nat := 0x{pack(hd):x}', f'def FI : Nat := 0x{pack(fi):x}', f'def FF : Nat := 0x{pack(ff):x}', '',
       '/-- descent chains: each step (bank index, src chart id, dst chart id), in relay order. -/',
       'def chains : List (List (Nat × Nat × Nat)) := [' + ',\n  '.join('[' + ', '.join(f'({idx[k]},{net.moves[k][0]},{net.moves[k][1]})' for k in c) + ']' for c in chains) + ']', '',
       '/-- chain shapes: height of the first source, then the height after each step. -/',
       'def shapes : List (List Nat) := [' + ', '.join('[' + ', '.join(str(x) for x in [hs[idx[c[0]]]] + [hd[idx[k]] for k in c]) + ']' for c in chains) + ']', '',
       '/-- relay evidence from the fold (descent j reads descent k: token k in forms[j]) as (bank index j, bank index k); this is the L1 fact. -/',
       'def relays : List (Nat × Nat) := [' + ', '.join(f'({idx[j]},{idx[k]})' for c in chains for k, j in zip(c, c[1:])) + ']', '',
       f'end {name}Data']
open(outp, 'w').write('\n'.join(out) + '\n')
