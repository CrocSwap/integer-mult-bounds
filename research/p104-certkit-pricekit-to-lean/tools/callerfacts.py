#!/usr/bin/env python3
"""CK-CALLER caller-facts generator: caller file (schema mixed-root-caller/1) -> Lean kernel facts.

  callerfacts.py CALLER.json --name N [--bind7113] [--build]

writes Nov15/CertCaller<N>Data.lean (packed caller data, see CertCallerCore) and Nov15/CertCaller<N>Facts.lean:
  T<N>/P<N> (rank-sorted histograms computed HERE in Python, independently of Lean) and the kernel theorems
  tHist : hist (tRaw C) = T<N>,  pHist : hist (pRaw C) = P<N>,  calls_known : calls C = L ∧ known C = true
(3 decides).  --bind7113 additionally proves T<N> = SafeRungsPrice.Tcal and P<N> = Pcal (rfl), i.e. the CERTKIT
caller constant equals the caller-file derivation.  The encoding is round-trip checked before writing.
Standard library only.  Pricing rules: CertCallerCore header (repo verifier pricing.py + #7113 IDLE_ODD rule).
"""
import argparse, hashlib, json, os, subprocess, sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))   # package root (paths are package-relative)
LEAN = os.path.join(ROOT, 'lean')
RUNLEAN = os.path.join(LEAN, 'tools', 'runlean.sh')
OPS = {'ADD': 1, 'SCALE': 2, 'SWAP': 3, 'LAMBDA': 4, 'QUERY': 5, 'IDLE_ONE': 6, 'IDLE_ODD': 7}


def invoice(C):
    """reference caller invoice (pricekit / repo pricing.py rules) straight from the JSON."""
    tys = list(C['types']); cnt = {t: len(C['types'][t]['ports']) for t in tys}
    T, P, L = Counter(), Counter(), 0
    for e in C['events']:
        if e[0] == 'J': L += 1; continue
        if e[1] == 'QUERY': P[1] += cnt[e[0]]
        elif e[1] == 'IDLE_ONE': P[8 * len(e[3])] += cnt[e[0]]
        elif e[1] == 'IDLE_ODD': P[8 * len(e[3]) + 1] += cnt[e[0]]
        elif e[1] not in ('ADD', 'SCALE', 'SWAP', 'LAMBDA'): sys.exit('unknown caller op %r' % e[1])
    for t in tys:
        for exponent, zero, *mask in C['types'][t]['diagonal']:
            T[int(exponent % 2) + 8 * sum(mask)] += cnt[t]
    return T, P, L


def encode(C):
    tys = list(C['types']); assert len(tys) <= 4
    ev = 0
    for i, e in enumerate(C['events']):
        if e[0] == 'J':
            x = 0
        else:
            st = 0
            if e[1] in ('IDLE_ONE', 'IDLE_ODD'):
                s = e[3]; assert len(set(s)) == len(s) and all(0 <= k < 26 for k in s), ('stage set', i)
                for k in s: st |= 1 << k
            x = OPS[e[1]] + 16 * tys.index(e[0]) + 64 * st
        assert x < 2 ** 32
        ev |= x << (32 * i)
    types = []
    for t in tys:
        D = C['types'][t]['diagonal']; rows = 0
        for i, (exponent, zero, *mask) in enumerate(D):
            assert -2 ** 15 <= exponent < 2 ** 15 and len(mask) <= 40 and set(mask) <= {0, 1}, ('diag', t, i)
            m = sum(b << k for k, b in enumerate(mask))
            rows |= (exponent + 2 ** 15 + (m << 16)) << (64 * i)
        types.append((len(C['types'][t]['ports']), len(D), rows))
    return types, len(C['events']), ev


def decode_invoice(types, nev, ev):
    """the Lean definitions (CertCallerCore) re-implemented: must reproduce invoice()."""
    sl = lambda w, c, i: c >> (w * i) & ((1 << w) - 1)
    T, P, L = Counter(), Counter(), 0
    for i in range(nev):
        x = sl(32, ev, i); op, ty, st = x % 16, x // 16 % 4, x // 64
        pc = bin(st).count('1')
        if op == 0: L += 1
        elif op == 5: P[1] += types[ty][0]
        elif op == 6: P[8 * pc] += types[ty][0]
        elif op == 7: P[8 * pc + 1] += types[ty][0]
    for ports, nrow, rows in types:
        for i in range(nrow):
            x = sl(64, rows, i)
            T[((x % 2 ** 16) - 2 ** 15) % 2 + 8 * bin(x >> 16).count('1')] += ports
    return T, P, L


def lst(H):
    return '[' + ', '.join('(%d, %d)' % (r, H[r]) for r in sorted(H) if H[r]) + ']'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('caller'); ap.add_argument('--name', required=True)
    ap.add_argument('--bind7113', action='store_true'); ap.add_argument('--build', action='store_true')
    a = ap.parse_args()
    raw = open(a.caller, 'rb').read(); C = json.loads(raw); sha = hashlib.sha256(raw).hexdigest()
    assert C.get('schema', '').startswith('mixed-root-caller/'), C.get('schema')
    T, P, L = invoice(C)
    types, nev, ev = encode(C)
    assert decode_invoice(types, nev, ev) == (T, P, L), 'round trip'
    N = a.name; ns = 'CertCaller' + N
    data = ['/- GENERATED by toolkit/certkit/callerfacts.py (lane CK-CALLER) from %s' % os.path.relpath(a.caller, ROOT),
            '   sha256 %s, schema %s, %d events, types %s.  DATA. -/' % (sha, C['schema'], nev, list(C['types'])),
            'import Nov15.CertCallerCore', '', 'namespace %s.Data' % ns, 'open CertCaller', '']
    for k, (ports, nrow, rows) in enumerate(types):
        data.append('def rows%d : Nat := 0x%x' % (k, rows))
    data.append('def evs : Nat := 0x%x' % ev)
    data.append('def C : CData := ⟨[%s], %d, evs⟩' % (', '.join('⟨%d, %d, rows%d⟩' % (p, n, k) for k, (p, n, _) in enumerate(types)), nev))
    data += ['', 'end %s.Data' % ns, '']
    bind = ''
    if a.bind7113:
        bind = ('\n/-- the CERTKIT caller constants ARE the caller-file derivation. -/\n'
                'theorem Tcal_eq : SafeRungsPrice.Tcal = hist (tRaw Data.C) := by rw [tHist]; rfl\n'
                'theorem Pcal_eq : SafeRungsPrice.Pcal = hist (pRaw Data.C) := by rw [pHist]; rfl\n'
                'theorem L_eq : calls Data.C = 17 := calls_known.1\n')
    facts = ['/- GENERATED by toolkit/certkit/callerfacts.py (lane CK-CALLER).  Caller facts of %s (sha256 %s):' % (os.path.basename(a.caller), sha[:16]),
             '   the caller block T/P histograms and the call count, derived in the kernel from the caller data (3 decides).',
             '   cdat s T%s - cdat s P%s is the Theorem K caller invoice Dc(s); cdat_hist: = the raw per-event/per-row sums.  Kernel only. -/' % (N, N),
             'import Nov15.%sData' % ns, '', 'namespace %s' % ns, 'open CertCaller SafeRungsPrice', '',
             'attribute [local irreducible] Data.evs %s' % ' '.join('Data.rows%d' % k for k in range(len(types))), '',
             'def T%s : List (ℕ × ℕ) := %s' % (N, lst(T)), 'def P%s : List (ℕ × ℕ) := %s' % (N, lst(P)), '',
             'theorem tHist : hist (tRaw Data.C) = T%s := by decide +kernel' % N,
             'theorem pHist : hist (pRaw Data.C) = P%s := by decide +kernel' % N,
             'theorem calls_known : calls Data.C = %d ∧ known Data.C = true := by decide +kernel' % L, bind,
             '/-- Dc(s) of this caller from its data: targets minus paid, raw items. -/',
             'theorem dc_eq (s : ℝ) : cdat s T%s - cdat s P%s = cdat s (tRaw Data.C) - cdat s (pRaw Data.C) := by' % (N, N),
             '  rw [← tHist, ← pHist, cdat_hist, cdat_hist]', '', 'end %s' % ns, '']
    for k in ('tHist', 'pHist', 'calls_known', 'dc_eq') + (('Tcal_eq', 'Pcal_eq') if a.bind7113 else ()):
        facts.append('#print axioms %s.%s' % (ns, k))
    out = os.path.join(LEAN, 'Nov15')
    open(os.path.join(out, ns + 'Data.lean'), 'w').write('\n'.join(data))
    open(os.path.join(out, ns + 'Facts.lean'), 'w').write('\n'.join(facts) + '\n')
    print('caller %s: L=%d T=%s P=%s S_caller=%d' % (N, L, lst(T), lst(P), sum(r * v for r, v in T.items()) - sum(r * v for r, v in P.items())))
    if a.build:
        for m in ('CertCallerCore', ns + 'Data', ns + 'Facts'):
            subprocess.run(['bash', RUNLEAN, 'Nov15/%s.lean' % m, '.lake/build/lib/lean/Nov15/%s.olean' % m], cwd=LEAN, check=True)


if __name__ == '__main__':
    main()
