# Step 4 of verify.sh: turns every CHECKED assertion of the README into a PASS/FAIL line.   usage: python check_logs.py LOGDIR
import ast, os, re, sys
L = sys.argv[1]
def rd(n):
    p = os.path.join(L, n)
    return open(p).read() if os.path.isfile(p) else ''
bad = 0
def chk(name, cond, detail=''):
    global bad
    print(('PASS ' if cond else 'FAIL ') + name + (('  [' + detail + ']') if detail else ''))
    bad += (not cond)
# 1. data regeneration
c = rd('gen_cmp.log')
chk('data80.txt, gens.txt (gen.py 80) and data3.txt (gen3.py) regenerated byte-identical to data/', all(('IDENTICAL ' + f) in c for f in ('data80.txt', 'gens.txt', 'data3.txt')) and 'DIFFERENT' not in c)
g = rd('gen80.out'); g3 = rd('gen3.out')
chk('gen.py: group on lines of order 172032, generators linear on labels', 'group order on lines 172032' in g and 'gens ok, linear on labels' in g)
chk('gen3.py: 120 / 1080 / 3360 finite directions, 1120 A2 planes, group order 172032, direction list invariant', 'dirs: roots 120 n4 1080 n6 3360' in g3 and 'A2 planes 1120' in g3 and 'group order on lines 172032 (expect 172032)' in g3 and 'invariant under generators: OK' in g3)
# 2. landscape
exp = {(7, 3): [[7, 7, 7, 6, 6, 6, 6, 6, 6, 1, 1], [7, 7, 7, 6, 6, 6, 6, 6, 6, 2]],
       (8, 3): [[7, 7, 7, 7, 6, 6, 6, 6, 6, 6, 1, 1, 1], [7, 7, 7, 7, 6, 6, 6, 6, 6, 6, 3], [7, 7, 7, 7, 7, 6, 6, 6, 6, 6, 1, 1],
                [7, 7, 7, 7, 7, 6, 6, 6, 6, 6, 2], [7, 7, 7, 7, 7, 7, 7, 7, 7, 3, 1], [7, 7, 7, 7, 7, 7, 7, 7, 7, 4]]}
got = {}; rows = 0
for l in rd('land3.out').splitlines():
    m = re.match(r"^d (\d) slack (\d) (\{.*?\}) (\[.*\])$", l)
    if m:
        rows += 1; d, k = int(m.group(1)), int(m.group(2)); t = ast.literal_eval(m.group(3)); lst = ast.literal_eval(m.group(4))
        assert t['SURV'] == len(lst) or len(lst) <= 8
        if t['SURV']: got[(d, k)] = [x[1] for x in lst]
chk('land3.py 3: 32 rows (d = 1..8, slack 0..3); no survivor at slack <= 2; slack 3 survivors exactly the 8 multisets of the README (2 at d = 7, 6 at d = 8)', rows == 32 and got == exp, 'rows %d, survivors %s' % (rows, sorted((k, len(v)) for k, v in got.items())))
# 3. carrier3
t = rd('carrier3.out')
chk('carrier3.py: all finite inputs of the Carrier / Parity Lemmas pass (7 PASS lines, 0 failing)', t.count('PASS ') == 7 and 'FAIL' not in t and 'carrier3: 0 failing' in t, '%d PASS' % t.count('PASS '))
# 4. the kills, both implementations
def histA(names):
    reps, hist, mr, md, ref, nref, ok = [], [0] * 9, 0, 0, 0, 0, True
    for n in names:
        o = rd(n + '.out'); e = rd(n + '.err')
        m = re.search(r'^OVERALL \S+ V1dim (\d+) V2dim (\d+) s (\d+) lim (\d+): max real rank (\d+), max #directions (\d+); rank histogram \(nonempty pairs\):((?: \d:\d+)+)$', o, re.M)
        if not m: ok = False; continue
        reps += [int(x) for x in re.findall(r'^rep (\d+) lines', o, re.M)]
        for k, v in re.findall(r' (\d):(\d+)', m.group(7)): hist[int(k)] += int(v)
        mr = max(mr, int(m.group(5))); md = max(md, int(m.group(6)))
        r = re.search(r'^REFINE max exact rank (\d+)$', o, re.M); ref = max(ref, int(r.group(1)) if r else 0)
        nref += len(re.findall(r'^REFINE rep ', o, re.M))
    return dict(ok=ok, reps=reps, hist=hist, maxrank=mr, maxdirs=md, refine=ref, nref=nref)
def histB(names):
    reps, hist, mr, md, ref, np8, ok = [], [0] * 9, 0, 0, 0, 0, True
    for n in names:
        o = rd(n + '.out')
        m = re.search(r'^RESULT dims (\d+) (\d+) s (\d+) lim (\d+) chunk (\d+)/(\d+): nreps (\d+), max relaxed rank (\d+), max #dirs (\d+), #pairs rank>=8: (\d+), refine max exact rank (\d+); hist((?: \d:\d+)+)$', o, re.M)
        if not m: ok = False; continue
        reps += [int(x) for x in re.findall(r'^rep (\d+) lines', o, re.M)]
        for k, v in re.findall(r' (\d):(\d+)', m.group(12)): hist[int(k)] += int(v)
        mr = max(mr, int(m.group(8))); md = max(md, int(m.group(9))); np8 += int(m.group(10)); ref = max(ref, int(m.group(11)))
    return dict(ok=ok, reps=reps, hist=hist, maxrank=mr, maxdirs=md, refine=ref, nref=np8)
H = lambda s: [0] + [int(x) for x in re.findall(r'\d:(\d+)', s)]
cases = [  # name, A jobs, B jobs, nreps, (max rank, max dirs), histogram, exact-refinement max, #refined pairs
    ('E1a (6,6) s=2 lim78 [4 multisets, need < 8 / < 7]', ['A_662_c%d' % i for i in range(3)], ['B_662_c%d' % i for i in range(2)], 159, (4, 10), H('1:14024 2:15950 3:1108 4:65 5:0 6:0 7:0 8:0'), None, None),
    ('E1b (6,6) s=4 lim80 relaxed + exact third flat over 161,420 [2 multisets, need < 8]', ['A_664_c%d' % i for i in range(24)], ['B_664_c%d' % i for i in range(4)], 159, (8, 32), H('1:319084 2:592591 3:24565 4:3405 5:543 6:144 7:36 8:6'), 4, 6),
    ('E1c (7,4) s=0 lim80 [2 multisets, need < 8]', ['A_740'], ['B_740'], 51, (4, 12), None, None, None),
    ('control (6,6) s=0 lim76 = S66: span 3, 6 directions', ['A_660'], ['B_660'], 159, (3, 6), None, None, None),
    ('control (7,7) s=0 lim76: rank 8 on 152 pairs (not vacuous)', ['A_ctl77'], ['B_ctl77'], 51, (8, 80), None, None, None)]
for name, an, bn, nrep, (mr, md), hist, ref, nref in cases:
    A, B = histA(an), histB(bn)
    cover = lambda r: sorted(r) == list(range(nrep))
    chk('%s: implementation A (s6x): all %d orbit reps covered once, max real rank %d' % (name, nrep, mr), A['ok'] and cover(A['reps']) and A['maxrank'] == mr and A['maxdirs'] == md, 'rank %s dirs %s' % (A['maxrank'], A['maxdirs']))
    chk('%s: implementation B (k3): all %d orbit reps covered once, max real rank %d' % (name, nrep, mr), B['ok'] and cover(B['reps']) and B['maxrank'] == mr and B['maxdirs'] == md, 'rank %s dirs %s' % (B['maxrank'], B['maxdirs']))
    chk('%s: A and B give the identical merged rank histogram%s' % (name, (' ' + str(hist[1:])) if hist else ''), A['ok'] and B['ok'] and A['hist'] == B['hist'] and (hist is None or A['hist'] == hist), str(A['hist'][1:]))
    if ref is not None:
        chk('%s: exact refinement: %d pairs with relaxed rank 8 refined, max exact rank %d (A and B)' % (name, nref, ref), A['refine'] == ref and B['refine'] == ref and A['nref'] == nref and B['nref'] == nref, 'A %s/%s B %s/%s' % (A['refine'], A['nref'], B['refine'], B['nref']))
chk('control (7,7): both implementations find exactly 152 pairs of rank 8', histA(['A_ctl77'])['hist'][8] == 152 and histB(['B_ctl77'])['nref'] == 152)
chk('control (6,6) s=0: 0 pairs of rank 8 (A and B)', histA(['A_660'])['hist'][8] == 0 and histB(['B_660'])['nref'] == 0)
print('check_logs: %d failing' % bad); sys.exit(1 if bad else 0)
