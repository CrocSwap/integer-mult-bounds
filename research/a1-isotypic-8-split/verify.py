def gcd_many(values):
    value = 0
    for item in values:
        item = abs(item)
        while item:
            value, item = item, value % item
    return value


def image_rank(columns):
    pivots = []
    for raw in columns:
        vector = {key: value for key, value in raw.items() if value}
        for pivot_index, pivot in pivots:
            coef = vector.get(pivot_index, 0)
            if not coef:
                continue
            scale = pivot[pivot_index]
            updated = {}
            for key in set(vector) | set(pivot):
                value = scale * vector.get(key, 0) - coef * pivot.get(key, 0)
                if value:
                    updated[key] = value
            vector = updated
            if vector:
                common = gcd_many(vector.values())
                if common > 1:
                    vector = {key: value // common for key, value in vector.items()}
        if not vector:
            continue
        pivot_index = min(vector)
        if vector[pivot_index] < 0:
            vector = {key: -value for key, value in vector.items()}
        pivots.append((pivot_index, vector))
    return len(pivots)


def matrix_rank(matrix):
    rows = [list(row) for row in matrix]
    if not rows:
        return 0
    width = len(rows[0])
    rank = 0
    for col in range(width):
        pivot = None
        for row in range(rank, len(rows)):
            if rows[row][col]:
                pivot = row
                break
        if pivot is None:
            continue
        rows[rank], rows[pivot] = rows[pivot], rows[rank]
        scale = rows[rank][col]
        for row in range(len(rows)):
            if row == rank or not rows[row][col]:
                continue
            factor = rows[row][col]
            for j in range(width):
                rows[row][j] = scale * rows[row][j] - factor * rows[rank][j]
        rank += 1
    return rank


def matvec(matrix, vector):
    return [sum(matrix[row][col] * vector[col] for col in range(len(vector))) for row in range(len(matrix))]


def in_rational_span(vector, basis):
    """Return whether vector is a rational combination of the basis rows."""
    width = len(basis)
    augmented = [[basis[col][row] for col in range(width)] + [vector[row]] for row in range(len(vector))]
    rank = 0
    for col in range(width):
        pivot = None
        for row in range(rank, len(augmented)):
            if augmented[row][col]:
                pivot = row
                break
        if pivot is None:
            continue
        augmented[rank], augmented[pivot] = augmented[pivot], augmented[rank]
        scale = augmented[rank][col]
        for row in range(len(augmented)):
            if row == rank or not augmented[row][col]:
                continue
            factor = augmented[row][col]
            for j in range(width + 1):
                augmented[row][j] = scale * augmented[row][j] - factor * augmented[rank][j]
        rank += 1
    return all(row[width] == 0 for row in augmented if not any(row[col] for col in range(width)))


def poly_mul(left, right):
    out = [0] * (len(left) + len(right) - 1)
    for i, coef in enumerate(left):
        for j, other in enumerate(right):
            out[i + j] += coef * other
    return tuple(out)


def charpoly(matrix):
    """Monic characteristic polynomial, ascending coefficients, by Leverrier's method."""
    size = len(matrix)
    previous = [[0] * size for _ in range(size)]
    coeffs = [1]
    for k in range(1, size + 1):
        base = [[previous[row][col] + (coeffs[-1] if row == col else 0) for col in range(size)] for row in range(size)]
        current = [
            [sum(matrix[row][mid] * base[mid][col] for mid in range(size)) for col in range(size)]
            for row in range(size)
        ]
        trace = sum(current[index][index] for index in range(size))
        expect(trace % k == 0, "the Leverrier trace is not divisible by the step")
        coeffs.append(-trace // k)
        previous = current
    expect(all(entry == 0 for row in previous for entry in row), "the Leverrier remainder is not zero")
    return tuple(reversed(coeffs))


def annihilator_image(name, matrix, vector):
    image = matvec(matrix, vector)
    if name == "x":
        return image
    if name == "x-2":
        return [entry - 8 * vector[index] for index, entry in enumerate(image)]
    if name == "x+2":
        return [entry + 8 * vector[index] for index, entry in enumerate(image)]
    second = matvec(matrix, image)
    if name == "x^2+2x-4":
        return [second[index] + 8 * image[index] - 64 * vector[index] for index in range(8)]
    if name == "x^2-2x-4":
        return [second[index] - 8 * image[index] - 64 * vector[index] for index in range(8)]
    fail("unknown summand")


def eval_poly(coefficients, point):
    value = 0
    power = 1
    for coef in coefficients:
        value += coef * power
        power *= point
    return value


def is_square(number):
    if number < 0:
        return False
    root = int(number**0.5)
    while (root + 1) * (root + 1) <= number:
        root += 1
    while root * root > number:
        root -= 1
    return root * root == number


def ambient_from(coords, vectors):
    ambient = {}
    for component, coef in coords.items():
        if not coef:
            continue
        for index, coeff in vectors[component][1]:
            ambient[index] = ambient.get(index, 0) + coef * coeff
    return {index: value for index, value in ambient.items() if value}


def trivial_trace(element, group):
    total = 0
    for symmetry in group:
        composed = compose(element, symmetry)
        closed = trace_s(composed["inv"], composed["eps"]) * fixed_addresses(composed["T"])
        dest, sign = action_tables(composed)
        direct = sum(sign[index] for index in range(4096) if dest[index] == index)
        expect(direct == closed, "the permutation trace disagrees with the closed trace formula")
        total += closed
    expect(total % len(group) == 0, "a trivial-character trace is not integral")
    return total // len(group)


