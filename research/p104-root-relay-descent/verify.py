"""Verify the edited PR6030 word with PR5827's own chain (the chain PR6030 used).  Apache-2.0.

Prepared by DreamingOfClouds with Claude Opus 5.5 (Anthropic), via Claude Code.  The chain below is
PR5827's own verifier (its package is authenticated from inputs/ and loaded unmodified, apart from
pricing.py whose declared literal edits are in PRICING-EDITS.json); the word is regenerated by
construct.py from PR6030's word (authenticated against its main-branch pin) and the explicit edit list.
Parts: --part build (authentication, regeneration, exact replay and storage inventory),
       --part chain (the complete chain; includes build).  Default: chain.
"""
from collections import Counter
from contextlib import ExitStack
from copy import deepcopy
from fractions import Fraction as Q
from pathlib import Path
import json, sys, tempfile
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from sources import sources, load, need, read, authenticate, base_word
from construct import construct, matches_shipped

EXPECT = read(HERE / 'EXPECT.json')


def reject(action):
    try:
        action()
    except ValueError as error:
        return str(error)
    raise ValueError('Invalid control accepted')


def delta(after, before):
    value = Counter(after)
    value.subtract(before)
    return {str(r): n for r, n in sorted(value.items()) if n}


def run(part):
    with ExitStack() as contexts:
        parent = contexts.enter_context(sources())          # PR5827's extracted package
        cursor = contexts.enter_context(load(parent / 'sources.py', 'base_source_top').sources())
        for depth in range(7):                              # PR5827's own seven-deep source chain
            module = load(cursor / 'sources.py', 'base_source_' + str(depth))
            cursor, root = contexts.enter_context(module.sources())
        text = (parent / 'pricing.py').read_text(encoding='utf-8')
        for old, new in read(HERE / 'PRICING-EDITS.json'):
            need(text.count(old) == 1, 'Unique declared pricing edit')
            text = text.replace(old, new)
        need(text == (HERE / 'pricing.py').read_text(encoding='utf-8'), 'Shipped pricing.py = PR5827 pricing.py + declared edits only')
        L = load(parent / 'local.py', 'local')
        L.ROOT = root
        source = base_word()                                # PR6030's word, authenticated
        word = construct(source, read(HERE / 'EDIT.json.gz'))
        need(matches_shipped(word, (HERE / 'WORD.json.gz').read_bytes()), 'Entire regenerated WORD payload, byte for byte')
        need(all(type(e[4]) is bool for e in word['program'] if e[0] == 'MOVE'), 'Canonical MOVE private flags')
        baseline, local = L.replay(source), L.replay(word)
        need((local['public_inputs'], local['owned_fields'], local['owned_lifetimes'], local['peak_owned_fields']) ==
             (baseline['public_inputs'], baseline['owned_fields'], baseline['owned_lifetimes'], baseline['peak_owned_fields'])
             == tuple(EXPECT['inventory']), 'Unchanged storage inventory')
        need(len(word['program']) == EXPECT['events'] <= 26000, 'Event count within the retained bound')
        need(delta(local['paid'], baseline['paid']) == EXPECT['paid_delta'], 'Exact paid-profile delta')
        need(delta(local['helpers'], baseline['helpers']) == EXPECT['helper_delta'], 'Exact productive-target delta')
        print('PASS regenerated WORD.json.gz, exact replay, storage inventory, paid delta', EXPECT['paid_delta'], flush=True)
        if part == 'build':
            print(EXPECT['status'] + '_BUILD'); return None
        columns = L.reverse_columns(word)
        need(columns['columns'] == 799, 'All input columns')
        print('PASS all input columns and separate transpose', flush=True)
        native = L.native(word)
        C = load(root / 'research/p104-productive-controller/caller.py', 'base_caller')
        caller = C.construct()
        need(caller == read(root / 'research/p104-productive-controller/CONTROLLER.json'), 'Exact physical caller')
        physical = C.physical(caller, word)
        print('PASS native maps, absolute phases, adapters and complete physical caller', flush=True)
        P = load(HERE / 'pricing.py', 'edit_price')
        price = P.run(local, native, caller, physical)
        need(price['raw_root_interval'] == EXPECT['interval'], 'Exact crossing interval')
        need((price['paid_calls'], price['productive_fields'], price['rank_mass_surplus']) ==
             (EXPECT['paid_calls'], EXPECT['productive_fields'], EXPECT['rank_mass_surplus']), 'Invoice')
        need(len(price['outer']['strict_checks']) == 54 and len(price['outer']['functional_checks']) == 4, 'Outer inventory')
        # the base word's profile, scaled as in the invoice, must fail at the new claim
        E = L.load(root / 'research/higher-moment-strictification/verify.py', 'base_price_engine')
        old_p = {int(r): n for r, n in price['paid'].items()}
        old_t = {int(r): n for r, n in price['targets'].items()}
        for r in set(baseline['paid']) | set(local['paid']):
            old_p[r] = old_p.get(r, 0) + 18 * (baseline['paid'].get(r, 0) - local['paid'].get(r, 0))
        for r in set(baseline['helpers']) | set(local['helpers']):
            old_t[r] = old_t.get(r, 0) + 18 * (baseline['helpers'].get(r, 0) - local['helpers'].get(r, 0))
        margin = E.moment(old_t, 1 - P.KAPPA)[1] - E.moment(old_p, 1 - P.KAPPA)[0]
        need(margin < 0, 'PR6030 full profile fails at the new claim')
        print('PASS both rational engines, completion, compiler and all outer costs', price['raw_root_interval'], flush=True)

        controls = C.controls(caller)
        for label, make in EXPECT_CONTROLS(word, source):
            controls[label] = reject(make)
        bad = deepcopy(local); bad['paid'][1] -= 1
        controls['unpaid_query'] = reject(lambda: P.assemble(bad, native, caller, physical))
        bad = deepcopy(local); bad['helpers'][9] += 1
        controls['extra_target_credit'] = reject(lambda: P.assemble(bad, native, caller, physical))
        bw = read(HERE / 'SOURCES.json')['base_word']; raw = (HERE / bw['local_path']).read_bytes()
        controls['damaged_base_word'] = reject(lambda: authenticate(bytes([raw[0] ^ 1]) + raw[1:], bw))
        for pin in read(HERE / 'SOURCES.json')['archived_files'][:3]:
            raw = (parent / Path(pin['path']).relative_to(read(HERE / 'SOURCES.json')['source_archive']['package'])).read_bytes()
            controls['damaged_source_' + Path(pin['path']).name] = reject(
                lambda raw=raw, pin=pin: authenticate(bytes([raw[0] ^ 1]) + raw[1:], pin))
        result = dict(status=EXPECT['status'], base_commit=EXPECT['base_commit'], source_local=baseline, local=local,
                      paid_delta=EXPECT['paid_delta'], target_delta=EXPECT['helper_delta'], separate_columns=columns,
                      native=native, physical_caller=physical, complete_cost=price,
                      base_margin_upper_at_new_claim=margin, controls=controls,
                      limits=['All five inherited framework assumptions remain.',
                              'The large uniform word and rounded multiplier are not materialized.',
                              'Author checks do not establish independent acceptance.',
                              'The selected frontier is unchanged.'])
        return P.encode(result)


def EXPECT_CONTROLS(word, source):
    """Corruptions of the edited word that the exact replay must reject."""
    L = sys.modules['local']
    out = []
    for label, index in EXPECT['control_sites'].items():
        bad = deepcopy(word); bad['program'].pop(index)
        out.append(('missing_' + label, lambda bad=bad: L.replay(bad)))
    for label, index in EXPECT['sign_sites'].items():
        bad = deepcopy(word); q = Q(bad['program'][index][-2]); bad['program'][index][-2] = str(-q)
        out.append(('wrong_sign_' + label, lambda bad=bad: L.replay(bad)))
    return out


def main():
    part = sys.argv[sys.argv.index('--part') + 1] if '--part' in sys.argv else 'chain'
    need(part in ('build', 'chain'), '--part must be build or chain')
    with tempfile.TemporaryDirectory(prefix='p104-edit-bytecode-') as cache:
        sys.pycache_prefix = cache
        result = run(part)
    if result is None:
        return
    path = HERE / 'RESULT.json'
    if '--write' in sys.argv:
        path.write_bytes((json.dumps(result, sort_keys=True, indent=2) + '\n').encode())
    else:
        need(read(path) == result, 'Exact retained output: RESULT.json')
    print(EXPECT['status'], flush=True)


if __name__ == '__main__':
    main()
