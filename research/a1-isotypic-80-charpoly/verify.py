def trivial_trace(element, group):
    total = 0
    for symmetry in group:
        composed = compose(element, symmetry)
        closed = trace_s(composed["inv"], composed["eps"]) * fixed_addresses(composed["T"])
        dest, sign = action_tables(composed)
        direct = sum(sign[index] for index in range(4096) if dest[index] == index)
        expect(direct == closed, "the permutation trace disagrees with the closed trace formula")
        total += closed
    expect(total % len(group) == 0, "a trivial-character trace is not integral")
    return total // len(group)


def coeff_bound(size, row_sum):
    best = 1
    binomial = 1
    power = 1
    for degree in range(size + 1):
        term = binomial * power
        if term > best:
            best = term
        if degree < size:
            binomial = binomial * (size - degree) // (degree + 1)
            power *= row_sum
    return best


def is_prime(number):
    if number < 2:
        return False
    if number % 2 == 0:
        return number == 2
    divisor = 3
    while divisor * divisor <= number:
        if number % divisor == 0:
            return False
        divisor += 2
    return True


def primes_past(limit):
    modulus = 1
    primes = []
    candidate = 1_000_003
    while modulus <= limit:
        if is_prime(candidate):
            primes.append(candidate)
            modulus *= candidate
        candidate += 2
    return primes, modulus


def charpoly_mod(matrix, prime):
    size = len(matrix)
    hess = [[entry % prime for entry in row] for row in matrix]
    for column in range(size - 2):
        pivot = None
        for row in range(column + 1, size):
            if hess[row][column]:
                pivot = row
                break
        if pivot is None:
            continue
        if pivot != column + 1:
            hess[column + 1], hess[pivot] = hess[pivot], hess[column + 1]
            for row in hess:
                row[column + 1], row[pivot] = row[pivot], row[column + 1]
        inverse = pow(hess[column + 1][column], -1, prime)
        for row in range(column + 2, size):
            factor = hess[row][column]
            if not factor:
                continue
            factor = factor * inverse % prime
            target = hess[row]
            source = hess[column + 1]
            for index in range(column, size):
                target[index] = (target[index] - factor * source[index]) % prime
            for host in hess:
                host[column + 1] = (host[column + 1] + factor * host[row]) % prime
    minors = [[1], [(prime - hess[0][0]) % prime, 1]]
    for end in range(1, size):
        previous = minors[end]
        diagonal = hess[end][end]
        output = [0] * (end + 2)
        for index, coefficient in enumerate(previous):
            output[index + 1] = coefficient
            output[index] = (output[index] - diagonal * coefficient) % prime
        product = 1
        for start in range(end - 1, -1, -1):
            product = product * hess[start + 1][start] % prime
            if product == 0:
                break
            scale = hess[start][end] * product % prime
            if scale == 0:
                continue
            for index, coefficient in enumerate(minors[start]):
                output[index] = (output[index] - scale * coefficient) % prime
        expect(output[-1] % prime == 1, "Hessenberg characteristic polynomial is not monic")
        minors.append(output)
    return minors[size]


def det_mod(matrix, prime):
    size = len(matrix)
    work = [[entry % prime for entry in row] for row in matrix]
    determinant = 1
    for column in range(size):
        pivot = None
        for row in range(column, size):
            if work[row][column]:
                pivot = row
                break
        if pivot is None:
            return 0
        if pivot != column:
            work[column], work[pivot] = work[pivot], work[column]
            determinant = (-determinant) % prime
        determinant = determinant * work[column][column] % prime
        inverse = pow(work[column][column], -1, prime)
        for row in range(column + 1, size):
            factor = work[row][column]
            if not factor:
                continue
            factor = factor * inverse % prime
            target = work[row]
            source = work[column]
            for index in range(column, size):
                target[index] = (target[index] - factor * source[index]) % prime
    return determinant


def crt_signed(residues, primes):
    value = 0
    modulus = 1
    for residue, prime in zip(residues, primes):
        increment = ((residue - value) % prime) * pow(modulus % prime, -1, prime) % prime
        value += increment * modulus
        modulus *= prime
    if value > modulus // 2:
        value -= modulus
    return value
def poly_mul(left, right):
    output = [0] * (len(left) + len(right) - 1)
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            output[i + j] += a * b
    return output


def poly_pow(base, exponent):
    result = [1]
    while exponent:
        if exponent & 1:
            result = poly_mul(result, base)
        exponent >>= 1
        if exponent:
            base = poly_mul(base, base)
    return result


def product_factors(factors):
    value = [1]
    for multiplicity, coefficients in factors:
        value = poly_mul(value, poly_pow(list(coefficients), multiplicity))
    return value

def trim(coefficients, prime):
    output = [coefficient % prime for coefficient in coefficients]
    while len(output) > 1 and output[-1] == 0:
        output.pop()
    return output


def monic_mod(coefficients, prime):
    inverse = pow(coefficients[-1], -1, prime)
    return [(coefficient * inverse) % prime for coefficient in coefficients]


def remainder_mod(numerator, divisor, prime):
    work = trim(numerator, prime)
    modulus = monic_mod(trim(divisor, prime), prime)
    degree = len(modulus) - 1
    while len(work) - 1 >= degree and not (len(work) == 1 and work[0] == 0):
        shift = len(work) - 1 - degree
        lead = work[-1]
        for index, coefficient in enumerate(modulus):
            work[shift + index] = (work[shift + index] - lead * coefficient) % prime
        while len(work) > 1 and work[-1] == 0:
            work.pop()
    return work


def gcd_mod(left, right, prime):
    first = trim(left, prime)
    second = trim(right, prime)
    while not (len(second) == 1 and second[0] == 0):
        first, second = second, remainder_mod(first, second, prime)
    if len(first) == 1 and first[0] == 0:
        return [0]
    return monic_mod(first, prime)


def pow_mod_poly(exponent, modulus, prime):
    result = [1]
    base = [0, 1]
    degree = len(modulus) - 1
    while exponent:
        if exponent & 1:
            result = remainder_mod(poly_mul(result, base), modulus, prime)
        exponent >>= 1
        if exponent:
            base = remainder_mod(poly_mul(base, base), modulus, prime)
        expect(len(result) <= degree + 1, "polynomial remainder grew past the modulus")
    return result


def is_square(number):
    if number < 0:
        return False
    root = int(number ** 0.5)
    while (root + 1) * (root + 1) <= number:
        root += 1
    while root * root > number:
        root -= 1
    return root * root == number


def x_minus_power(exponent, modulus, prime):
    power = pow_mod_poly(exponent, modulus, prime)
    if len(power) < 2:
        power = power + [0] * (2 - len(power))
    power = power[:]
    power[1] = (power[1] - 1) % prime
    return trim(power, prime)


def irreducible_mod(coefficients, prime):
    reduced = trim(coefficients, prime)
    if len(reduced) <= 2:
        return len(reduced) == 2
    if reduced[-1] % prime == 0:
        return False
    modulus = monic_mod(reduced, prime)
    degree = len(modulus) - 1
    derivative = [((index * coefficient) % prime) for index, coefficient in enumerate(modulus)][1:]
    if gcd_mod(modulus, derivative or [0], prime) != [1]:
        return False
    primes = []
    value = degree
    divisor = 2
    while divisor * divisor <= value:
        if value % divisor == 0:
            primes.append(divisor)
            while value % divisor == 0:
                value //= divisor
        divisor += 1
    if value > 1:
        primes.append(value)
    if x_minus_power(prime ** degree, modulus, prime) != [0]:
        return False
    for factor in primes:
        if gcd_mod(x_minus_power(prime ** (degree // factor), modulus, prime), modulus, prime) != [1]:
            return False
    return True


def prove_irreducible(coefficients):
    degree = len(coefficients) - 1
    expect(coefficients[-1] == 1, "a factor is not monic")
    if degree == 1:
        return
    if degree == 2:
        discriminant = coefficients[1] * coefficients[1] - 4 * coefficients[0]
        expect(not is_square(discriminant), "a quadratic factor is reducible over Z")
        return
    candidate = 1009
    tried = 0
    while tried < 80:
        if is_prime(candidate) and irreducible_mod(coefficients, candidate):
            return
        if is_prime(candidate):
            tried += 1
        candidate += 2
    fail("no prime in the first 80 primes at or above 1009 proved a factor irreducible")

def descending(coefficients):
    terms = []
    for power, coefficient in enumerate(coefficients):
        if coefficient:
            terms.append((power, coefficient))
    parts = []
    for power, coefficient in reversed(terms):
        if power == 0:
            body = str(abs(coefficient))
            if not parts:
                parts.append(str(coefficient))
            else:
                parts.append(("+ " if coefficient > 0 else "- ") + body)
            continue
        magnitude = abs(coefficient)
        letter = "x" if power == 1 else "x^" + str(power)
        if magnitude == 1:
            body = letter
        else:
            body = str(magnitude) + letter
        if not parts:
            parts.append(body if coefficient > 0 else "-" + body)
        else:
            parts.append(("+ " if coefficient > 0 else "- ") + body)
    return " ".join(parts)
def row_sum(matrix):
    return max(sum(abs(entry) for entry in row) for row in matrix)


def evaluate(coefficients, point, prime):
    value = 0
    power = 1
    for coefficient in coefficients:
        value = (value + coefficient * power) % prime
        power = power * point % prime
    return value


def shifted_det(matrix, point, prime):
    size = len(matrix)
    work = [[(-entry) % prime for entry in row] for row in matrix]
    for index in range(size):
        work[index][index] = (work[index][index] + point) % prime
    return det_mod(work, prime)


class OrbitLattice:
    """Integer solution space of monomial eigenvalue equations on Q^n."""

    def __init__(self, size):
        self.size = size
        self.parent = list(range(size))
        self.rel = [1] * size
        self.dead = [False] * size

    def find(self, index):
        sign = 1
        seen = []
        while self.parent[index] != index:
            seen.append(index)
            sign *= self.rel[index]
            index = self.parent[index]
        accumulated = 1
        for step in reversed(seen):
            accumulated = self.rel[step] * accumulated
            self.rel[step] = accumulated
            self.parent[step] = index
        return index, sign

    def constrain(self, dst, src, sgn):
        root_dst, sign_dst = self.find(dst)
        root_src, sign_src = self.find(src)
        if root_dst == root_src:
            if sign_dst != sgn * sign_src:
                self.dead[root_dst] = True
            return
        self.parent[root_dst] = root_src
        self.rel[root_dst] = sgn * sign_src * sign_dst
        if self.dead[root_dst] or self.dead[root_src]:
            self.dead[root_src] = True

    def add_operator(self, dest, sign, eigenvalue):
        for src in range(self.size):
            self.constrain(dest[src], src, sign[src] * eigenvalue)

    def basis(self):
        groups = {}
        for index in range(self.size):
            root, sign = self.find(index)
            if self.dead[root]:
                continue
            groups.setdefault(root, []).append((index, sign))
        vectors = []
        for items in groups.values():
            items.sort()
            pivot = items[0][1]
            vectors.append((items[0][0], [(index, coeff * pivot) for index, coeff in items]))
        vectors.sort()
        return vectors


def monomial(columns_word):
    dest = [0] * len(columns_word)
    sign = [0] * len(columns_word)
    for src, image in enumerate(columns_word):
        expect(len(image) == 1, "a dihedral word does not act by a monomial matrix")
        (dst, value), = image.items()
        expect(value in (1, -1), "a dihedral word has a coefficient other than plus or minus one")
        dest[src] = dst
        sign[src] = value
    expect(len(set(dest)) == len(dest), "a dihedral word does not permute the 216-basis")
    return dest, sign


def apply_monomial(dest, sign, sparse):
    acc = {}
    for src, coef in sparse.items():
        if not coef:
            continue
        target = dest[src]
        acc[target] = acc.get(target, 0) + sign[src] * coef
    return {index: value for index, value in acc.items() if value}


def canonical(obj):
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=True)


def minor_matrix(matrix, block):
    return [[matrix[row][col] for col in block] for row in block]


def connected_components(matrix):
    size = len(matrix)
    seen = [False] * size
    blocks = []
    for start in range(size):
        if seen[start]:
            continue
        stack = [start]
        seen[start] = True
        block = []
        while stack:
            node = stack.pop()
            block.append(node)
            for other in range(size):
                if seen[other]:
                    continue
                if matrix[node][other] or matrix[other][node]:
                    seen[other] = True
                    stack.append(other)
        blocks.append(sorted(block))
    return blocks


def interpolate_mod(matrix, prime):
    """Monomial characteristic polynomial modulo prime, from determinants at 0..n."""
    size = len(matrix)
    xs = list(range(size + 1))
    divided = [shifted_det(matrix, point, prime) for point in xs]
    for level in range(1, size + 1):
        for index in range(size, level - 1, -1):
            divided[index] = (
                (divided[index] - divided[index - 1]) * pow(xs[index] - xs[index - level], -1, prime)
            ) % prime
    coeff = [0] * (size + 1)
    coeff[0] = divided[size] % prime
    for knot in range(size - 1, -1, -1):
        nxt = [0] * (size + 1)
        for index, term in enumerate(coeff):
            nxt[index] = (nxt[index] - term * xs[knot]) % prime
            if index + 1 <= size:
                nxt[index + 1] = (nxt[index + 1] + term) % prime
        nxt[0] = (nxt[0] + divided[knot]) % prime
        coeff = nxt
    return coeff


def charpoly_integer(matrix):
    """Monic characteristic polynomial of an integer matrix, ascending coefficients."""
    size = len(matrix)
    bound = coeff_bound(size, row_sum(matrix))
    primes, modulus = primes_past(2 * bound)
    expect(modulus > 2 * bound, "CRT modulus does not exceed the coefficient bound")
    residues = [[] for _ in range(size + 1)]
    for index, prime in enumerate(primes):
        polynomial = charpoly_mod(matrix, prime)
        expect(len(polynomial) == size + 1 and polynomial[-1] == 1, "modular characteristic polynomial has the wrong degree")
        if index == 0:
            expect(
                interpolate_mod(matrix, prime) == polynomial,
                "Hessenberg characteristic polynomial disagrees with determinant interpolation",
            )
        elif index < 3:
            for point in (0, 1, 2, 3, 5):
                expect(
                    evaluate(polynomial, point, prime) == shifted_det(matrix, point, prime),
                    "Hessenberg characteristic polynomial disagrees with a determinant",
                )
        for power, coefficient in enumerate(polynomial):
            residues[power].append(coefficient)
    coefficients = [crt_signed(residues[index], primes) for index in range(size + 1)]
    expect(coefficients[-1] == 1, "characteristic polynomial is not monic")
    expect(all(abs(coefficient) <= bound for coefficient in coefficients), "a coefficient exceeds the Gershgorin binomial bound")
    expect(-coefficients[size - 1] == sum(matrix[index][index] for index in range(size)), "trace disagrees with the degree n-1 coefficient")
    return coefficients


def exact_quotient(target, divisor):
    work = list(target)
    degree = len(divisor) - 1
    expect(divisor[-1] == 1, "exact division requires a monic divisor")
    if len(work) - 1 < degree:
        return None
    quotient = [0] * (len(work) - degree)
    while len(work) - 1 >= degree and not (len(work) == 1 and work[0] == 0):
        shift = len(work) - 1 - degree
        lead = work[-1]
        quotient[shift] = lead
        for index, coefficient in enumerate(divisor):
            work[shift + index] -= lead * coefficient
        while len(work) > 1 and work[-1] == 0:
            work.pop()
    if work not in ([0], []):
        return None
    while len(quotient) > 1 and quotient[-1] == 0:
        quotient.pop()
    return quotient


def scale_characteristic(coefficients):
    degree = len(coefficients) - 1
    expect(
        all(coefficient % (4 ** (degree - index)) == 0 for index, coefficient in enumerate(coefficients)),
        "chi_A is not an integer polynomial",
    )
    return [coefficient // (4 ** (degree - index)) for index, coefficient in enumerate(coefficients)]


def substituted_minus(coefficients):
    """Monic polynomial f(-x), up to the unit needed when the degree is odd."""
    signed = [coefficient if index % 2 == 0 else -coefficient for index, coefficient in enumerate(coefficients)]
    if (len(coefficients) - 1) % 2:
        signed = [-coefficient for coefficient in signed]
    return signed


def factor_counts(polynomial):
    remaining = list(polynomial)
    counts = []
    for multiplicity, factor in FACTORS:
        count = 0
        divisor = list(factor)
        while count < multiplicity:
            quotient = exact_quotient(remaining, divisor)
            if quotient is None:
                break
            remaining = quotient
            count += 1
        counts.append(count)
    return tuple(counts), remaining


def selected_product(counts):
    chosen = [(count, factor) for count, (_multiplicity, factor) in zip(counts, FACTORS) if count]
    return product_factors(chosen)


def store_evidence(path, payload, expected_sha):
    raw = (canonical(payload) + "\n").encode()
    digest = sha256_bytes(raw)
    if "--dump-evidence" in sys.argv:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)
