def power(element, count, identity):
    value = identity
    for _ in range(count):
        value = compose(value, element)
    return value


def coordinates_216(sparse, owners, vectors):
    alphas = {}
    for index, value in sparse.items():
        if not value:
            continue
        info = owners.get(index)
        expect(info is not None, "a vector leaves the 216-dimensional joint space")
        component, base = info
        alpha = value * base
        previous = alphas.get(component)
        expect(previous is None or previous == alpha, "a joint component receives two coefficients")
        alphas[component] = alpha
    for component, alpha in alphas.items():
        for index, coeff in vectors[component][1]:
            expect(sparse.get(index, 0) == coeff * alpha, "a joint component is only partly present")
    return alphas


def permute_component(dest, sign, items, owners, vectors):
    image = {}
    for index, coeff in items:
        target = dest[index]
        image[target] = image.get(target, 0) + sign[index] * coeff
    image = {index: value for index, value in image.items() if value}
    return coordinates_216(image, owners, vectors)


def combine_words(word_images, sign_u):
    images = []
    width = len(word_images[0])
    for component in range(width):
        acc = {}
        for power_index in range(6):
            rotation_sign = -1 if power_index % 2 else 1
            for dest, value in word_images[2 * power_index][component].items():
                acc[dest] = acc.get(dest, 0) + rotation_sign * value
            reflection_sign = rotation_sign * sign_u
            for dest, value in word_images[2 * power_index + 1][component].items():
                acc[dest] = acc.get(dest, 0) + reflection_sign * value
        images.append({dest: value for dest, value in acc.items() if value})
    return images


