#!/usr/bin/env python3
"""Checks of the p104-lowerbound-toolkit package (standard library only; Lean is NOT run here).

Static: file pins (MANIFEST.sha256, both directions); no sorry/admit/native_decide/axiom/opaque/unsafe/implemented_by/
extern/ofReduceBool outside comments and strings; build-order.txt is a topological order of the Nov15 import graph and
equals the import closure of All.lean; every Check.lean name is declared; CHECK-axioms.txt lists exactly the Check.lean
names, each within {propext, Classical.choice, Quot.sound}; toolchain and Mathlib pins; no local paths.
Python side: lean/Nov15/FrameCert.lean is regenerated BYTE-IDENTICAL from data/frame (tools/framecert).
drat/ (SAT/DRAT certificate of the tight class, not Lean): hashes.tsv/cubes.txt consistency and five regenerated CNF hashes.
The kernel check itself is verify.sh (lean/check.sh; needs Lean and the pinned Mathlib).

DreamingOfClouds with Claude Opus 5.5 (Anthropic), via Claude Code. Apache-2.0.
"""
import hashlib
import json
import os
import re
import sys
import subprocess
import tempfile
from pathlib import Path

sys.dont_write_bytecode = True
PKG = Path(__file__).resolve().parent
LEAN = PKG / "lean"
NOV = LEAN / "Nov15"
STD = {"propext", "Classical.choice", "Quot.sound"}
MATHLIB_REV = "55b7917b472489c7c56a0fa6393af05cfd536599"
TOOLCHAIN = "leanprover/lean4:v4.33.0-rc1"
FORBIDDEN = ["sorry", "admit", "native_decide", "axiom", "opaque", "unsafe", "implemented_by", "extern",
             "ofReduceBool"]
WORDS = [  # (name, word file, chain tag, slot)
    ("T7669", "t7669.json.gz", "7669"),
    ("Ws4", "w_s4.json.gz", "Ws4"),
]
IMP = re.compile(r"^\s*import\s+Nov15\.(\S+)", re.M)


def fail(msg):
    print("FAIL: " + msg)
    sys.exit(1)


def strip_lean(src):
    """Remove (nested) block comments, line comments and string literals."""
    out, i, n, depth = [], 0, len(src), 0
    while i < n:
        if src.startswith("/-", i):
            depth += 1; i += 2; continue
        if depth:
            if src.startswith("-/", i):
                depth -= 1; i += 2
            else:
                i += 1
            continue
        if src.startswith("--", i):
            j = src.find("\n", i); i = n if j < 0 else j; continue
        if src[i] == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append('""'); i = j + 1; continue
        out.append(src[i]); i += 1
    if depth:
        fail("unterminated block comment")
    return "".join(out)


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def check_manifest():
    rows = {}
    for line in (PKG / "MANIFEST.sha256").read_text(encoding="utf-8").splitlines():
        digest, name = line.split("  ", 1)
        rows[name] = digest
    present = set()
    for p in PKG.rglob("*"):
        rel = p.relative_to(PKG).as_posix()
        if (not p.is_file() or ".lake" in p.parts or "logs" in p.parts or "__pycache__" in p.parts
                or rel in ("MANIFEST.sha256", "lean/logs-Check.txt")):
            continue
        present.add(rel)
    if set(rows) != present:
        fail("MANIFEST.sha256 file set differs: missing %s, extra %s"
             % (sorted(present - set(rows))[:5], sorted(set(rows) - present)[:5]))
    for name, digest in rows.items():
        if sha(PKG / name) != digest:
            fail("sha256 mismatch: " + name)
    return len(rows)


def check_lean():
    order = (LEAN / "build-order.txt").read_text(encoding="utf-8").split()
    shipped = sorted(p.stem for p in NOV.glob("*.lean"))
    if len(set(order)) != len(order) or sorted(order) != shipped:
        fail("lean/Nov15 differs from build-order.txt")
    imports, decls, seen = {}, set(), set()
    for m in order:
        code = strip_lean((NOV / (m + ".lean")).read_text(encoding="utf-8"))
        imports[m] = IMP.findall(code)
        for tok in FORBIDDEN:
            if re.search(r"(?<![\w.'])" + re.escape(tok) + r"(?![\w'])", code):
                fail("forbidden token %r outside comments in %s" % (tok, m))
        ns = re.findall(r"^namespace\s+(\S+)", code, re.M)
        for name in re.findall(r"(?:theorem|lemma|def|abbrev|structure|inductive|instance)\s+([^\s(:{\[]+)", code):
            decls.add(name); decls.update(n + "." + name for n in ns)
        for d in imports[m]:
            if d not in seen:
                fail("build-order.txt is not topological: %s imports %s" % (m, d))
        seen.add(m)
    for f in ("All.lean", "Check.lean"):
        code = strip_lean((LEAN / f).read_text(encoding="utf-8"))
        for tok in FORBIDDEN:
            if re.search(r"(?<![\w.'])" + re.escape(tok) + r"(?![\w'])", code):
                fail("forbidden token %r in %s" % (tok, f))
    closure, stack = set(), IMP.findall((LEAN / "All.lean").read_text(encoding="utf-8"))
    while stack:
        m = stack.pop()
        if m in closure:
            continue
        if m not in imports:
            fail("All.lean closure needs missing module " + m)
        closure.add(m); stack.extend(imports[m])
    if closure != set(order):
        fail("build-order.txt != import closure of All.lean (extra %s)" % sorted(set(order) - closure)[:5])
    names = re.findall(r"^#print axioms (\S+)", (LEAN / "Check.lean").read_text(encoding="utf-8"), re.M)
    if len(set(names)) != len(names):
        fail("duplicate names in Check.lean")
    got = {}
    for line in (PKG / "CHECK-axioms.txt").read_text(encoding="utf-8").splitlines():
        m1 = re.match(r"^'(\S+)' depends on axioms: \[(.*)\]$", line)
        m2 = re.match(r"^'(\S+)' does not depend on any axioms$", line)
        if m1:
            got[m1.group(1)] = {x.strip() for x in m1.group(2).split(",")}
        elif m2:
            got[m2.group(1)] = set()
        else:
            fail("unparsed CHECK-axioms.txt line: " + line)
    if sorted(got) != sorted(names):
        fail("CHECK-axioms.txt names differ from Check.lean")
    for nm, ax in got.items():
        if not ax <= STD:
            fail("non-standard axioms for %s: %s" % (nm, sorted(ax - STD)))
    tc = (LEAN / "lean-toolchain").read_text(encoding="utf-8").strip()
    if tc != TOOLCHAIN or MATHLIB_REV not in (LEAN / "lakefile.toml").read_text(encoding="utf-8") \
            or MATHLIB_REV not in (LEAN / "lake-manifest.json").read_text(encoding="utf-8"):
        fail("toolchain / Mathlib pin")
    return len(order), len(names)


def check_framecert():
    with tempfile.TemporaryDirectory() as td:
        out = os.path.join(td, "FrameCert.lean")
        subprocess.run([sys.executable, "-I", "-B", str(PKG / "tools" / "framecert" / "asm.py"), out], check=True)
        if Path(out).read_bytes() != (NOV / "FrameCert.lean").read_bytes():
            fail("FrameCert.lean is not byte-identical to its regeneration")
    return "FrameCert.lean regenerated byte-identical from data/frame (tools/framecert)"


def check_drat():
    """drat/: cubes.txt and hashes.tsv list the same 1001 cubes; the base CNF and a few cube CNFs regenerate to the pinned
    sha256 (the full certificate check is drat/check.py, optional proofs drat/run_drat.sh)."""
    import hashlib as hl
    d = PKG / "drat"
    rows = [l.split("\t") for l in (d / "hashes.tsv").read_text(encoding="utf-8").splitlines() if not l.startswith("#")]
    ids = [l.split("\t")[0] for l in (d / "cubes.txt").read_text(encoding="utf-8").splitlines() if not l.startswith("#")]
    if len(ids) != 1001 or [r[0] for r in rows] != ids or any(r[4] != "UNSAT" or r[5] != "VERIFIED" for r in rows):
        fail("drat/cubes.txt and drat/hashes.tsv differ or are not 1001 UNSAT/VERIFIED cubes")
    sys.path.insert(0, str(d))
    import gen
    b = gen.Base()
    for cid in ("i3", "f33", "i1_d1le5", "j8_6", ids[-1]):
        if hl.sha256(gen.cube_text(cid, b).encode()).hexdigest() != dict((r[0], r[1]) for r in rows)[cid]:
            fail("drat cube CNF does not regenerate to its pinned sha256: " + cid)
    return "drat: 1001 cubes listed, 5 sample CNFs regenerate to the pinned sha256"


def main():
    nfiles = check_manifest()
    nmod, nnames = check_lean()
    for p in PKG.rglob("*"):
        if p.is_file() and p.suffix in (".py", ".md", ".json", ".sh", ".lean", ".txt", ".toml") \
                and ".lake" not in p.parts:
            t = p.read_text(encoding="utf-8", errors="replace")
            if re.search(r"/(?:Users|home)/|claude[.]ai/code", t):
                fail("local path in " + p.relative_to(PKG).as_posix())
    print(check_framecert())
    print(check_drat())
    print("PASS_LOWERBOUND_PACKAGE %d pinned files, %d modules, %d headline names" % (nfiles, nmod, nnames))


if __name__ == "__main__":
    main()
