#!/usr/bin/env python3
"""Generate the kernel-checkable CK instance from independently validated inputs.
Apache-2.0; substantial OpenAI Codex assistance.
"""
from pathlib import Path
import argparse
import hashlib
import json
from check_source import load_fixture

HERE = Path(__file__).resolve().parent


def render(fixture):
    gates = fixture['cleanup']
    recipe = fixture['selected_indices']
    chosen = set(recipe)
    cut = max(recipe) + 1
    palette = sorted({(g["num"], g["den"]) for g in gates})
    codes = [palette.index((g["num"], g["den"])) for g in gates]
    def instr(i):
        g = gates[i]
        shape = f".add {g['target']} {g['source']}" if g['kind'] == 'add' else f".scale {g['target']}"
        return f"⟨{i}, {shape}⟩"
    def seq(xs):
        return '[\n  ' + ',\n  '.join(xs) + '\n]'
    digest = hashlib.sha256(json.dumps(fixture, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return f'''-- Generated by generate_lean.py; do not hand-edit.
-- Validated fixture canonical SHA-256: {digest}
-- Apache-2.0. Substantial OpenAI Codex assistance.
import CleanupPrefix

set_option maxRecDepth 20000
set_option maxHeartbeats 16000000
noncomputable section
namespace CleanupPrefix.CK

-- Prevent elaboration from symbolically executing thousands of arbitrary-state gates.
-- The transparent kernel definition and all previously proved equations are unchanged.
attribute [local irreducible] run

noncomputable def initial : List Instruction := {seq(instr(i) for i in range(cut))}
noncomputable def suffix : List Instruction := {seq(instr(i) for i in range(cut, len(gates)))}
noncomputable def cleanup : List Instruction := initial ++ suffix
noncomputable def recipe : List Nat := {repr(recipe)}
noncomputable def selected : List Instruction := {seq(instr(i) for i in recipe)}
noncomputable def prefixTail : List Instruction := {seq(instr(i) for i in range(cut) if i not in chosen)}
noncomputable def remainder : List Instruction := prefixTail ++ suffix

attribute [local irreducible] initial suffix cleanup recipe selected prefixTail remainder

/-- The whole original-prefix and disjointness check is kernel-reduced. -/
theorem checked : sourceExtract recipe initial = some (selected, prefixTail) := by decide +kernel

/-- This fixture uses precisely recipe order and the original stable remainder. -/
theorem selected_order : selected.map Instruction.index = recipe := by decide +kernel

theorem prefix_filter : prefixTail =
    initial.filter (fun g => !recipe.contains g.index) := by decide +kernel

theorem recipe_below_cut : recipe.all (fun i => decide (i < {cut})) = true := by decide +kernel

theorem suffix_above_cut : suffix.all (fun g => decide ({cut} ≤ g.index)) = true := by decide +kernel

theorem suffix_unselected : suffix.all (fun g => !recipe.contains g.index) = true :=
  suffix_unselected_of_bounds recipe suffix {cut} recipe_below_cut suffix_above_cut

theorem stable_remainder : remainder =
    cleanup.filter (fun g => !recipe.contains g.index) := by
  unfold remainder cleanup
  rw [List.filter_append, ← prefix_filter]
  rw [List.filter_eq_self.mpr (List.all_eq_true.mp suffix_unselected)]

/-- Universal in every coefficient, including the source's exact rationals.
No numerical state sampling and no field implementation are assumed. -/
theorem scalar_rewrite [Scalar α] (coeff : Nat → α) (before after : List Instruction)
    (σ : State α) :
    run coeff (before ++ cleanup ++ after) σ =
      run coeff (before ++ (selected ++ remainder) ++ after) σ :=
  by
  have h := sourceExtract_in_context coeff recipe initial selected prefixTail before (suffix ++ after) checked σ
  simpa only [cleanup, remainder, List.append_assoc] using h

-- A concrete coefficient record, preserved exactly from the validated source.
noncomputable def rationalPalette : List (Int × Nat) := {seq(f"({n}, {d})" for n, d in palette)}
noncomputable def coefficientCodes : List Nat := {repr(codes)}
noncomputable def rationalData : List (Int × Nat) :=
  coefficientCodes.map (fun j => rationalPalette[j]?.getD (0, 1))
attribute [local irreducible] rationalPalette coefficientCodes rationalData

/-- Supply an interpretation of exact numerator/positive-denominator pairs.
For Q/C one uses their usual rational embedding; its algebra instance is external. -/
noncomputable def coefficients (interpret : Int → Nat → α) (i : Nat) : α :=
  let code := coefficientCodes[i]?.getD 0
  let q := rationalPalette[code]?.getD (0, 1)
  interpret q.1 q.2

theorem source_coefficient_rewrite [Scalar α] (interpret : Int → Nat → α)
    (σ : State α) :
    run (coefficients interpret) cleanup σ =
      run (coefficients interpret) (selected ++ remainder) σ :=
  by
  have h := scalar_rewrite (coefficients interpret) [] [] σ
  simpa only [List.nil_append, List.append_nil] using h

#print axioms checked
#print axioms scalar_rewrite
#print axioms source_coefficient_rewrite
end CleanupPrefix.CK
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='regenerate the committed Lean instance')
    args = parser.parse_args()
    content = render(load_fixture())
    target = HERE / 'CKFixture.lean'
    if args.write:
        target.write_text(content)
    elif not target.exists() or target.read_text() != content:
        raise SystemExit('CKFixture.lean differs from validated source; run generate_lean.py --write')
    print('PASS_CK_LEAN_SOURCE_BINDING', hashlib.sha256(content.encode()).hexdigest())

if __name__ == '__main__':
    main()
