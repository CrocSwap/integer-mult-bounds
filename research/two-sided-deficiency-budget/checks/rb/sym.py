# frame-preserving signed permutations (W(D8)-type, pair partition {12}{34}{56}{78}); check they act on P112 and LINEARLY on labels; orbits of the 1200 directions
import numpy as np, itertools, json
from targ import H, off, LAB, L2
idx={}
for t,r in enumerate(L2):
    idx[tuple(r)]=t; idx[tuple(-r)]=t
def gens():
    g=[]
    P=[(0,1),(2,3),(4,5),(6,7)]
    def perm(p):
        M=np.zeros((8,8),int)
        for i,j in enumerate(p): M[j,i]=1
        return M
    g.append(perm([1,0,2,3,4,5,6,7]))            # swap within pair
    g.append(perm([2,3,0,1,4,5,6,7]))            # swap pairs
    g.append(perm([2,3,4,5,6,7,0,1]))            # cycle pairs
    S=np.eye(8,dtype=int); S[0,0]=-1; S[2,2]=-1; g.append(S)   # even sign change
    S=np.eye(8,dtype=int); S[0,0]=-1; S[1,1]=-1; g.append(S)
    return g
def lineperm(M):
    return [idx[tuple(M@r)] for r in L2]
def solveA(pi):
    # find F2-linear A with A LAB[t] = LAB[pi[t]] for all t
    basis=[];img=[];red=[]
    for t in range(112):
        x=LAB[t]; y=LAB[pi[t]]
        for (bx,by) in red:
            if x^bx<x: x^=bx; y^=by
        if x: red.append((x,y)); red.sort(reverse=True)
    # check consistency: every label reduces to 0 with image 0
    for t in range(112):
        x=LAB[t]; y=LAB[pi[t]]
        for (bx,by) in sorted(red,reverse=True):
            if x^bx<x: x^=bx; y^=by
        if x!=0 or y!=0: return False
    return len(red)
G=gens(); PIs=[lineperm(M) for M in G]
print('linear on labels (rank):',[solveA(p) for p in PIs])
# orbits of directions under group generated by G
Hn=[np.array(h) for h in H]
def canon(v):
    v=tuple(v); return v if next(c for c in v if c)>0 else tuple(-np.array(v))
hid={canon(h):i for i,h in enumerate(H)}
orb=[-1]*len(H); k=0
for i in range(len(H)):
    if orb[i]>=0: continue
    st=[i]; orb[i]=k
    while st:
        j=st.pop()
        for M in G:
            jj=hid[canon(M@np.array(H[j]))]
            if orb[jj]<0: orb[jj]=k; st.append(jj)
    k+=1
from collections import Counter
reps={}
for i,o in enumerate(orb): reps.setdefault(o,i)
print('orbits',k,[(len(off(H[reps[o]])),c) for o,c in sorted(Counter(orb).items())])
json.dump([reps[o] for o in sorted(reps)],open('reps.json','w'))
