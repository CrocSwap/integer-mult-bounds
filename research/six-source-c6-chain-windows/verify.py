#!/usr/bin/env python3
"""Exact chain windows for the c=6 six-source diagonal s + t = 39.

Standard library only.  Every scientific gate raises SystemExit, so running
with -O cannot silence a failure.  Loop bounds: every loop ranges over a
constant-size range or over a finite set built from constants.  The census has
77,220 weight-3 states with 4 <= s <= 18; partial coordinate enumeration has
at most 10**6 entries because column_options() has ten choices.  No recursion.

Interface (cited, not re-proved): the merged package
research/six-source-c6-centre-classification defines floor words on k = 6
sources at c = 6, the prefix counts q_t, and the weight-3 mask condition.
Usage: verify.py [--print-witnesses]
"""

import hashlib
import itertools
import json
import sys
from pathlib import Path

C = 6
K = 6
LENGTH = 36
PAIR_SUM = 39
TOP = 18
LOW = 4
MID = 9
ALLOWED = (0, 1, 6, 7, 12)
PKG = Path(__file__).resolve().parent
ROOT = PKG.parents[1]

# Cited words.  CONTROL_T1 is printed in open PR #7099; the two CENTRE words
# are printed in the merged centre-classification README.
CONTROL_T1 = "012334500112234455345554432211002103"
CENTRE_SEP3 = "333333444444555555012000001111122222"
CENTRE_09 = "333333012000001111122222444444555555"

# Witnesses generated by witness_words() and re-checked literally from the
# strings alone.  Key: sorted S(18).  Value: (first window index s0, word).
WITNESS = {
    (0, 1, 7, 7, 12, 12): (13, '344444455555533222123220330000011111'),
    (0, 6, 7, 7, 7, 12): (8, '345555554433222111234111220334400000'),
    (1, 1, 1, 12, 12, 12): (18, '333333444444555555012000001111122222'),
    (1, 1, 6, 7, 12, 12): (13, '344444455555533222013222330000011111'),
    (1, 6, 6, 7, 7, 12): (8, '345555554433222111034111222334400000'),
    (6, 6, 6, 7, 7, 7): (4, '345554433222111000345000111222334455'),
}
# Word with weight-3 at (0,9) and at every s in [8, 18].
WITNESS_09 = '345555552443322111234111223344000000'


def require(ok, message):
    if not ok:
        raise SystemExit("FAIL: " + message)


def weight3(sv):
    """Weight-3 mask: all entries in {0,1,6,7,12}, exactly three in {1,7}."""
    return all(x in ALLOWED for x in sv) and sum(1 for x in sv if x % C == 1) == 3


def column_options():
    """(q_j, t_j) pairs with q <= t <= 6 and q + t in ALLOWED."""
    return [(q, t) for t in range(C + 1) for q in range(t + 1) if q + t in ALLOWED]


def static_states(s):
    """All weight-3 diagonal states (q_s, q_{39-s}) with q_s <= q_{39-s} <= 6."""
    opts = column_options()
    parts = [((), 0, 0, 0)]
    for _ in range(K):
        grown = []
        for cols, sq, st, ones in parts:
            for q, t in opts:
                nsq, nst = sq + q, st + t
                nones = ones + ((q + t) % C == 1)
                if nsq <= s and nst <= PAIR_SUM - s and nones <= 3:
                    grown.append((cols + ((q, t),), nsq, nst, nones))
        parts = grown
    out = []
    for cols, sq, st, ones in parts:
        if sq == s and st == PAIR_SUM - s and ones == 3:
            out.append((tuple(c[0] for c in cols), tuple(c[1] for c in cols)))
    return sorted(out)


def diag_sum(state):
    return tuple(a + b for a, b in zip(state[0], state[1]))


def lows(state):
    return sum(1 for x in diag_sum(state) if x <= 1)


def highs(state):
    return sum(1 for x in diag_sum(state) if x == 12)


def base_vector(state):
    return tuple(C * (x // C) for x in diag_sum(state))


def successors(state, next_layer):
    """States at s+1 reached by early letter w_s = a and late letter w_{38-s} = b."""
    q, t = state
    found = []
    for a in range(K):
        qa = q[:a] + (q[a] + 1,) + q[a + 1:]
        for b in range(K):
            if t[b] == 0:
                continue
            tb = t[:b] + (t[b] - 1,) + t[b + 1:]
            if (qa, tb) in next_layer:
                found.append((qa, tb))
    return sorted(found)


def build_layers():
    return {s: static_states(s) for s in range(LOW, TOP + 1)}


def build_successors(layers):
    sets = {s: set(v) for s, v in layers.items()}
    return {s: {x: successors(x, sets[s + 1]) for x in layers[s]} for s in range(LOW, TOP)}


def reach_masks(layers, succ, require_09=False):
    """reach[s][x]: bit i set iff top state i is joined to x by weight-3 steps.

    With require_09, states at s = 9 whose q_9 is not weight-3 reach nothing.
    """
    top_index = {x: i for i, x in enumerate(layers[TOP])}
    reach = {TOP: {x: 1 << i for x, i in top_index.items()}}
    for s in range(TOP - 1, LOW - 1, -1):
        layer = {}
        for x in layers[s]:
            mask = 0
            for y in succ[s][x]:
                mask |= reach[s + 1][y]
            if require_09 and s == MID and not weight3(x[0]):
                mask = 0
            layer[x] = mask
        reach[s] = layer
    return reach, top_index


def check_lemma_a(layers, succ):
    """Every legal step between weight-3 states keeps all bases 6*floor(S/6)."""
    steps = 0
    for s in range(LOW, TOP):
        for x in layers[s]:
            for y in succ[s][x]:
                require(base_vector(x) == base_vector(y), "base changed at s=%d" % s)
                steps += 1
    return steps


def check_static_bound(layers):
    """5*lows <= s-3, highs == lows, and the first s carrying L lows is 3+5L."""
    first = {}
    for s in range(LOW, TOP + 1):
        for x in layers[s]:
            low = lows(x)
            require(highs(x) == low, "highs != lows at s=%d" % s)
            require(C * low <= s and 5 * low <= s - 3, "bound violated at s=%d" % s)
            first[low] = min(first.get(low, s), s)
    require(first == {0: 4, 1: 8, 2: 13, 3: 18}, "first appearance %r" % (first,))
    return first


def popcount(n):
    return bin(n).count("1")


def family_masks(layers, top_index):
    groups = {}
    for x in layers[TOP]:
        groups.setdefault(tuple(sorted(diag_sum(x))), []).append(top_index[x])
    masks = {f: sum(1 << i for i in idx) for f, idx in groups.items()}
    return masks, {f: len(idx) for f, idx in groups.items()}


def window_table(layers, reach, masks):
    """Per family: lows, first window start, start/end/joined counts there."""
    table = {}
    for fam, mask in sorted(masks.items()):
        low = sum(1 for v in fam if v <= 1)
        per_s0 = {}
        for s0 in range(LOW, TOP + 1):
            joined = sum(popcount(reach[s0][x] & mask) for x in layers[s0])
            starts = sum(1 for x in layers[s0] if reach[s0][x] & mask)
            per_s0[s0] = (starts, joined)
        first = min(s for s, v in per_s0.items() if v[1] > 0)
        require(first == max(LOW, 3 + 5 * low), "window start %r %d" % (fam, first))
        require(all(per_s0[s][1] == 0 for s in range(LOW, first)), "gap %r" % (fam,))
        require(all(per_s0[s][1] > 0 for s in range(first, TOP + 1)), "hole %r" % (fam,))
        table[fam] = (low, first, per_s0[first][0], popcount(mask), per_s0[first][1])
    return table


def forward_joined(layers, succ, s0, top_index):
    """Second method: forward closure from each start; end-index sets per start."""
    result = {}
    for x in layers[s0]:
        frontier = {x}
        for s in range(s0, TOP):
            frontier = {y for z in frontier for y in succ[s][z]}
        result[x] = {top_index[y] for y in frontier}
    return result


def check_forward(layers, succ, top_index, masks, table):
    """The forward closure reproduces every joined-pair count at the first window."""
    for fam, row in table.items():
        s0 = row[1]
        ends = forward_joined(layers, succ, s0, top_index)
        bits = {i for i in range(len(layers[TOP])) if masks[fam] >> i & 1}
        joined = sum(len(e & bits) for e in ends.values())
        starts = sum(1 for e in ends.values() if e & bits)
        require((starts, joined) == (row[2], row[4]), "forward mismatch %r" % (fam,))
    return len(table)


def pick_chain(layers, succ, reach, s0, mask):
    """Lexicographically first chain of states from s0 to s = 18 inside `mask`."""
    starts = [x for x in layers[s0] if reach[s0][x] & mask]
    require(bool(starts), "no start state at s0=%d" % s0)
    chain = [starts[0]]
    for s in range(s0, TOP):
        nxt = [y for y in succ[s][chain[-1]] if reach[s + 1][y] & mask]
        require(bool(nxt), "chain stuck at s=%d" % s)
        chain.append(nxt[0])
    return chain


def chain_to_word(chain, s0):
    """Lift a state chain to a 36-letter floor word (ascending order outside it)."""
    word = [None] * LENGTH
    q0, t0 = chain[0]
    pos = 0
    for letter in range(K):
        for _ in range(q0[letter]):
            word[pos] = letter
            pos += 1
    for i in range(len(chain) - 1):
        s = s0 + i
        (q, t), (q2, t2) = chain[i], chain[i + 1]
        word[s] = [j for j in range(K) if q2[j] != q[j]][0]
        word[38 - s] = [j for j in range(K) if t2[j] != t[j]][0]
    qt, tt = chain[-1]
    pos = TOP
    for letter in range(K):
        for _ in range(tt[letter] - qt[letter]):
            word[pos] = letter
            pos += 1
    pos = PAIR_SUM - s0
    for letter in range(K):
        for _ in range(C - t0[letter]):
            word[pos] = letter
            pos += 1
    require(all(x is not None for x in word), "word has holes")
    return "".join(str(x) for x in word)


def counts(word, n):
    return tuple(word[:n].count(j) for j in range(K))


def check_word(text, s0, want_09=False):
    """Literal check of a floor word; returns the sorted diagonal sum at s = 18."""
    require(len(text) == LENGTH, "length %d" % len(text))
    word = [int(ch) for ch in text]
    require(all(0 <= x < K for x in word), "letter out of range")
    require(all(word.count(j) == C for j in range(K)), "not a floor word")
    for s in range(s0, TOP + 1):
        sv = tuple(a + b for a, b in zip(counts(word, s), counts(word, PAIR_SUM - s)))
        require(weight3(sv), "not weight-3 at s=%d" % s)
    if want_09:
        require(weight3(counts(word, MID)), "(0,9) is not weight-3")
    top = tuple(a + b for a, b in zip(counts(word, TOP), counts(word, PAIR_SUM - TOP)))
    return tuple(sorted(top))


def rejects(text, s0, want_09=False):
    try:
        check_word(text, s0, want_09)
    except SystemExit:
        return True
    return False


def witness_words(layers, succ, reach, masks, table):
    """Deterministic witnesses: one per family, plus one with (0,9) weight-3."""
    words = {}
    for fam, row in sorted(table.items()):
        chain = pick_chain(layers, succ, reach, row[1], masks[fam])
        words[fam] = (row[1], chain_to_word(chain, row[1]))
    everything = (1 << len(layers[TOP])) - 1
    filtered, _ = reach_masks(layers, succ, require_09=True)
    return words, chain_to_word(pick_chain(layers, succ, filtered, 8, everything), 8), filtered


def check_threshold(layers, filtered):
    """(0,9) weight-3 together with weight-3 on [s0,18] needs s0 >= 8."""
    nine = {v for v in itertools.product(range(C + 1), repeat=K) if sum(v) == MID and weight3(v)}
    require(len(nine) == 60 and nine == set(itertools.permutations((1, 1, 1, 6, 0, 0))), "(0,9) shapes")
    for x in layers[MID]:
        if x[0] in nine:
            require(lows(x) == 1, "(0,9)-shaped state with lows != 1")
    starts = {s0: sum(1 for x in layers[s0] if filtered[s0][x]) for s0 in range(LOW, MID + 1)}
    require(all(starts[s0] == 0 for s0 in range(LOW, 8)), "threshold: chain below 8")
    require(starts[8] > 0 and starts[9] > 0, "threshold: no chain at 8 and 9")
    return starts


def check_witnesses(generated, generated_09):
    """Stored witnesses equal the generated ones and pass the literal checks."""
    require(WITNESS == generated and WITNESS_09 == generated_09, "stored witnesses differ")
    for fam, (s0, word) in WITNESS.items():
        require(check_word(word, s0) == fam, "witness family %r" % (fam,))
        if s0 > LOW:
            require(rejects(word, s0 - 1), "witness extends below window %r" % (fam,))
    for s0 in range(8, TOP + 1):
        check_word(WITNESS_09, s0, want_09=True)
    require(rejects(WITNESS_09, 7, want_09=True), "(0,9) witness must fail at s=7")
    readme = (PKG / "README.md").read_text(encoding="utf-8")
    for fam, (s0, word) in WITNESS.items():
        require(word in readme, "README lacks witness %r" % (fam,))
    require(WITNESS_09 in readme, "README lacks the (0,9) witness")
    return len(WITNESS) + 1


def check_sources():
    sources = json.loads((PKG / "SOURCES.json").read_text(encoding="utf-8"))
    checked = 0
    for row in sources["files"]:
        if row["usage"] != "input":
            continue
        data = (ROOT / row["path"]).read_bytes()
        require(hashlib.sha256(data).hexdigest() == row["sha256"], "pin " + row["path"])
        text = data.decode("utf-8")
        for anchor in ("{0,1,6,7,12}", "weight-3 mask", CENTRE_SEP3, CENTRE_09):
            require(anchor in text, "anchor %r missing in %s" % (anchor, row["path"]))
        checked += 1
    require(checked == 1, "expected exactly one live input")
    return checked


def check_controls(layers):
    require(check_word(CONTROL_T1, LOW) == (6, 6, 6, 7, 7, 7), "cited T1 word")
    require(check_word(CENTRE_SEP3, TOP) == (1, 1, 1, 12, 12, 12), "cited separation-3 word")
    require(rejects(CENTRE_SEP3, TOP - 1), "separation-3 word must fail at s=17")
    require(weight3(counts([int(c) for c in CENTRE_09], MID)), "cited (0,9) word")
    require(rejects(CONTROL_T1[:-1], LOW), "35 letters must be rejected")
    require(rejects(CONTROL_T1[:-1] + "4", LOW), "a seventh copy must be rejected")
    require(rejects(CONTROL_T1, LOW, want_09=True), "T1 word has no weight-3 (0,9)")
    require(len(layers[TOP]) == 700, "top layer size")
    return 7


def run(print_witnesses):
    inputs = check_sources()
    layers = build_layers()
    total = sum(len(v) for v in layers.values())
    succ = build_successors(layers)
    steps = check_lemma_a(layers, succ)
    first = check_static_bound(layers)
    reach, top_index = reach_masks(layers, succ)
    masks, sizes = family_masks(layers, top_index)
    require(sorted(sizes.values()) == [20, 20, 120, 180, 180, 180], "family sizes")
    table = window_table(layers, reach, masks)
    forward = check_forward(layers, succ, top_index, masks, table)
    words, word_09, filtered = witness_words(layers, succ, reach, masks, table)
    starts = check_threshold(layers, filtered)
    if print_witnesses:
        print("WITNESS = {")
        for fam, value in sorted(words.items()):
            print("    %r: %r," % (fam, value))
        print("}")
        print("WITNESS_09 = %r" % word_09)
        return 0
    stored = check_witnesses(words, word_09)
    controls = check_controls(layers)
    joined = [table[f][4] for f in sorted(table)]
    print("PASS_SIX_SOURCE_C6_CHAIN_WINDOWS states=%d steps=%d first=%s joined=%s forward=%d "
          "starts09=%s witnesses=%d controls=%d inputs=%d" % (
              total, steps, sorted(first.items()), joined, forward,
              [starts[s] for s in range(LOW, MID + 1)], stored, controls, inputs))
    return 0


if __name__ == "__main__":
    sys.exit(run("--print-witnesses" in sys.argv))
