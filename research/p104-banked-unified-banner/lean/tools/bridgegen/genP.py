if 'ph' in args:
    s = HDR % 'chunk combination lemmas' + 'import Nov15.Bridge7761R4\n' + ''.join('import Nov15.Bridge7761PS%s\n' % c for c in 'abcdefg') + 'import Nov15.Bridge7761PB\n'
    s += ''.join('import Nov15.Bridge7761PC%d\nimport Nov15.Bridge7761PO%d\n' % (b, b) for b in range(NBLK))
    s += 'namespace Bridge7761\nopen BridgeP\n'
    for nm, fam, n, N, ws in [('SF', 'sF', 90, len(FF), 'FBW'), ('SR', 'sR', 8, len(RJ), 'RKW'), ('SO', 'sO', 29, len(OJ), 'OFW')]:
        s += 'theorem all%s : ∀ i, i < %d → chk%s (min 1500 (%d - 1500 * i)) (1500 * i) (%s.getD i 0) = true := by\n  intro i hi; interval_cases i\n  exacts [%s]\n' % (nm, n, nm, N, ws, ', '.join('%s_%d' % (fam, i) for i in range(n)))
    def chain(name, stmt, chunks_, thm, lim):
        out = 'theorem %s : ∀ k, k < %d → %s k = true := by\n  intro k hk\n' % (name, lim, stmt)
        for idx, (a, n) in enumerate(chunks_):
            ex = 'exact List.all_eq_true.1 %s k (List.mem_range\'_1.2 ⟨by omega, by omega⟩)' % (thm % a)
            if idx < len(chunks_) - 1:
                out += '  by_cases h%d : k < %d\n  · %s\n' % (idx, a + n, ex)
            else:
                out += '  %s\n' % ex
        return out
    s += chain('allB', 'chkB', wchunks(BW, int(KV.get('wb', 12000))), 'cB_%d', NB)
    s += chain('allOB', 'chkOB', wchunks(OW, int(KV.get('wo', 8000))), 'cOB_%d', NF)
    for b in range(NBLK):
        s += chain('allC%d' % b, '(chkBank %d QT%d)' % (W * b, b), wchunks(BW, int(KV.get('wc', 12000))), 'cC%d_%%d' % b, NB)
        s += chain('allO%d' % b, '(chkOut %d QT%d)' % (W * b, b), wchunks(OW, int(KV.get('wo', 8000))), 'cO%d_%%d' % b, NF)
    s += 'end Bridge7761\n'
    open(OUTD + 'Bridge7761PH.lean', 'w').write(s); print('PH', len(s))
