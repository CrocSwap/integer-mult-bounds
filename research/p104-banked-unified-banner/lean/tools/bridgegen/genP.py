# Generator (our code): packed per-bank proof data for hO (outVec Recipe7761 .. = O7761).
import os as _os
_HERE=_os.path.dirname(_os.path.abspath(__file__))
# BRIDGE_OUT: a COPY of ../../Nov15 (read for inputs, overwritten with outputs); BRIDGE_GRAPH: final7761.json.gz from apply.py
OUTD=_os.environ['BRIDGE_OUT'].rstrip('/')+'/'
BG=_HERE+'/'
# usage: python3 genP.py [pd] [pq] [ps] [pb] [pc] [po]
import gzip, json, sys, re
from fractions import Fraction as F
from math import lcm
sys.set_int_max_str_digits(0)
W = 256; NBLK = 5; WB = 72
args = sys.argv[1:]

g = json.loads(gzip.decompress(open(_os.environ['BRIDGE_GRAPH'], 'rb').read()))
first = g['first_output']; sched = g['schedule']
forms = {k: [(d, F(c)) for d, c in f] for k, f in g['forms']}
bsched = [k for k in sched if k < first]; assert len(bsched) == 5746
pos = {k: i for i, k in enumerate(bsched)}
NB = 5746; NF = 1262
def encQ(c):
    assert -32768 < c.numerator < 32768 and c.denominator < 65536
    return (c.numerator + 32768) | (c.denominator << 16)
FF = []; FC = []; FB = []; RJ = []; RC = []; RK = []; OJ = []; OC = []; OF = []; outorder = []
for k in sched:
    if k < first:
        for d, c in forms[k]:
            if d < 0: FF.append(~d); FC.append(encQ(c)); FB.append(pos[k])
            else: RJ.append(pos[d]); RC.append(encQ(c)); RK.append(pos[k])
    else:
        outorder.append(k - first)
        for d, c in forms[k]:
            OJ.append(pos[d]); OC.append(encQ(c)); OF.append(k - first)
rj = json.load(open(BG + 'recipe.json'))
assert (rj['NF'], rj['NR'], rj['NO']) == (len(FF), len(RJ), len(OJ))
assert len(outorder) == NF and sorted(outorder) == list(range(NF))
def nz(s): return (s % 65536) - 32768
def dz(s): return s // 65536
def sl(P, w, i): return (P >> (w * i)) & ((1 << w) - 1)
g1d = open(OUTD + 'Bridge7761G1D.lean').read()
def hexc(name): return int(re.search(r'def %s : Nat := 0x([0-9a-f]+)' % name, g1d).group(1), 16)
ODK = hexc('ODK'); OPK = hexc('OPK'); PIK = hexc('PIK')
# check our chunk words equal the R4D ones (spot check by regenerating chunk 0)
def pack(xs, w):
    v = 0
    for x in reversed(xs): assert 0 <= x < (1 << w); v = (v << w) | x
    return v

# per-bank term ranges (contiguous: FB, RK nondecreasing)
assert all(FB[i] <= FB[i+1] for i in range(len(FB)-1)) and all(RK[i] <= RK[i+1] for i in range(len(RK)-1))
SF = [0] * (NB + 1); SR = [0] * (NB + 1)
for k in range(NB + 1):
    pass
import bisect
SF = [bisect.bisect_left(FB, k) for k in range(NB + 1)]
SR = [bisect.bisect_left(RK, k) for k in range(NB + 1)]
SG = [0] * NF
for p, f in enumerate(outorder): SG[f] = p
TU = outorder[:]
OPOS = [SG[f] for f in OF]; assert all(OPOS[i] <= OPOS[i+1] for i in range(len(OPOS)-1))
SO = [bisect.bisect_left(OPOS, p) for p in range(NF + 1)]
q = lambda s: F(nz(s), dz(s))
# scales
DK = [0] * NB
for k in range(NB):
    DK[k] = lcm(1, *[q(FC[t]).denominator for t in range(SF[k], SF[k+1])],
                *[(q(RC[t]) / DK[RJ[t]]).denominator for t in range(SR[k], SR[k+1])])
def mfz(k, t): m = DK[k] * q(FC[t]); assert m.denominator == 1; return int(m)
def mrz(k, t): m = DK[k] * q(RC[t]) / DK[RJ[t]]; assert m.denominator == 1; return int(m)
BK = [0] * NB
for k in range(NB):
    BK[k] = sum(abs(mfz(k, t)) for t in range(SF[k], SF[k+1])) + sum(abs(mrz(k, t)) * BK[RJ[t]] for t in range(SR[k], SR[k+1]))
ddv = lambda f: q(sl(ODK, 32, f)); oov = lambda f: q(sl(OPK, 32, f)); pip = lambda f: sl(PIK, 11, f)
DF = [0] * NF
for f in range(NF):
    p = SG[f]
    DF[f] = lcm(1, ddv(f).denominator, oov(f).denominator, *[(q(OC[t]) / DK[OJ[t]]).denominator for t in range(SO[p], SO[p+1])])
def moz(f, t): m = DF[f] * q(OC[t]) / DK[OJ[t]]; assert m.denominator == 1; return int(m)
OB = []
for f in range(NF):
    p = SG[f]
    OB.append(sum(abs(moz(f, t)) * BK[OJ[t]] for t in range(SO[p], SO[p+1])) + abs(DF[f] * ddv(f)) + abs(DF[f] * oov(f)))
print('DK bits', max(DK).bit_length(), 'DF bits', max(DF).bit_length(), 'BK bits', max(BK).bit_length(), 'OB bits', int(max(OB)).bit_length())
assert max(OB) < 2 ** WB and max(DK) < 2 ** 32 and max(DF) < 2 ** 40 and max(BK) < 2 ** 48

def hexn(v): return '0x%x' % v
HDR = '-- generated by bridgegen/genP.py : %s\n'

if 'pd' in args:
    s = HDR % 'tables and checkers for the packed proof of hO' + 'import Nov15.Bridge7761PBT\n' + ''.join('import Nov15.Bridge7761R4D%s\n' % c for c in 'abcdefghi') + 'import Nov15.Bridge7761G1D\nnamespace Bridge7761\nopen BridgeP\n'
    for nm, arr, w in [('SFK', SF, 18), ('SRK', SR, 14), ('SOK', SO, 16), ('SGK', SG, 11), ('TUK', TU, 11), ('DKK', DK, 32), ("DFK", DF, 40), ('BKK', BK, 48)]:
        s += 'def %s : Nat := %s\n' % (nm, hexn(pack(arr, w)))
    s += open(BG + 'genP_pd.lean').read()
    def tree(names, depth):
        m = 1 << depth; v = names + ['0'] * (m - len(names))
        def tr(il):
            if len(il) == 1: return 'BT.lf %s' % v[il[0]]
            return 'BT.nd (%s) (%s)' % (tr(il[0::2]), tr(il[1::2]))
        return tr(list(range(m)))
    for nm, n in [('FF', 90), ('FC', 90), ('FB', 90), ('RJ', 8), ('RC', 8), ('RK', 8), ('OJ', 29), ('OC', 29), ('OF', 29)]:
        d = (n - 1).bit_length()
        s += 'noncomputable def %sT : BT Nat := %s\n' % (nm, tree(['%s_%d' % (nm, i) for i in range(n)], d))
    s += open(BG + 'genP_pd2.lean').read()
    s += 'end Bridge7761\n'
    open(OUTD + 'Bridge7761PD.lean', 'w').write(s); print('PD', len(s))

# block values
def blockQ(b):
    b0 = W * b; Q = [0] * NB
    for k in range(NB):
        v = 0
        for t in range(SF[k], SF[k+1]):
            gg = FF[t]
            if b0 <= gg < b0 + W: v += mfz(k, t) << (WB * (gg - b0))
        for t in range(SR[k], SR[k+1]): v += mrz(k, t) * Q[RJ[t]]
        Q[k] = v
    return Q

if 'pq' in args:
    for b in range(NBLK):
        b0 = W * b; Q = blockQ(b)
        s = HDR % ('packed scaled bank forms, block %d (columns %d..%d), straight-line' % (b, b0, b0 + W - 1)) + 'import Nov15.Bridge7761PBT\nnamespace Bridge7761\nopen BridgeP\nnoncomputable section\n'
        for k in range(NB):
            pos_ = []; neg_ = []
            for t in range(SF[k], SF[k+1]):
                gg = FF[t]
                if b0 <= gg < b0 + W:
                    m = mfz(k, t); sh = WB * (gg - b0)
                    (pos_ if m > 0 else neg_).append('%d <<< %d' % (abs(m), sh))
            terms = []
            if pos_: terms.append('Int.ofNat (%s)' % ' + '.join(pos_))
            if neg_: terms.append('- Int.ofNat (%s)' % ' + '.join(neg_))
            for t in range(SR[k], SR[k+1]):
                terms.append('(%d) * q%d_%d' % (mrz(k, t), b, RJ[t]))
            body = ' + '.join(terms) if terms else '0'
            body = body.replace('+ - ', '- ')
            if body.startswith('- '): body = '0 ' + body
            s += 'def q%d_%d : Int := %s\n' % (b, k, body)
        m = 1 << 13
        def tr(il):
            if len(il) == 1: return 'BT.lf %s' % ('q%d_%d' % (b, il[0]) if il[0] < NB else '0')
            return 'BT.nd (%s) (%s)' % (tr(il[0::2]), tr(il[1::2]))
        s += 'def QT%d : BT Int := %s\nend\nend Bridge7761\n' % (b, tr(list(range(m))))
        open(OUTD + 'Bridge7761PQ%d.lean' % b, 'w').write(s); print('PQ', b, len(s))
        json.dump({'sum': str(sum(Q))}, open(BG + 'pq%d.json' % b, 'w'))

def chunks(n, size):
    return [(a, min(size, n - a)) for a in range(0, n, size)]
def wchunks(wts, cap):
    out = []; a = 0; acc = 0
    for i, w in enumerate(wts):
        if acc + w > cap and i > a: out.append((a, i - a)); a = i; acc = 0
        acc += w
    out.append((a, len(wts) - a)); return out
KV = dict(a.split('=') for a in args if '=' in a)
BW = [SF[k+1] - SF[k] + 3 * (SR[k+1] - SR[k]) + 1 for k in range(NB)]
OW = [SO[p+1] - SO[p] + 1 for p in range(NF)]

if 'ps' in args:
    items = [('sF_%d : chkSF %d %d FB_%d' % (i, min(1500, len(FF) - 1500 * i), 1500 * i, i)) for i in range(90)]
    items += [('sR_%d : chkSR %d %d RK_%d' % (i, min(1500, len(RJ) - 1500 * i), 1500 * i, i)) for i in range(8)]
    items += [('sO_%d : chkSO %d %d OF_%d' % (i, min(1500, len(OJ) - 1500 * i), 1500 * i, i)) for i in range(29)]
    PSN = 'abcdefgh'
    for fi in range(0, len(items), 20):
        s = HDR % 'slice checks (owner of every term lies in its start-table slice)' + 'import Nov15.Bridge7761PD\nnamespace Bridge7761\n'
        for it in items[fi:fi+20]: s += 'theorem %s = true := by decide +kernel\n' % it
        s += 'end Bridge7761\n'
        open(OUTD + 'Bridge7761PS%s.lean' % PSN[fi // 20], 'w').write(s)
    print('PS files', (len(items) + 19) // 20)

if 'pb' in args:
    CB = int(dict(a.split('=') for a in args if '=' in a).get('cb', 500))
    s = HDR % 'once-checks: divisibility of all multipliers, beta recursion, output bounds' + 'import Nov15.Bridge7761PD\nnamespace Bridge7761\n'
    names = []
    for a, n in wchunks(BW, int(KV.get('wb', 12000))):
        s += 'theorem cB_%d : (List.range\' %d %d).all chkB = true := by decide +kernel\n' % (a, a, n); names.append(('cB_%d' % a, a, n))
    onames = []
    for a, n in wchunks(OW, int(KV.get('wo', 8000))):
        s += 'theorem cOB_%d : (List.range\' %d %d).all chkOB = true := by decide +kernel\n' % (a, a, n); onames.append(('cOB_%d' % a, a, n))
