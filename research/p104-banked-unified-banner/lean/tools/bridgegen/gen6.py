# Bridge generator (our code): packed chart tables (basis 16-bit slots, pivots 4-bit slots, 9 slots per chart) -> Bridge7761R1D.lean
import os as _os
_HERE=_os.path.dirname(_os.path.abspath(__file__))
# BRIDGE_OUT: a COPY of ../../Nov15 (read for inputs, overwritten with outputs); BRIDGE_GRAPH: final7761.json.gz from apply.py
OUTD=_os.environ['BRIDGE_OUT'].rstrip('/')+'/'
BG=_HERE+'/'
import re
s=open(OUTD+'Bridge7761D1.lean').read()
def get(name):
    body=re.search(r'def %s : List \(List ℕ\) := (.*)\n'%name,s).group(1)
    return [[int(x) for x in re.findall(r'\d+',r)] for r in re.findall(r'\[([^\[\]]*)\]',body[1:-1])]
B=get('chBasis'); P=get('chPiv'); assert len(B)==len(P)==1099
def pack(xs,w):
    v=0
    for x in reversed(xs): assert 0<=x<(1<<w); v=(v<<w)|x
    return v
bs=[];ps=[]
for b,p in zip(B,P):
    assert len(b)==len(p)<=9 and all(x>0 for x in b)
    bs+=b+[0]*(9-len(b)); ps+=p+[0]*(9-len(p))
out='-- generated by bridgegen/gen6.py packed chart tables of #7761\nnamespace Bridge7761\ndef BASK : Nat := 0x%x\ndef PVK : Nat := 0x%x\nend Bridge7761\n'%(pack(bs,16),pack(ps,4))
open(OUTD+'Bridge7761R1D.lean','w').write(out); print('ok',len(out))

# ================= recipe data (--recipe) =================
import sys
if '--recipe' in sys.argv:
    import gzip, json
    from fractions import Fraction
    g=json.loads(gzip.decompress(open(_os.environ['BRIDGE_GRAPH'],'rb').read()))
    first=g['first_output']; sched=g['schedule']
    forms={k:[(d,Fraction(c)) for d,c in f] for k,f in g['forms']}
    bsched=[k for k in sched if k<first]; assert len(bsched)==5746
    pos={k:i for i,k in enumerate(bsched)}
    NB=5746
    def encQ(c):
        assert -32768<c.numerator<32768 and c.denominator<65536
        return (c.numerator+32768)|(c.denominator<<16)
    FF=[];FC=[];FB=[];RJ=[];RC=[];RK=[];OJ=[];OC=[];OF=[]
    for k in sched:
        if k<first:
            for d,c in forms[k]:
                if d<0: FF.append(~d);FC.append(encQ(c));FB.append(pos[k])
                else: RJ.append(pos[d]);RC.append(encQ(c));RK.append(pos[k]); assert pos[d]<pos[k]
        else:
            for d,c in forms[k]:
                assert d>=0; OJ.append(pos[d]);OC.append(encQ(c));OF.append(k-first)
    print('NF',len(FF),'NR',len(RJ),'NO',len(OJ))
    CH=1500
    chunks=[]   # (tag, idx, n, [(name,w,vals)])
    def mk(tag,arrs):
        N=len(arrs[0][2]); out=[]
        for i in range(0,N,CH):
            out.append((tag,i//CH,min(CH,N-i),[(nm,w,v[i:i+CH]) for nm,w,v in arrs]))
        return out
    chunks+=mk('F',[('FF',11,FF),('FC',32,FC),('FB',13,FB)])
    chunks+=mk('R',[('RJ',13,RJ),('RC',32,RC),('RK',13,RK)])
    chunks+=mk('O',[('OJ',13,OJ),('OC',32,OC),('OF',11,OF)])
    PER=15
    files=[chunks[i:i+PER] for i in range(0,len(chunks),PER)]
    for fi,fc in enumerate(files):
        nm='Bridge7761R4D%s'%'abcdefghijklmnop'[fi]
        s='-- generated by bridgegen/gen6.py --recipe recipe chunks of #7761 (1500 terms/chunk; coefficients encQ = (num+2^15)|(den<<16))\nnamespace Bridge7761\n'
        for tag,i,n,arrs in fc:
            for a,w,v in arrs: s+='def %s_%d : Nat := 0x%x\n'%(a,i,pack(v,w))
        open(OUTD+nm+'.lean','w').write(s+'end Bridge7761\n')
    json.dump(dict(NF=len(FF),NR=len(RJ),NO=len(OJ),files=len(files),chunks=[(t,i,n) for t,i,n,_ in chunks]),open(BG+'recipe.json','w'))
    print('files',len(files))
