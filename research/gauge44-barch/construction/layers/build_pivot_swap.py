"""Cost-neutral pivot-role swaps inside existing entrance-kernel families.  Apache-2.0.  Prepared with Claude Code
assistance.  The pivot/donor role exchange follows PR266's "pivot role is moved" idea (bit side), applied here to the
complex supplier's multicut kernel families (PR568 build_multicut_kernels.py shape).

A kernel family on the input word is an entering helper p (start_extra E) together with the gates that read p at frame
E before any other touch of p:  d += c_d * p @E  (d a helper or, in B, a target).  They cancel p's complete dirty
response:  col(p) + sum_d c_d * col_{g_d}(d) = 0, where col_{g}(d) is d's suffix response from gate g on.

Swap to the new pivot x (a helper donor of the family with exactly one family gate g_x = x's FIRST touch, and no other
touch of x up to the family's last gate):
    g_x :  x += c_x p   ->   p += (1/c_x) x
    g_d :  d += c_d p   ->   d += (c_d/c_x) x          (d != x, same position and frame E)
    start_extra: p -> x (same E); cleanup regenerated by the inherited inverse rule.
Exactness (PROOF-NOTE-PIVOT.md): x holds only its initial dirt at every rewritten gate, and p holds only its initial dirt
until g_x, so x's new response is col(x) + col(p)/c_x + sum_d (c_d/c_x) col_{g_d}(d) = (c_x col(x) + col(p) +
sum_d c_d col_{g_d}(d)) / c_x = 0, because col(x) = col_{g_x}(x).  This script checks it by exact rational replay anyway.
Cost: the frame chains of p and x are exchanged (p now climbs [] -> E at g_x where x did; x starts at E where p did), so
gk_word.profile and the width multiset are unchanged; both are asserted.

Recipe: {input_content_sha256, output_content_sha256, swaps: [{pivot, new_pivot, entrance, gates: [{part, index,
before, after}]}]}.  Every expected `after` gate is recomputed from the rule above and must equal the recipe.

Negative controls (--controls): mutated recipes/words that must be rejected at pinned reasons:
  * nonzero response: another family gate's rescaled coefficient has the wrong sign;
  * wrong pivot coefficient: g_x's new coefficient doubled;
  * wrong entrance: the recipe's entrance is not p's start_extra;
  * non-family gate: a recipe gate whose `before` is not the word's gate;
  * new pivot touched in the window: x replaced by a family donor that is not a fresh helper (a target donor, or the
    first other helper donor when the family has no target donor).
"""
from pathlib import Path
from collections import Counter
from fractions import Fraction as Q
import argparse, copy, gzip, hashlib, json, sys
assert __debug__, 'Assertions required'
ap = argparse.ArgumentParser()
for k in ('--input', '--recipe', '--gk-dir', '--out'): ap.add_argument(k, type=Path, required=True)
a = ap.parse_args(); assert not a.out.exists()
sys.path.insert(0, str(a.gk_dir)); import gk_word as G, gk_common as C
G.V = C.V = 112; G.DATA = C.DATA = 7168
V = 112
raw = json.loads(gzip.decompress(a.input.read_bytes())); recipe = json.loads(a.recipe.read_text())
enc = lambda x: json.dumps(x, sort_keys=True, separators=(',', ':')).encode(); sha = lambda x: hashlib.sha256(x).hexdigest()
regs = lambda e: [e[1]] + ([e[2]] if e[0] == 'add' else [])
inv_rule = lambda w: [G.inverse(e, G.FULL) for e in reversed(w['A'] + w['B']) if not V <= e[1] < 2 * V]
dy = lambda q: q != 0 and q.denominator & (q.denominator - 1) == 0


def response(w, h):
    rows = {}
    def get(r): return rows.setdefault(r, {r: Q(1)})
    for e in w['A'] + w['cut'] + w['B']:
        if e[0] == 'scale':
            q = Q(e[2], e[3]); rows[e[1]] = {j: q * x for j, x in get(e[1]).items()}
        else:
            t, s = e[1], e[2]; q = Q(e[3], e[4]); src = get(s); tgt = get(t)
            for j, x in list(src.items()):
                z = tgt.get(j, Q(0)) + q * x
                if z: tgt[j] = z
                else: tgt.pop(j, None)
    return {r: rows[r][h] for r in range(V, 2 * V) if r in rows and rows[r].get(h)}


def build(w0, rec):
    w = copy.deepcopy(w0); n = 2 * V + w['report']['R']
    assert w['cleanup'] == inv_rule(w), 'input cleanup is not the inherited inverse rule'
    P0 = G.profile(w); W0 = Counter(C.widths_of(w))
    AB = [('A', i) for i in range(len(w['A']))] + [('B', i) for i in range(len(w['B']))]
    pos = {k: j for j, k in enumerate(AB)}
    seen = set(); receipts = []; rules = []
    for s in rec['swaps']:
        p, x, E = s['pivot'], s['new_pivot'], s['entrance']
        assert 2 * V <= p < n and w['start_extra'].get(str(p)) == E, 'pivot is not an entering helper at the entrance'
        assert 2 * V <= x < n and x not in w['centers'], 'new pivot must be a helper'
        assert str(x) not in w['start_extra'], 'new pivot already entering'
        assert not {p, x} & seen, 'registers shared between swaps'; seen |= {p, x}
        gs = s['gates']; ks = [pos[(g['part'], g['index'])] for g in gs]
        assert ks == sorted(ks) and len(set(ks)) == len(ks)
        for g in gs:
            e = w[g['part']][g['index']]
            assert e == g['before'], 'recipe gate is not the word gate'
            assert e[0] == 'add' and e[2] == p and e[1] != p and list(e[-1]) == list(E), 'not a family gate (d += c p @E)'
        touch = lambda r: [j for j, (part, i) in enumerate(AB) if r in regs(w[part][i])]
        tp = touch(p); assert tp[:len(ks)] == ks, 'family gates must be all touches of the pivot up to its first other touch'
        gx = [k for k, g in zip(ks, gs) if g['before'][1] == x]; assert len(gx) == 1, 'new pivot must have exactly one family gate'
        tx = touch(x); assert tx[0] == gx[0], 'new pivot touched before its family gate'
        assert len(tx) == 1 or tx[1] > ks[-1], 'new pivot touched inside the family window'
        cx = Q(*[g['before'][3:5] for g in gs if g['before'][1] == x][0])
        for g in gs:
            d, f = g['before'][1], g['after']
            assert f[0] == 'add' and list(f[-1]) == list(E) and (f[1:3] == [p, x] if d == x else f[1:3] == [d, x]), 'after-gate shape'
            assert dy(Q(f[3], f[4])), 'non-dyadic swapped coefficient'
            w[g['part']][g['index']] = f
            q = 1 / cx if d == x else Q(g['before'][3], g['before'][4]) / cx
            rules.append((f, ['add', p, x, q.numerator, q.denominator, list(E)] if d == x else ['add', d, x, q.numerator, q.denominator, list(E)]))
        w['start_extra'][str(x)] = w['start_extra'].pop(str(p))
        receipts.append(dict(pivot=p, new_pivot=x, entrance=E, family_gates=len(gs)))
    w['cleanup'] = inv_rule(w)
    for s in rec['swaps']:
        assert not response(w, s['new_pivot']), 'new pivot dirty response not zero'
    assert all(f == e for f, e in rules), 'recipe after-gate is not the swap rule'
    P1 = G.profile(w)
    assert P1 == P0, 'paid profile not identical (swap is not cost-neutral)'
    assert Counter(C.widths_of(w)) == W0, 'width multiset changed'
    w['report']['local_profile'] = {str(k): v for k, v in sorted(P1.items())}
    w['report']['local_rank_mass'] = sum(k * v for k, v in P1.items())
    return w, receipts


assert sha(enc(raw)) == recipe['input_content_sha256'], 'input content'
out, receipts = build(raw, recipe)
o = enc(out); assert sha(o) == recipe['output_content_sha256'], sha(o)

# ---- negative controls -------------------------------------------------------------------------------------------
WHY = dict(nonzero='new pivot dirty response not zero', coef='new pivot dirty response not zero',
           entrance='paid profile not identical', nonfamily='recipe gate is not the word gate',
           window='new pivot')
controls = []


def reject(name, mut, why):
    r = copy.deepcopy(recipe); w = copy.deepcopy(raw)
    mut(r, w)
    try:
        build(w, r)
    except AssertionError as ex:
        msg = str(ex)
        assert why in msg, ('control rejected for the wrong reason', name, msg)
        controls.append(dict(control=name, reason=msg)); return
    raise AssertionError('control accepted: ' + name)


for si, s in enumerate(recipe['swaps']):
    x = s['new_pivot']; tag = '%d->%d' % (s['pivot'], x)
    def m_other(r, w, si=si):
        g = [g for g in r['swaps'][si]['gates'] if g['before'][1] != r['swaps'][si]['new_pivot']][0]
        g['after'] = list(g['after']); g['after'][3] = -g['after'][3]
    def m_coef(r, w, si=si):
        g = [g for g in r['swaps'][si]['gates'] if g['before'][1] == r['swaps'][si]['new_pivot']][0]
        g['after'] = list(g['after']); g['after'][3] *= 2
    def m_nonfamily(r, w, si=si):
        g = r['swaps'][si]['gates'][0]; g['before'] = list(g['before']); g['before'][3] = -g['before'][3]
    def m_window(r, w, si=si):
        S = r['swaps'][si]; S['new_pivot'] = [g['before'][1] for g in S['gates'] if g['before'][1] != S['new_pivot']][0]
    def m_entrance(r, w, si=si):
        S = r['swaps'][si]; S['entrance'] = [1]
    reject('swap %s: another family gate keeps a wrong (unrescaled-sign) coefficient: new pivot response nonzero' % tag, m_other, WHY['nonzero'])
    reject('swap %s: wrong pivot coefficient (1/c doubled) on the new pivot gate' % tag, m_coef, WHY['coef'])
    reject('swap %s: non-family gate in the recipe' % tag, m_nonfamily, WHY['nonfamily'])
    reject('swap %s: new pivot replaced by another family donor (not a fresh cold helper)' % tag, m_window, WHY['window'])
    reject('swap %s: wrong entrance frame for the moved entrance' % tag, m_entrance, 'pivot is not an entering helper at the entrance')
controls_receipt = list(controls)

a.out.mkdir(parents=True); (a.out / 'FULL-WORD.json.gz').write_bytes(gzip.compress(o, mtime=0))
rc = dict(status='PASS_COST_NEUTRAL_PIVOT_SWAPS', input_content_sha256=recipe['input_content_sha256'],
          output_content_sha256=recipe['output_content_sha256'], swaps=receipts, local_profile=out['report']['local_profile'],
          negative_controls_rejected=controls_receipt,
          scope='Exact family rewrite, exact zero dirty response of every new pivot, identical paid profile and widths, '
                'regenerated inverse-rule cleanup.  Native all-column audit, HPE/cold steps and global checks remain separate.')
(a.out / 'PIVOT-SWAP.json').write_text(json.dumps(rc, indent=2, sort_keys=True) + '\n', newline='\n'); print(json.dumps(rc, indent=2))
