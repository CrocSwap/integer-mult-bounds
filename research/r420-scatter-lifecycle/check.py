#!/usr/bin/env python3
"""Bind the R420 literals, then compile four fresh Lean modules offline."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import resource
import shutil
import signal
import subprocess
import time

PACKAGE = Path(__file__).resolve().parent
STANDARD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}
CORE_MANIFEST_SHA = "2c27354193fc7b11079b61116ab8e9c80485903845bda48ddf3c66057fed2cb1"
SOURCE_PATHS = [
    "research/e8-bit-r420/data/bitE8mut-r420.json.gz",
    "research/e8-bit-carrier-skeleton/code/bit/export_records.py",
    "research/lean-current-r420-boundary-interfaces/OFFICIAL_CORE_MANIFEST.json",
]
REQUIRED_PROBES = {
    "BitXorTargetTranslation": ("CurrentMain.BitXor", [
        "run_shift", "run_off_target", "target_identity", "erased_eq_of_agree_off_target"]),
    "BitCopyScatterWindow": ("CurrentMain.BitCopyScatter", [
        "copy_at_temp", "clear_at_temp", "window_eq_clear_direct", "runWindows_eq_clear_direct",
        "directWindows_untouched", "runWindows_independent_of_temp"]),
    "R420ScatterData": ("CurrentMain.R420ScatterData", ["source_shape"]),
    "R420ScatterLifecycle": ("CurrentMain.R420ScatterLifecycle", [
        "original_excludes_temp", "exporter_window_binding", "raw_shape", "raw_domains",
        "source_rows_no_duplicates", "decode_roundtrip", "ordered_window_binding",
        "decoded_bounds", "windows_well_formed", "windows_nonempty", "exact_lifecycle",
        "final_temp_zero", "original_coordinate", "original_registers",
        "sources_helpers_preserved", "incoming_temp_independent", "clean_temp_restored"]),
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_inventory(manifest):
    require([row["path"] for row in manifest["repository_inputs"]] == SOURCE_PATHS,
            "exact three-source inventory required")
    require(manifest["word"] == SOURCE_PATHS[0] and manifest["core_manifest"] == SOURCE_PATHS[2],
            "fixed word/core manifest paths required")
    require([row["name"] for row in manifest["modules"]] == list(REQUIRED_PROBES),
            "exact four-module inventory required")
    for row in manifest["modules"]:
        namespace, names = REQUIRED_PROBES[row["name"]]
        require(row["probes"] == [namespace + "." + name for name in names],
                f"required probe inventory: {row['name']}")


def render_data(word):
    """Exact source projection; no repository generator or supplier is run."""
    require(type(word["v"]) is int and word["v"] == 120, "R420 port count")
    require(type(word["R"]) is int and word["R"] == 420, "R420 helper count")
    require(len(word["ret"]) == 9 and len(word["scatter"]) == 120, "R420 shape")
    require(all(type(x) is int and 240 <= x < 660 for x in word["ret"]), "retained domain")
    require(all(type(row) is list and all(type(k) is int and 0 <= k < 9 for k in row)
                for row in word["scatter"]), "scatter domain")
    nat_list = lambda xs: "[" + ", ".join(map(str, xs)) + "]"
    rows = ",\n  ".join(nat_list(row) for row in word["scatter"])
    windows = [(q, [120 + t for t, row in enumerate(word["scatter"]) if k in row])
               for k, q in enumerate(word["ret"])]
    window_rows = ",\n  ".join(f"({q}, {nat_list(ds)})" for q, ds in windows)
    return ("import Init\n\n"
            "/-! Literal projection of the pinned PR543 R420 word. Generated by check.py's\n"
            "render_data; checked against the source before every build. Supplier:\n"
            "eumemic, with substantial Anthropic Claude assistance; Apache-2.0. -/\n"
            "namespace CurrentMain.R420ScatterData\n"
            "set_option Elab.async false\n"
            f"def v : Nat := {word['v']}\n"
            f"def R : Nat := {word['R']}\n"
            f"def ret : List Nat := {nat_list(word['ret'])}\n"
            f"def scatter : List (List Nat) := [{rows}]\n\n"
            "/-- Exact retained-major membership loop in the pinned record exporter. -/\n"
            f"def exportedWindows : List (Nat × List Nat) := [{window_rows}]\n\n"
            "theorem source_shape : v = 120 ∧ R = 420 ∧ 2*v+R = 660 ∧\n"
            "    ret.length = 9 ∧ scatter.length = 120 ∧\n"
            "    (scatter.map List.length).foldl Nat.add 0 = 568 := by decide +kernel\n"
            "end CurrentMain.R420ScatterData\n"
            "#print axioms CurrentMain.R420ScatterData.source_shape\n")


def bind(repo):
    manifest = json.loads((PACKAGE / "MANIFEST.json").read_text())
    validate_inventory(manifest)
    for item in manifest["repository_inputs"]:
        require(sha(repo / item["path"]) == item["sha256"], f"source hash: {item['path']}")
    raw = gzip.decompress((repo / manifest["word"]).read_bytes())
    require(hashlib.sha256(raw).hexdigest() == manifest["decoded_word_sha256"], "decoded word hash")
    word = json.loads(raw)
    require((PACKAGE / "R420ScatterData.lean").read_bytes() == render_data(word).encode(),
            "R420 Lean data differs from exact source projection")
    for module in manifest["modules"]:
        path = PACKAGE / (module["name"] + ".lean")
        require(sha(path) == module["sha256"], f"Lean source hash: {path.name}")
        source = path.read_text()
        require(re.findall(r"^import (\S+)$", source, re.M) == module["imports"],
                f"imports: {path.name}")
        require(re.findall(r"^#print axioms (\S+)$", source, re.M) == module["probes"],
                f"probe declarations: {path.name}")
    return manifest


def check_core(repo, lean, manifest):
    core_path = repo / manifest["core_manifest"]
    require(sha(core_path) == CORE_MANIFEST_SHA, "official core manifest")
    core = json.loads(core_path.read_text())
    root = lean.parent.parent
    require(sha(lean) == core["binary"]["sha256"], "official Lean binary")
    require(len(core["ordered_modules"]) == 317, "official Init closure size")
    for module in core["ordered_modules"]:
        for kind in ("source", "object"):
            record = module[kind]
            path = root / record["file"]
            require(path.stat().st_size == record["bytes"] and sha(path) == record["sha256"],
                    f"official core {kind}: {module['module']}")


def limits():
    os.setsid()
    resource.setrlimit(resource.RLIMIT_AS, (4 * 1024**3, 4 * 1024**3))
    resource.setrlimit(resource.RLIMIT_CPU, (60, 62))


def compile_modules(lean, build, manifest):
    validate_inventory(manifest)
    require(not build.exists(), "build directory must not already exist")
    build.mkdir(parents=True)
    env = {"PATH": str(lean.parent) + ":/usr/bin:/bin", "HOME": str(build),
           "LEAN_PATH": str(build), "LANG": "C.UTF-8"}
    receipts = []
    for module in manifest["modules"]:
        name = module["name"]
        source = build / (name + ".lean")
        shutil.copyfile(PACKAGE / source.name, source)
        started = time.monotonic()
        command = [str(lean), "-s", "65536", "-j", "1", "-o", name + ".olean", source.name]
        with (build / (name + ".log")).open("wb") as log:
            process = subprocess.Popen(command, cwd=build, env=env, stdout=log,
                                       stderr=subprocess.STDOUT, preexec_fn=limits)
            try:
                code = process.wait(timeout=60)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
                raise ValueError(f"Lean timed out: {name}") from None
        elapsed = time.monotonic() - started
        text = (build / (name + ".log")).read_text()
        require(code == 0, f"Lean failed: {name}; see {name}.log")
        records = []
        pattern = r"'([^']+)' (?:does not depend on any axioms|depends on axioms: \[([^\]]*)\])"
        for match in re.finditer(pattern, text, re.S):
            axioms = [] if match[2] is None else [x.strip() for x in match[2].split(",") if x.strip()]
            require(set(axioms) <= STANDARD_AXIOMS, f"nonstandard axioms: {match[1]}")
            records.append({"declaration": match[1], "axioms": axioms})
        require([x["declaration"] for x in records] == module["probes"], f"missing/reordered probes: {name}")
        require(sha(source) == module["sha256"], f"changed build source: {name}")
        receipts.append({"module": name, "seconds": round(elapsed, 6), "probes": records,
                         "source_sha256": sha(source), "object_sha256": sha(build / (name + ".olean")),
                         "log_sha256": sha(build / (name + ".log"))})
    return receipts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=PACKAGE.parents[1])
    parser.add_argument("--lean", type=Path)
    parser.add_argument("--build-dir", type=Path)
    parser.add_argument("--bind-only", action="store_true")
    args = parser.parse_args()
    manifest = bind(args.repo.resolve())
    if args.bind_only:
        print("PASS source binding; Lean compilation not requested")
        return
    require(args.lean is not None and args.build_dir is not None, "--lean and --build-dir required")
    lean, build = args.lean.resolve(), args.build_dir.resolve()
    check_core(args.repo.resolve(), lean, manifest)
    receipts = compile_modules(lean, build, manifest)
    bind(args.repo.resolve())
    check_core(args.repo.resolve(), lean, manifest)
    result = {"status": "PASS", "lean": "4.21.0", "modules": len(receipts),
              "probes": sum(len(row["probes"]) for row in receipts),
              "manifest_sha256": sha(PACKAGE / "MANIFEST.json"), "receipts": receipts}
    (build / "RESULT.json").write_text(json.dumps(result, indent=2) + "\n")
    print(f"PASS {result['modules']} fresh modules, {result['probes']} standard-axiom probes")


if __name__ == "__main__":
    main()
