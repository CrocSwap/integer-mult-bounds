import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]


def require(ok, message):
    if not ok:
        raise ValueError(message)


def main():
    pins=json.loads((HERE/'SOURCES.json').read_text())
    with tempfile.TemporaryDirectory(prefix='consolidation path with spaces ') as temp:
        root=Path(temp)/'checkout'
        for rel in pins['files']:
            dst=root/rel;dst.parent.mkdir(parents=True,exist_ok=True)
            shutil.copyfile(ROOT/rel,dst)
        target=root/HERE.relative_to(ROOT)
        shutil.copytree(HERE,target,ignore=shutil.ignore_patterns('__pycache__'))
        script=target/'verify.py'
        # Minimal source closure, no .git, no cached intermediate outputs.
        good=subprocess.run([sys.executable,'-I','-B',str(script)],capture_output=True,text=True)
        require(good.returncode==0,good.stdout+good.stderr)
        def reject(args, text):
            result=subprocess.run([sys.executable,*args],capture_output=True,text=True)
            require(result.returncode!=0 and text in result.stderr, 'wrong rejection: '+result.stderr)
        reject(['-I','-O','-B',str(script)],'Run without -O')
        existing=Path(temp)/'existing';existing.mkdir();marker=existing/'marker';marker.write_text('preserve')
        reject(['-I','-B',str(script),'--out',str(existing)],'FileExistsError')
        require(marker.read_text()=='preserve','existing output was changed')
        source=root/'research/r420-compensation-basis/verify.py'
        original=source.read_bytes();source.write_bytes(original+b'\n# mutation\n')
        reject(['-I','-B',str(script)],'source changed:')
        source.write_bytes(original)
        recipe=target/'DECODER-RECIPE.json';original=recipe.read_bytes()
        data=json.loads(original);data['selected_indices'].pop();recipe.write_text(json.dumps(data))
        reject(['-I','-B',str(script)],'decoder subset')
        recipe.write_bytes(original)
        # A stale combined receipt cannot be silently regenerated by normal replay.
        result=target/'EXPECTED.json';data=json.loads(result.read_text());data['bit']['saved_additions']+=1
        result.write_text(json.dumps(data))
        reject(['-I','-B',str(script)],'frozen consolidation receipt differs')
    print('PASS_CONSOLIDATION_PACKAGE relocation=1 rejections=5')


if __name__=='__main__':
    main()
