"""Faster coversat encoding (copy of ../new/coversat.py + symmetry breaking).  Writes DIMACS; solve with kissat.
usage: gen.py UNIT T c1,c2,.. OUT.cnf [flags]
flags: --sb (old SB, always wanted) --C7  --zero --rref --lex  --donly (C2 on D_j x D_j; SAT-control)  --lexlen N  --noC4

SOUNDNESS NOTES
(Z) zero: U^j_t is only ever used when t in R_j, W^j_s only when s in A_j (every C2 clause is conditioned on r/a);
    forcing U^j_t=0 for t notin R_j and W^j_s=0 for s notin A_j just fixes unused variables, so any model stays a model.
(R) rref: the pairs (U,W) with U W^T = M restricted to R x A form an orbit family under GL(c,2): (U g, W g^{-T}).
    Let r=rank W (as |A| x c, i.e. dim of the row space of W^T, the span of the c rows w_k=(W[s][k])_s).  Replace W by the
    canonical basis: W^T -> reduced row echelon form E=g W^T where g in GL(c,2) (RREF is unique per row space; its nonzero
    rows come first), U -> U g^{-1}.  Then U W^T unchanged.  So every solution has an equivalent one with W^T in RREF
    (nonzero rows first, pivots strictly increasing, pivot columns zero in other rows).  Rows k of zero W^T-rows give
    columns of U that multiply 0, so we also fix U[.][k]=0 there.  Every rank<=c matrix has a factorisation with c columns,
    and a minimal one (rank=r) has W of rank r, so after RREF + zero-padding it is of this canonical form.
    (Not every matrix has exactly one such form if W has rank > rank M, but at least one exists: sound.)
(L) lex: B-problem invariant under any automorphism w of the orthogonality graph on lines (W(D_n) acts through reflections;
    all clauses refer only to orthogonality) acting on the line index of every variable.  After sorting totals by size
    (old SB, invariant under w), choose in each orbit under W the solution whose vector X = (x[t][0] t=0..v-1, x[t][1].., ..)
    is lexicographically MAXIMAL.  Then X >=lex w.X for all w in W.  This also implies x[0][0]=1 (D_0 non-empty), consistent
    with the old rule 'line 0 in D_0'.  Totals permutation is not used here (sizes already sorted)."""
import io, contextlib, sys, itertools, os
import numpy as np
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','lib'))
with contextlib.redirect_stdout(io.StringIO()):
    import ade
from pysat.formula import IDPool, CNF
from pysat.card import CardEnc, EncType
UNITS={'D4':lambda:ade.D(4),'D5':lambda:ade.D(5),'D6':lambda:ade.D(6),'E6':ade.E6b,'E7':ade.E7}
F=set(a for a in sys.argv if a.startswith('--'))

def weyl_perms(L):
    """group generated by reflections, as permutations of lines (tuples)"""
    v=len(L); key={}
    for i,r in enumerate(L): key[tuple(np.rint(r*2).astype(int))]=i; key[tuple(np.rint(-r*2).astype(int))]=i
    gens=[]
    for r in L:
        r=np.array(r,float); n=r@r
        p=tuple(key[tuple(np.rint((x-2*(x@r)/n*r)*2).astype(int))] for x in L)
        gens.append(p)
    gens=set(gens); idp=tuple(range(v)); G={idp}; fr=[idp]
    while fr:
        nf=[]
        for g in fr:
            for h in gens:
                k=tuple(h[g[i]] for i in range(v))
                if k not in G: G.add(k); nf.append(k)
        fr=nf
    return sorted(G)

def build(nm,T,cs):
    L=UNITS[nm](); G=np.rint(L@L.T).astype(int); v=len(L)
    orth=lambda a,b: a!=b and G[a,b]==0
    pool=IDPool(); cl=[]; Bv={}
    for t in range(v):
        for s in range(v):
            if orth(t,s): Bv[t,s]=pool.id(('B',t,s))
    X=[[pool.id(('x',t,j)) for j in range(T)] for t in range(v)]
    for t in range(v): cl.append(X[t][:])
    def xor_eq_cond(lits,rhs_lit,cond):
        acc=lits[0]
        for x in lits[1:]:
            y=pool.id(('xr',len(cl),acc,x)); cl.extend([[-y,acc,x],[-y,-acc,-x],[y,-acc,x],[y,acc,-x]]); acc=y
        neg=[-c for c in cond]
        if rhs_lit is None: cl.append(neg+[-acc])
        elif rhs_lit is True: cl.append(neg+[acc])
        else: cl.append(neg+[-acc,rhs_lit]); cl.append(neg+[acc,-rhs_lit])
    Rv=[[pool.id(('r',t,j)) for j in range(T)] for t in range(v)]
    Av=[[pool.id(('a',t,j)) for j in range(T)] for t in range(v)]
    for t in range(v):
        for j in range(T):
            cl.extend([[-X[t][j],Rv[t][j]],[-X[t][j],Av[t][j]],[X[t][j],-Rv[t][j],-Av[t][j]]])
    for j in range(T):
        c=cs[j]
        U=[[pool.id(('U',j,t,k)) for k in range(c)] for t in range(v)]
        W=[[pool.id(('W',j,t,k)) for k in range(c)] for t in range(v)]
        if '--zero' in F:
            for t in range(v):
                for k in range(c): cl.append([-U[t][k],Rv[t][j]]); cl.append([-W[t][k],Av[t][j]])
        if '--rref' in F:
            # row k of W^T is (W[s][k])_s.  pre[k][s] = OR_{s'<=s} W[s'][k]
            pre=[[pool.id(('pre',j,k,s)) for s in range(v)] for k in range(c)]
            for k in range(c):
                for s in range(v):
                    w=W[s][k]; p=pre[k][s]
                    if s==0: cl.extend([[-w,p],[w,-p]])
                    else: cl.extend([[-w,p],[-pre[k][s-1],p],[-p,w,pre[k][s-1]]])
                    # pivot at s: w & not pre[k][s-1]  => other rows have 0 at s
                    for k2 in range(c):
                        if k2==k: continue
                        cl.append([-w]+([pre[k][s-1]] if s>0 else [])+[-W[s][k2]])
                # zero rows => U column zero
                for t in range(v): cl.append([-U[t][k],pre[k][v-1]])
            for k in range(c-1):
                for s in range(v):
                    # pivot_{k+1} <= s  =>  pivot_k <= s-1
                    if s==0: cl.append([-pre[k+1][0]])
                    else: cl.append([-pre[k+1][s],pre[k][s-1]])
        for t in range(v):
            for s in range(v):
                prods=[]
                for k in range(c):
                    p=pool.id(('p',j,t,s,k)); cl.extend([[-p,U[t][k]],[-p,W[s][k]],[p,-U[t][k],-W[s][k]]]); prods.append(p)
                if '--donly' in F: cond=[X[t][j]] if t==s else [X[t][j],X[s][j]]
                else: cond=[X[t][j]] if t==s else [Rv[t][j],Av[s][j]]
                rhs=True if t==s else (Bv[t,s] if orth(t,s) else None)
                xor_eq_cond(prods,rhs,cond)
    for (t,s),b in Bv.items():
        y=[pool.id(('y',t,s,j)) for j in range(T)]
        for j in range(T): cl.extend([[-y[j],Rv[t][j]],[-y[j],Av[s][j]],[y[j],-Rv[t][j],-Av[s][j]]])
        for j in range(T): cl.append([-b,-y[j]]+[y[k] for k in range(T) if k!=j])
    if '--C7' in F:
        EP={}; EL={}
        def eP(a,b):
            k=(min(a,b),max(a,b))
            if k not in EP:
                e=EP[k]=pool.id(('eP',)+k)
                for (x,y) in ((a,b),(b,a)):
                    if (x,y) in Bv: cl.append([-e,-Bv[x,y]])
                for j in range(T): cl.extend([[-e,-Rv[a][j],Rv[b][j]],[-e,Rv[a][j],-Rv[b][j]]])
            return EP[k]
        def eL(a,b):
            k=(min(a,b),max(a,b))
            if k not in EL:
                e=EL[k]=pool.id(('eL',)+k)
                for (x,y) in ((a,b),(b,a)):
                    if (x,y) in Bv: cl.append([-e,-Bv[x,y]])
                for j in range(T): cl.extend([[-e,-Av[a][j],Av[b][j]],[-e,Av[a][j],-Av[b][j]]])
            return EL[k]
        for t,t2 in itertools.combinations(range(v),2):
            cs_=[s_ for s_ in range(v) if (t,s_) in Bv and (t2,s_) in Bv]
            for s1,s2 in itertools.combinations(cs_,2):
                cl.append([-Bv[t,s1],-Bv[t,s2],-Bv[t2,s1],-Bv[t2,s2],eP(t,t2),eL(s1,s2)])
    for S in itertools.combinations(range(v),T+1):
        if not all(orth(a,b) for a,b in itertools.combinations(S,2)): continue
        for o in itertools.permutations(S):
            cl.append([-Bv[o[a],o[b]] for a in range(T+1) for b in range(a+1,T+1)])
    if '--noC4' not in F:
        for S in itertools.combinations(range(v),T):
            if not all(orth(a,b) for a,b in itertools.combinations(S,2)): continue
            allB=[Bv[a,b] for a in S for b in S if a!=b]
            for j in range(T): cl.append([-x for x in allB]+[X[t][j] for t in S])
    cl.append([X[0][0]])
    if '--sb' in F:
        enc=CardEnc.atleast([X[t][0] for t in range(v)],bound=-(-v//T),vpool=pool,encoding=EncType.seqcounter); cl.extend(enc.clauses)
        for j in range(T-1):
            lits=[X[t][j] for t in range(v)]+[-X[t][j+1] for t in range(v)]
            enc=CardEnc.atleast(lits,bound=v,vpool=pool,encoding=EncType.seqcounter); cl.extend(enc.clauses)
    if '--lex' in F:
        Gp=weyl_perms(L)
        vec=[X[t][j] for j in range(T) for t in range(v)]
        n=len(vec); ll=n
        if '--lexlen' in sys.argv: ll=int(sys.argv[sys.argv.index('--lexlen')+1])
        idx={x:i for i,x in enumerate(vec)}
        nl=0
        for g in Gp:
            if g==tuple(range(v)): continue
            img=[X[g[t]][j] for j in range(T) for t in range(v)]   # (g.X)_i
            prev=None; pos=[i for i in range(min(ll,n)) if img[i]!=vec[i]]
            for q,i in enumerate(pos):
                a,b=vec[i],img[i]
                cl.append(([-prev] if prev else [])+[a,-b])
                if q<len(pos)-1:
                    e=pool.id(('lx',nl,i)); 
                    cl.append([e]+([-prev] if prev else [])+[a,b]); cl.append([e]+([-prev] if prev else [])+[-a,-b]); prev=e
            nl+=1
        print('lex perms',nl,file=sys.stderr)
    return cl,pool,Bv,X,v

if __name__=='__main__':
    nm=sys.argv[1]; T=int(sys.argv[2]); cs=[int(x) for x in sys.argv[3].split(',')]; out=sys.argv[4]
    cl,pool,Bv,X,v=build(nm,T,cs)
    CNF(from_clauses=cl).to_file(out); print(out,'vars',pool.top,'clauses',len(cl))
