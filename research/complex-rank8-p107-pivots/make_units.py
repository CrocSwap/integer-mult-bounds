#!/usr/bin/env python3
"""Census of 5-subsets of P112 under verify.py's generators, a pivot per open orbit, and the generator words of
COVER.json; regenerates UNITS.json and COVER.json, which verify.py rechecks (needs numpy; verify.py does not).

    python3 -I -B research/complex-rank8-p107-pivots/make_units.py --out-dir /new/dir

Method: enumerate the group H generated by the 8 generators (172032 elements) with a BFS tree, so each element
has a word. Label all quadruples by H-orbit with a transporter from the orbit's representative (first in colex
order). A 5-subset c gets the key (j, m): j is the least orbit label among its five sub-quadruples, and m is the
least Stab(rep_j)-orbit point among the images g^-1(c \\ s) over sub-quadruples s with label j, where g carries
rep_j onto s. Two 5-subsets are H-equivalent iff their keys agree. The orbit sizes are checked to sum to
C(112, 5). Unit: the first candidate (quadruple representative + one line) of each open orbit. Pivot: the first
frame inside the live set, in verify.py's frame order, that passes (I3), (I4), gluing and Lemma 9.
"""
import argparse
import itertools
import json
import sys
from math import comb
from multiprocessing import Pool
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import verify as V  # noqa: E402


def closure(gens):
    import numpy as np
    gs = [np.array(g, dtype=np.uint8) for g in gens]
    e = np.arange(V.NL, dtype=np.uint8)
    seen, elems, parent, pgen, frontier = {e.tobytes(): 0}, [e], [-1], [-1], [0]
    while frontier:
        nxt = []
        for n in frontier:
            for gi, g in enumerate(gs):
                q = g[elems[n]]  # apply elems[n], then g
                if q.tobytes() not in seen:
                    seen[q.tobytes()] = len(elems)
                    elems.append(q)
                    parent.append(n)
                    pgen.append(gi)
                    nxt.append(len(elems) - 1)
        frontier = nxt
    return np.array(elems), parent, pgen


def pivot(X):
    live = [i for i in V.P112 if i not in X]
    for F in V.frames_inside(live):
        if V.passes(V.inputs(live, F)):
            return F
    return None


def main():
    import numpy as np
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-dir', required=True)
    ap.add_argument('--jobs', type=int, default=8)
    args = ap.parse_args()
    out = Path(args.out_dir)
    for f in ('UNITS.json', 'COVER.json'):
        if (out / f).exists():
            print(f'refusing to overwrite {out / f}')
            return 2
    gens = V.stabiliser(V.FRAME0)[::V.GEN_STEP]
    E, parent, pgen = closure(gens)
    pos = np.full(V.NL, -1)
    pos[V.P112] = np.arange(112)
    EP = pos[E[:, V.P112]].astype(np.int64)  # H on positions 0..111 of P112
    inv = np.argsort(EP, axis=1)
    elem = {EP[n].astype(np.int8).tobytes(): n for n in range(len(EP))}
    assert len(elem) == len(EP)

    def word(n):
        w = []
        while parent[n] >= 0:
            w.append(pgen[n])
            n = parent[n]
        return w[::-1]

    tab = np.array([[comb(x, j + 1) for j in range(5)] for x in range(112)], dtype=np.int64)
    rank = lambda a: sum(tab[a[:, j], j] for j in range(a.shape[1]))
    subs4 = np.array(list(itertools.combinations(range(112), 4)), dtype=np.int64)
    byrank = np.empty(len(subs4), dtype=np.int64)
    byrank[rank(subs4)] = np.arange(len(subs4))
    lab = np.full(len(subs4), -1, dtype=np.int64)
    tr = np.full(len(subs4), -1, dtype=np.int64)
    reps4 = []
    while (lab < 0).any():
        q = tuple(int(x) for x in subs4[byrank[np.nonzero(lab < 0)[0][0]]])
        rr = rank(np.sort(EP[:, list(q)], axis=1))
        _, first = np.unique(rr, return_index=True)
        lab[rr[first]], tr[rr[first]] = len(reps4), first
        reps4.append(q)
    orbmin, to = [], []
    for q in reps4:
        st = np.nonzero((np.sort(EP[:, list(q)], axis=1) == np.array(q)).all(axis=1))[0]
        orbmin.append(EP[st].min(axis=0))
        to.append(st[EP[st].argmin(axis=0)])

    def canon(c):
        """(key, h) with h in H carrying c onto the key's canonical 5-subset."""
        best = None
        for r in c:
            k = int(rank(np.array([[x for x in c if x != r]]))[0])
            j, g = int(lab[k]), int(tr[k])
            y = int(inv[g][r])
            if best is None or (j, int(orbmin[j][y])) < best[0]:
                best = ((j, int(orbmin[j][y])), g, int(to[j][y]))
        key, g, s = best
        return key, EP[s][inv[g]]

    L = lambda Y: tuple(sorted(V.P112[x] for x in Y))
    frames = [tuple(sorted(int(pos[f]) for f in F)) for F in V.frames_inside(V.P112)]
    inframe = {c for F in frames for c in itertools.combinations(F, 5)}
    cands = sorted({tuple(sorted(q + (x,))) for q in reps4 for x in range(112) if x not in q})
    orbits = {}
    for c in cands:
        orbits.setdefault(canon(c)[0], []).append(c)
    total = sum(len(EP) // int((np.sort(EP[:, list(v[0])], axis=1) == np.array(v[0])).all(axis=1).sum())
                for v in orbits.values())
    assert total == comb(112, 5), total
    open_orbits = sorted((v for v in orbits.values() if v[0] not in inframe), key=lambda v: v[0])
    print(f'{len(reps4)} quadruple orbits; {len(orbits)} 5-subset orbits, sizes sum to C(112,5); '
          f'{len(open_orbits)} open', flush=True)
    names = {v[0]: f'u{n:04d}' for n, v in enumerate(open_orbits, 1)}
    # Level 1: triple-orbit representative + one line -> quadruple representative.
    cover4 = {}
    for c in sorted({tuple(sorted(o[0] + (x,))) for o in V.triple_orbits(gens) for x in V.P112 if x not in o[0]}):
        k = int(rank(np.array([sorted(int(pos[x]) for x in c)]))[0])
        cover4[' '.join(map(str, c))] = [int(lab[k]), word(int(tr[k]))]
    # Level 2: quadruple representative + one line -> unit.
    cover5 = {}
    for v in open_orbits:
        _, hu = canon(v[0])
        for c in v:
            _, hc = canon(c)
            h = np.argsort(hc)[hu]  # hc^-1 after hu: unit -> c
            cover5[' '.join(map(str, L(c)))] = [names[v[0]], word(elem[h.astype(np.int8).tobytes()])]
    with Pool(args.jobs) as pool:
        pivots = pool.map(pivot, [L(v[0]) for v in open_orbits], chunksize=8)
    if any(F is None for F in pivots):
        raise SystemExit('a unit has no passing pivot')
    units = {names[v[0]]: {'quintuple': [V.LINES[i] for i in L(v[0])], 'pivot': [V.LINES[i] for i in F]}
             for v, F in zip(open_orbits, pivots)}
    print(f'{len(units)} units with pivots; {len(cover4)} + {len(cover5)} cover words')
    (out / 'UNITS.json').write_text(json.dumps(units, separators=(',', ':')) + '\n')
    (out / 'COVER.json').write_text(json.dumps({'reps4': [[V.LINES[i] for i in L(r)] for r in reps4],
                                                'cover4': cover4, 'cover5': cover5},
                                               sort_keys=True, separators=(',', ':')) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
