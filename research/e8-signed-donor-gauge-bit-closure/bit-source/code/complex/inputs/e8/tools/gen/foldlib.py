"""Numbers for the rate lemmas of one unit (library; used by crate.py and foldgen.py).  Exact rational
certificates; Lean re-checks all.

One UNIT = one element of the group: W live roles, block list H = {rank: count} (all blocks of the
unit, live and scratch), label dimension m, deficit D = W*m - sum r*H[r].

Table of the generic lemma (Work/FoldRate/Group.lean): fill parameter s, t = 2^s.
  whole-block fact  : (t-1) * M(z) + W * ((m-1)/m)^z + W * (1/m)^z < t * W,   M(z) = sum H[r] (r/m)^z
  whole-block sharp : W <= M(z')                (then the fact fails for EVERY s)
  per-rank fact     : t * W * (m - m^z) < (t-1) * D
"""
from fractions import Fraction
from decimal import Decimal, getcontext
import gen_rates, gen_sharp          # log_upper, log_lower, frac_lean
from gen_rates import frac_lean
getcontext().prec = 80


# bank blocks of the bridged word B_2 beyond `5 * 2v` blocks of rank h-1 (see unit()):
#  B2  (merged idle climbs)        : X1,Y1 = 3 x (h-1), 2h+2;   X2,Y2 = 2h-2, h-1, 2 x (h-1), 4
#  B2t (only the tail of pair 1)   : X1,Y1 = 3 x (h-1), 2h+2;   X2,Y2 = 5 x (h-1), 4
#  B2u (unmerged)                  : every bank role 5 x (h-1), 4
BANK = {
    'B2': [(2, lambda h: h - 1), (2, lambda h: 2 * h - 2), (2, lambda h: 2 * h + 2), (2, lambda h: 4)],
    'B2t': [(6, lambda h: h - 1), (2, lambda h: 2 * h + 2), (2, lambda h: 4)],
    'B2u': [(10, lambda h: h - 1), (4, lambda h: 4)],
    # two more cuts, NOT generated by default (only if the network delivers them):
    #  B2s : X1,Y1 = 3 x (h-1), 2h-2, 4;  X2,Y2 = 2h-2, h-1, 2 x (h-1), 4        (L16: 40380 / 40381)
    #  B2w : X1,Y1 = 5 x (h-1), 4;        X2,Y2 = 2h-2, h-1, 2 x (h-1), 4        (L16: 40017 / 40018)
    'B2s': [(2, lambda h: h - 1), (4, lambda h: 2 * h - 2), (4, lambda h: 4)],
    'B2w': [(6, lambda h: h - 1), (2, lambda h: 2 * h - 2), (4, lambda h: 4)],
}


def moment_dec(H, m, eps):
    z = Decimal(1) - Decimal(eps.numerator) / Decimal(eps.denominator)
    return sum(Decimal(n) * (Decimal(r) / Decimal(m)) ** z for r, n in H.items())


def block_lhs_dec(u, eps, s):
    """(t-1) M + W c - t W   (negative = holds)"""
    t = 2 ** s
    m, W = u['m'], u['W']
    z = Decimal(1) - Decimal(eps.numerator) / Decimal(eps.denominator)
    c = (Decimal(m - 1) / Decimal(m)) ** z + (Decimal(1) / Decimal(m)) ** z
    return (t - 1) * moment_dec(u['H'], m, eps) + W * c - t * W


def rank_lhs_dec(u, eps, s):
    t = 2 ** s
    m, W, D = u['m'], u['W'], u['D']
    z = Decimal(1) - Decimal(eps.numerator) / Decimal(eps.denominator)
    return t * W * (Decimal(m) - Decimal(m) ** z) - (t - 1) * D


def best_units(u, B, s):
    """largest A with the whole-block fact at fill parameter s, the first A' with W <= M (fails at
    every fill), and the same two for per-rank; by high-precision evaluation"""
    def last_true(f):
        lo, hi = 0, 10 ** B
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if f(mid):
                lo = mid
            else:
                hi = mid
        return lo
    A = last_true(lambda a: block_lhs_dec(u, Fraction(a, 10 ** B), s) < 0)
    Af = last_true(lambda a: moment_dec(u['H'], u['m'], Fraction(a, 10 ** B)) < u['W']) + 1
    Ar = last_true(lambda a: rank_lhs_dec(u, Fraction(a, 10 ** B), s) < 0)
    m, W, D = u['m'], u['W'], u['D']
    Arf = last_true(lambda a: W * (Decimal(m) - Decimal(m) ** (Decimal(1) - Decimal(a) / Decimal(10 ** B))) < D) + 1
    return A, Af, Ar, Arf


def ceil_frac(x, G):
    y = x * 10 ** G
    return Fraction(-((-y.numerator) // y.denominator), 10 ** G)


def floor_frac(x, G):
    y = x * 10 ** G
    return Fraction(y.numerator // y.denominator, 10 ** G)


def plan_block(u, A, B, s, Dd=12):
    """upper bounds q of every term T m z r n (unit list) and of the two idle terms, with
    (t-1) sum q + W (qa + qb) < t W checked exactly"""
    eps = Fraction(A, 10 ** B)
    t = 2 ** s
    m, W, H = u['m'], u['W'], u['H']
    rows = []
    for r, n in [(r, H[r]) for r in sorted(H)] + [(m - 1, 1), (1, 1)]:
        L, N = gen_rates.log_upper(m, r, Dd)
        x = eps * L
        assert x <= 1
        val = n * Fraction(r, m) * (1 + x + x * x / 2 + x ** 3 * Fraction(2, 9))
        rows.append([r, n, L, N, val])
    nH = len(H)
    exact = (t - 1) * sum(row[4] for row in rows[:nH]) + W * (rows[nH][4] + rows[nH + 1][4])
    margin = t * W - exact
    if margin <= 0:
        return None
    G = 0
    while Fraction((t - 1) * nH + 2 * W, 10 ** G) > margin / 50:
        G += 1
    for row in rows:
        row.append(ceil_frac(row[4], G))
    tot = (t - 1) * sum(row[5] for row in rows[:nH]) + W * (rows[nH][5] + rows[nH + 1][5])
    assert tot < t * W
    return dict(rows=rows[:nH], idle=rows[nH:], G=G, slack_rel=float(margin / (t * W)))


def plan_sharp(u, A1, B, Dd=12):
    """lower bounds q of every term with sum q >= W"""
    eps = Fraction(A1, 10 ** B)
    m, W, H = u['m'], u['W'], u['H']
    rows = []
    for r in sorted(H):
        n = H[r]
        L, s, nn = gen_sharp.log_lower(m, r, Dd)
        x = eps * L
        rows.append([r, n, L, s, nn, n * Fraction(r, m) * (1 + x + x * x / 2 + x ** 3 / 6)])
    margin = sum(row[5] for row in rows) - W
    if margin < 0:
        return None
    G = 0
    while margin > 0 and Fraction(len(rows), 10 ** G) > margin / 50:
        G += 1
    for row in rows:
        row.append(floor_frac(row[5], G))
    assert sum(row[6] for row in rows) >= W
    return dict(rows=rows, G=G, slack_rel=float(margin / W))


def plan_rank(u, A, B, s, Dd=12):
    """rational upper bound L of log m with t W m (x - x^2/2 + x^3/4) < (t-1) D, x = eps L"""
    eps = Fraction(A, 10 ** B)
    t = 2 ** s
    m, W, D = u['m'], u['W'], u['D']
    L, N = gen_rates.log_upper(m, 1, Dd)
    x = eps * L
    lhs = t * W * m * (x - x * x / 2 + x ** 3 / 4)
    if not (x <= 1 and lhs < (t - 1) * D):
        return None
    return dict(L=L, N=N, slack_rel=float(1 - lhs / ((t - 1) * D)))
