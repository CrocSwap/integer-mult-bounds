#!/usr/bin/env python3
"""Seven orthogonal binary full-guard events lie below the product of their marginals.

Over F_2, let U_1..U_7 be pairwise orthogonal rank-one idempotents on F_2^m and
G uniform in GL_m(F_2).  E_t says every leading principal minor of order 1..m-1
of G(I-U_t)G^-1 is nonzero.  With n = m-1 and X = 2^m, Nick Petalas's PR4275
character law gives the joint probability

    Pr(E_1 ... E_k) = N_n / (2^(kn) prod_{i<k} (X - 2^i)),
    N_n = sum_c (-1)^|c| Z(c)^n = sum_z H[z] z^n,

over zero-diagonal binary k x k matrices c.  The marginal is s_m = 3^n/((X-1)2^n).
This verifier checks, for k = 7 and every m >= 7,

    N_n (X-1)^6 < 3^(7n) prod_{j=1..6} (X - 2^j)         (n = m - 1)

from the exact signed spectrum H of all 2^42 characters.  The spectrum is
regenerated by spectrum.c (orbit-reduced extension enumerator) and compared with
SPECTRUM_K7.txt; the enumerator is validated against labelled brute force
(k <= 5 always, k = 6 with --brute6), the three-state definition, and the
spectra published in the pinned predecessor files for k = 3, 4, 5.

Standard library only; every check raises an explicit exception, so `python -O`
keeps all of them.  A C compiler (cc, gcc or clang) is required.

    python3 verify.py             # full default replay
    python3 verify.py --brute6    # k = 6 labelled brute-force control (2^30 matrices)
    python3 verify.py --labelled7 # k = 7 without orbit reduction (about 4000 core-seconds)
"""
import argparse
import itertools
import math
import os
import pathlib
import random
import re
import shutil
import subprocess
import sys
import tempfile
import time
from fractions import Fraction

PACKAGE = pathlib.Path(__file__).resolve().parent
ROOT = PACKAGE.parent.parent
K = 7
EXACT_N_MIN = 6            # m = 7 is the first dimension holding seven orthogonal requests
EXACT_N_MAX = 400          # exact big-integer comparison for n = EXACT_N_MIN .. EXACT_N_MAX
TAIL_N_MAX = 1000          # bound on the search for the tail threshold
MAX_SHARDS = 4
PINNED = {
    "law": "research/corankone-triple-header-law/PROOF.md",
    "five": "research/five-event-guard-correlation/PROOF.md",
    "four": "research/corankone-four-correlation/PROOF.md",
}


class Failure(Exception):
    """A verification step failed."""


def require(condition, message):
    if not condition:
        raise Failure(message)


def expect_failure(label, function, *args):
    """A control: `function` must raise Failure on the doctored input."""
    try:
        function(*args)
    except Failure:
        return
    raise Failure("control did not reject: " + label)


# ---------------------------------------------------------------- spectrum IO


def parse_spectrum(text):
    """Parse lines 'z count' with strictly increasing z and nonzero counts."""
    spectrum, previous = {}, 0
    for line in text.splitlines():
        fields = line.split(" ")
        require(len(fields) == 2, "malformed spectrum line: %r" % line)
        z, count = int(fields[0]), int(fields[1])
        require(z > previous and count != 0, "spectrum lines must increase with nonzero counts")
        spectrum[z] = count
        previous = z
    return spectrum


def moment(spectrum, n):
    return sum(count * z**n for z, count in spectrum.items())


# ------------------------------------------------- the definition and subsets


def z_literal(arcs, k):
    """Three-state sum over sigma in {0,1,2}^k of (-1)^{arcs from label 1 to label 2}."""
    total = 0
    for sigma in itertools.product(range(3), repeat=k):
        parity = sum(1 for (i, j) in arcs if sigma[i] == 1 and sigma[j] == 2) & 1
        total += -1 if parity else 1
    return total


def z_subset(arcs, k):
    """Subset form: A with even incoming parity outside A, weight 2^(k-|A|)."""
    rows = [0] * k
    for (i, j) in arcs:
        rows[i] |= 1 << j
    mask, total = (1 << k) - 1, 0
    for a in range(1 << k):
        r = 0
        for i in range(k):
            if (a >> i) & 1:
                r ^= rows[i]
        if (r & ~a & mask) == 0:
            total += 1 << (k - bin(a).count("1"))
    return total


def all_arcs(k):
    return [(i, j) for i in range(k) for j in range(k) if i != j]


def definition_spectrum(k):
    """Signed spectrum from the literal three-state definition; also compares the subset form."""
    arcs_all, spectrum = all_arcs(k), {}
    for mask in range(1 << len(arcs_all)):
        arcs = [arcs_all[b] for b in range(len(arcs_all)) if (mask >> b) & 1]
        z = z_literal(arcs, k)
        require(z == z_subset(arcs, k), "subset form differs from the definition at k=%d" % k)
        spectrum[z] = spectrum.get(z, 0) + (-1 if len(arcs) & 1 else 1)
    return {z: v for z, v in sorted(spectrum.items()) if v}


def sampled_definition_check(k, samples, seed):
    """The subset form equals the three-state definition on random characters."""
    rng, arcs_all = random.Random(seed), all_arcs(k)
    for _ in range(samples):
        arcs = [a for a in arcs_all if rng.random() < rng.choice((0.1, 0.3, 0.5))]
        require(z_literal(arcs, k) == z_subset(arcs, k), "subset form differs at k=%d" % k)


# ------------------------------------------------------------ the C enumerator


def find_compiler():
    for name in ("cc", "gcc", "clang"):
        path = shutil.which(name)
        if path:
            return path
    raise Failure("no C compiler (cc, gcc or clang) on PATH")


def build(workdir):
    exe = pathlib.Path(workdir) / "spectrum"
    flags = ["-std=c11", "-O2", "-Wall", "-Wextra", "-Wpedantic", "-Werror"]
    done = subprocess.run([find_compiler()] + flags + ["-o", str(exe), str(PACKAGE / "spectrum.c")],
                          capture_output=True, text=True, timeout=300)
    require(done.returncode == 0, "spectrum.c failed to compile:\n" + done.stderr)
    return exe


def run_spectrum(exe, k, mode, shards=1):
    """Run the enumerator on `shards` processes and add their counts."""
    require(1 <= shards <= 64, "bad shard count")
    procs = [subprocess.Popen([str(exe), str(k), mode, str(s), str(shards)],
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
             for s in range(shards)]
    spectrum, characters = {}, 0
    for proc in procs:
        out, err = proc.communicate(timeout=3600)
        require(proc.returncode == 0, "spectrum %d %s failed: %s" % (k, mode, err))
        found = re.search(r"characters=(\d+)", err)
        require(found is not None, "spectrum printed no character count")
        characters += int(found.group(1))
        for z, count in parse_pairs(out):
            spectrum[z] = spectrum.get(z, 0) + count
    require(characters == 2 ** (k * (k - 1)), "enumerator did not cover every character")
    return {z: v for z, v in sorted(spectrum.items()) if v}


def parse_pairs(text):
    for line in text.splitlines():
        z, count = line.split(" ")
        yield int(z), int(count)


def format_spectrum(spectrum):
    return "".join("%d %d\n" % (z, v) for z, v in sorted(spectrum.items()))


# ---------------------------------------------- published spectra (pinned text)


def pinned_text(key):
    return " ".join((ROOT / PINNED[key]).read_text(encoding="utf-8").split())


def check_pinned_statements(texts):
    """The pinned predecessor files state the facts used as controls."""
    needles = {
        "law": ["C(2,m,k) = 2^(-k(k-1)) sum_c (-1)^(|c|) Z(c)^n",
                "(27^n - 6*21^n + 6*19^n - 6*17^n + 16*15^n - 18*13^n + 9*11^n - 2*9^n) / 64",
                "exists if and only if m >= k + 1"],
        "five": ["N_n = 243^n − 20·189^n + 60·171^n − 40·165^n",
                 "Σ_{z<189} |b_z| = 1,048,555", "max_{z<189} z = 171"],
        "four": ["N_n = 81^n - 12*63^n + R_n", "|R_n| <= 4083*57^n"],
    }
    for key, items in needles.items():
        for needle in items:
            require(needle in texts[key], "pinned %s file lacks: %s" % (key, needle))


def check_published_spectra(spectra):
    """k = 3, 4, 5 spectra against the closed forms in the pinned files."""
    three = {27: 1, 21: -6, 19: 6, 17: -6, 15: 16, 13: -18, 11: 9, 9: -2}
    require(spectra[3] == three, "k=3 spectrum differs from the published closed form")
    h4 = spectra[4]
    below = {z: v for z, v in h4.items() if z < 63}
    require(h4[81] == 1 and h4[63] == -12 and h4[57] == 24, "k=4 top coefficients differ")
    require(sum(abs(v) for v in below.values()) == 4083 and max(below) == 57, "k=4 remainder differs")
    h5 = spectra[5]
    below = {z: v for z, v in h5.items() if z < 189}
    require([h5[z] for z in (243, 189, 171, 165)] == [1, -20, 60, -40], "k=5 top coefficients differ")
    require(sum(abs(v) for v in below.values()) == 1048555 and max(below) == 171, "k=5 remainder differs")


# --------------------------------------------------------- the k = 7 theorem


def check_spectrum_facts(h):
    """Structural facts of the k = 7 spectrum, all read from the table."""
    require(len(h) == 493, "expected 493 nonzero spectrum entries")
    require(sum(h.values()) == 0, "signed multiplicities must sum to zero")
    require(sum(abs(v) for v in h.values()) == 2**42, "absolute multiplicities must sum to 2^42")
    require(h[2187] == 1 and h[1701] == -42 and h[1539] == 210, "top three levels differ")
    rest = {z: v for z, v in h.items() if z < 1539}
    require(max(rest) == 1485 and sum(abs(v) for v in rest.values()) == 2**42 - 253,
            "remainder bounds differ")
    for n in range(7):
        require(moment(h, n) == 0, "N_%d must vanish (binary threshold m >= k+1)" % n)
    walks = moment(h, 7)
    require(walks > 0 and walks % (2**42 * math.factorial(7)) == 0,
            "N_7 must be a positive multiple of 2^42 * 7!")
    return walks // 2**42


def inequality_sides(h, n, k=K):
    x = 2 ** (n + 1)
    right = 3 ** (k * n)
    for j in range(1, k):
        right *= x - 2**j
    return moment(h, n) * (x - 1) ** (k - 1), right


def check_exact_range(h):
    """N_n (X-1)^6 < 3^(7n) prod (X - 2^j) for every EXACT_N_MIN <= n <= EXACT_N_MAX."""
    worst = (0, 1, 0)
    for n in range(EXACT_N_MIN, EXACT_N_MAX + 1):
        left, right = inequality_sides(h, n)
        require(0 <= left < right, "inequality fails at n=%d (m=%d)" % (n, n + 1))
        if left * worst[1] > worst[0] * right:
            worst = (left, right, n)
    return worst


def tail_lemma(h):
    """Constants of the integer tail bound, and the facts it needs."""
    big_a = sum(abs(v) for z, v in h.items() if z < 1539)

    def lam(n):
        return 39 * 1701**n - 210 * 1539**n - big_a * 1485**n

    first = next((n for n in range(1, TAIL_N_MAX) if lam(n) >= 0), None)
    require(first == 188 and lam(187) < 0, "tail threshold is not 188")
    for n in range(first, TAIL_N_MAX):
        require(lam(n) >= 0, "tail lemma lambda(n) < 0 at n=%d" % n)
    for n in range(60):
        gap = lam(n + 1) - 1701 * lam(n)
        require(gap == 210 * 162 * 1539**n + 216 * big_a * 1485**n, "growth identity fails")
    for n in range(first, TAIL_N_MAX):
        bound = 2187**n - 3 * 1701**n
        require(moment(h, n) <= bound, "N_n exceeds 2187^n - 3*1701^n at n=%d" % n)
    return first


def check_closing_inequalities():
    """The two elementary inequalities that finish the tail argument."""
    require((2**8 - 1) * 7**7 > 40 * 9**7, "(2^(n+1)-1)(7/9)^n > 40 fails at n=7")
    for n in range(7, 400):
        require((2 ** (n + 2) - 1) * 7 > 9 * (2 ** (n + 1) - 1), "monotonicity fails at n=%d" % n)
        x = 2 ** (n + 1)
        product = math.prod(x - 2**j for j in range(1, 7))
        require(product >= (x - 1) ** 5 * (x - 121), "Weierstrass bound fails at n=%d" % n)


def check_top_levels(spectra):
    """Observed for k = 4..7: levels 3^k, 7*3^(k-2), 19*3^(k-3), 55*3^(k-4) with
    coefficients 1, -k(k-1), k(k-1)(k-2), -8*C(k,4).  A finite observation, not a theorem."""
    for k in range(4, 8):
        h, top = spectra[k], sorted(spectra[k], reverse=True)[:4]
        levels = [3**k, 7 * 3 ** (k - 2), 19 * 3 ** (k - 3), 55 * 3 ** (k - 4)]
        counts = [1, -k * (k - 1), k * (k - 1) * (k - 2), -8 * math.comb(k, 4)]
        require(top == levels and [h[z] for z in top] == counts, "top levels differ at k=%d" % k)


def asymptotic_check(h):
    """1 - rho_m = 42 (7/9)^(m-1) (1 + O((19/21)^(m-1))) shows in the exact ratios."""
    for n in (100, 400):
        left, right = inequality_sides(h, n)
        gap = Fraction(right - left, right)
        predicted = 42 * Fraction(7, 9) ** n
        require(abs(gap - predicted) * 1000 < predicted, "asymptotic form fails at n=%d" % n)


# --------------------------------------------------------------- the controls


def run_controls(h, spectra):
    bumped = dict(h)
    bumped[1701] += 1
    expect_failure("one-unit arc coefficient", check_spectrum_facts, bumped)
    doubled = dict(h)
    doubled[2187] = 2
    expect_failure("doubled top coefficient", check_exact_range, doubled)
    expect_failure("shifted subset form", lambda: require(
        all(z_subset(a, 3) + 1 == z_literal(a, 3) for a in ([], [(0, 1)], [(0, 1), (1, 2)])),
        "shifted subset form"))
    doctored = dict(spectra[4])
    doctored[57] += 1
    expect_failure("doctored k=4 spectrum", check_published_spectra, {**spectra, 4: doctored})
    texts = {key: pinned_text(key) for key in PINNED}
    texts["five"] = texts["five"].replace("243^n", "244^n")
    expect_failure("altered pinned statement", check_pinned_statements, texts)
    expect_failure("wrong tail threshold", lambda: require(
        (39 * 1701**187 - 210 * 1539**187 - (2**42 - 253) * 1485**187) >= 0, "threshold"))


# ------------------------------------------------------------------- drivers


def shard_count():
    return max(1, min(MAX_SHARDS, os.cpu_count() or 1))


def replay_default():
    started = time.time()
    committed = parse_spectrum((PACKAGE / "SPECTRUM_K7.txt").read_text(encoding="utf-8"))
    texts = {key: pinned_text(key) for key in PINNED}
    check_pinned_statements(texts)
    definition = {k: definition_spectrum(k) for k in (3, 4)}
    for k, samples in ((5, 60), (6, 40), (7, 20)):
        sampled_definition_check(k, samples, seed=k)
    with tempfile.TemporaryDirectory() as workdir:
        exe = build(workdir)
        spectra = {k: run_spectrum(exe, k, "ext") for k in (3, 4, 5, 6)}
        for k in (3, 4, 5):
            require(run_spectrum(exe, k, "brute") == spectra[k], "ext differs from brute at k=%d" % k)
        for k in (3, 4):
            require(definition[k] == spectra[k], "ext differs from the definition at k=%d" % k)
        check_published_spectra(spectra)
        h7 = run_spectrum(exe, K, "ext", shards=shard_count())
    require(h7 == committed, "regenerated k=7 spectrum differs from SPECTRUM_K7.txt")
    walks = check_spectrum_facts(committed)
    worst = check_exact_range(committed)
    first = tail_lemma(committed)
    check_closing_inequalities()
    asymptotic_check(committed)
    check_top_levels({**spectra, K: committed})
    run_controls(committed, spectra)
    print("k=3..6 spectra: %s nonzero entries; ext equals brute at k<=5, definition at k<=4"
          % "/".join(str(len(spectra[k])) for k in (3, 4, 5, 6)))
    print("k=7 spectrum: 493 entries regenerated and equal to SPECTRUM_K7.txt; N_7/2^42 = %d = 7! * %d"
          % (walks, walks // math.factorial(7)))
    print("top four levels checked for k=4..7 (observation, not a theorem)")
    print("exact range n=%d..%d: strict inequality; tightest n=%d, 1 - rho = %.3e"
          % (EXACT_N_MIN, EXACT_N_MAX, worst[2], float(Fraction(worst[1] - worst[0], worst[1]))))
    print("tail: lambda(n) >= 0 from n=%d, so N_n <= 2187^n - 3*1701^n for n >= %d" % (first, first))
    print("elapsed %.1f s" % (time.time() - started))
    print("PASS_SEVEN_EVENT_GUARD_CORRELATION")


def replay_brute6():
    with tempfile.TemporaryDirectory() as workdir:
        exe = build(workdir)
        brute = run_spectrum(exe, 6, "brute", shards=shard_count())
        require(brute == run_spectrum(exe, 6, "ext"), "ext differs from labelled brute force at k=6")
    require(len(brute) == 176 and brute[729] == 1 and brute[567] == -30 and brute[513] == 120,
            "k=6 spectrum shape differs")
    print("k=6: labelled brute force over 2^30 matrices equals the orbit-reduced spectrum (176 entries)")
    print("PASS_SEVEN_EVENT_GUARD_BRUTE6")


def replay_labelled7():
    committed = parse_spectrum((PACKAGE / "SPECTRUM_K7.txt").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory() as workdir:
        exe = build(workdir)
        labelled = run_spectrum(exe, K, "labelled", shards=max(1, os.cpu_count() or 1))
    require(labelled == committed, "labelled k=7 spectrum differs from SPECTRUM_K7.txt")
    print("k=7: unreduced labelled base matrices give the committed spectrum")
    print("PASS_SEVEN_EVENT_GUARD_LABELLED7")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--brute6", action="store_true", help="k=6 labelled brute-force control")
    group.add_argument("--labelled7", action="store_true", help="k=7 control without orbit reduction")
    args = parser.parse_args()
    try:
        if args.brute6:
            replay_brute6()
        elif args.labelled7:
            replay_labelled7()
        else:
            replay_default()
    except Failure as error:
        print("FAIL: %s" % error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
