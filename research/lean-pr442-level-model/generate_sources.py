#!/usr/bin/env python3
"""Reproduce finite literal inputs without consulting either pending-mask definition.

The JSON parser and this extractor are outside Lean's kernel. The generated
tables carry published input hashes and are joined to existing kernel-checked
frame and route tables in LevelFrameJoins. Apache-2.0; substantial AI assistance.
"""
import argparse
from fractions import Fraction
import gzip
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "lean-multi-host-source"


def digest(blob):
    return hashlib.sha256(blob).hexdigest()


def load_gzip(path, compressed=None, uncompressed=None):
    blob = path.read_bytes()
    if compressed is not None:
        assert digest(blob) == compressed, f"compressed hash: {path.name}"
    raw = gzip.decompress(blob)
    if uncompressed is not None:
        assert digest(raw) == uncompressed, f"uncompressed hash: {path.name}"
    return json.loads(raw)


def source_inputs():
    versions = json.loads((SOURCE / "source-versions.json").read_text())
    for name in ("states.json.gz", "frames.json.gz", "geometry.json.gz", "hosted-template.json.gz"):
        pin = versions["inputs"][name]
        load_gzip(SOURCE / "inputs" / name, pin["sha256_compressed"], pin["sha256_uncompressed"])
    # The final public manifests are checked separately by verify.py. These
    # published raw-data pins keep this extractor independently reproducible.
    state_pin = versions['inputs']['states.json.gz']
    states = load_gzip(SOURCE / "inputs/states.json.gz",
        compressed=state_pin['sha256_compressed'],
        uncompressed=state_pin['sha256_uncompressed'])
    frames = load_gzip(SOURCE / "inputs/frames.json.gz", uncompressed=
        "884480e45865a9d9d57f5f7198844a64271b046bc95e9820efbefb9e10878330")
    geometry = load_gzip(SOURCE / "inputs/geometry.json.gz", uncompressed=
        "fc7b29b16ee754ca9717973b745d6322bbf8351a5e35e3fc9e0fbf7a88dc0317")
    template = load_gzip(SOURCE / "inputs/hosted-template.json.gz", uncompressed=
        "dd7833dcaff8c84b258847f4c4d65b6402c702700ae37d2c464083ee37b24126")
    word = load_gzip(HERE / "inputs/pr386-word.json.gz", compressed=
        "1fb726ea3818fe0837cceb0dd22a71a0814f064e5e781628104610d6468e0e55")
    old_geometry = load_gzip(HERE / "inputs/pr386-geometry.json.gz", compressed=
        "5c980202227859e8bb9b863f94503930c2a59d460c0421356688e2b0d828b4a1")
    assert geometry["inherited_geometry_sha256"] == digest(
        (HERE / "inputs/pr386-geometry.json.gz").read_bytes())
    assert geometry["ports"] == old_geometry["ports"], "PR386 route/port reuse"
    assert word["lines"] == [p["q"] for p in geometry["ports"]]
    assert len(word["frames"]) == len(frames["frames"]) == 944
    assert (word["R"], states["R"]) == (865, 747)
    return word, states, frames["frames"], geometry, template, versions


def basis(labels, lines):
    """Choose literal root rows in the source exporter's independent-row order."""
    rows, pivots, result = [], [], []
    for label in labels:
        row = list(map(Fraction, lines[label]))
        for pivot, earlier in zip(pivots, rows):
            if row[pivot]:
                coefficient = row[pivot] / earlier[pivot]
                row = [a - coefficient * b for a, b in zip(row, earlier)]
        nonzero = [i for i, x in enumerate(row) if x]
        if nonzero:
            rows.append(row)
            pivots.append(nonzero[0])
            result.append(lines[label])
    return result


def arr(values):
    return "#[" + ", ".join(map(str, values)) + "]"


def lis(values):
    return "[" + ", ".join(map(str, values)) + "]"


def boolean(value):
    return "true" if value else "false"


def render():
    word, states, frames, geometry, template, _versions = source_inputs()
    nports = len(geometry["ports"])
    assert nports == 120
    initial = [states["initial"][str(i)] for i in range(240)]
    final = [states["final"][str(i)] for i in range(240)]
    # This explicitly tests the old R865 word's data-role labels against the
    # R747 invocation, without equating their different helper-role arrays.
    assert word["start"][:240] == initial
    assert word["final"][:240] == final
    used_labels = sorted(set(initial + final))
    for label in used_labels:
        assert basis(word["frames"][label], word["lines"]) == frames[str(label)]["B"]
    prefix = template["schedule"][:10]
    assert prefix[-1]["kind"] == "bridge"
    calls = [c for c in template["calls"] if c["replica"] == 0 and c["stage"] < 4]
    assert [c["stage"] for c in calls] == list(range(4))
    lines = ["""import Std

/-!
Literal endpoint and schedule inputs for the two children used by PR540.
Generated by generate_sources.py. Python parsing is not kernel verified.
PR386 word compressed SHA256:
  1fb726ea3818fe0837cceb0dd22a71a0814f064e5e781628104610d6468e0e55
PR386 and PR442 frames.json raw SHA256 (identical complete frame artifact):
  884480e45865a9d9d57f5f7198844a64271b046bc95e9820efbefb9e10878330
PR442 geometry raw SHA256:
  fc7b29b16ee754ca9717973b745d6322bbf8351a5e35e3fc9e0fbf7a88dc0317
PR442 hosted-template raw SHA256:
  dd7833dcaff8c84b258847f4c4d65b6402c702700ae37d2c464083ee37b24126
Apache-2.0. Prepared with substantial AI assistance.
-/
namespace PR442LevelModel
set_option maxHeartbeats 0
set_option maxRecDepth 100000

abbrev Port := Fin 120
abbrev LocalAxis := Fin 8
"""]
    lines.append("def rootRows : Array (Array Int) := " + arr(arr(p["q"]) for p in geometry["ports"]))
    lines.append("def oldRootRows : Array (Array Int) := " + arr(arr(q) for q in word["lines"]))
    lines.append("def rootVector (p : Port) (i : LocalAxis) : Int := (rootRows.getD p.val #[]).getD i.val 0")
    lines.append("def oldRootVector (p : Port) (i : LocalAxis) : Int := (oldRootRows.getD p.val #[]).getD i.val 0")
    for name, values in [("sourceEntrance", initial[:120]), ("targetEntrance", initial[120:]),
                         ("sourceExit", final[:120]), ("targetExit", final[120:]),
                         ("oldSourceEntrance", word["start"][:120]),
                         ("oldTargetEntrance", word["start"][120:240]),
                         ("oldSourceExit", word["final"][:120]),
                         ("oldTargetExit", word["final"][120:240])]:
        lines.append(f"def {name}Ids : Array Nat := {arr(values)}")
        lines.append(f"theorem {name}_bound : ∀ p : Port, {name}Ids.getD p.val 0 < 944 := by decide +kernel")
        lines.append(f"def {name} (p : Port) : Fin 944 := ⟨{name}Ids.getD p.val 0, {name}_bound p⟩")
    lines.append("def oldEntranceLineLabels : Array (List Nat) := " + arr(
        lis(word["frames"][f]) for f in word["start"][:120]))
    lines.append("def oldEntranceBasisRows : Array (Array (Array Int)) := " + arr(
        arr(arr(row) for row in basis(word["frames"][f], word["lines"])) for f in word["start"][:120]))
    lines.append("def oldTargetExitBasisRows : Array (Array (Array Int)) := " + arr(
        arr(arr(row) for row in basis(word["frames"][f], word["lines"])) for f in word["final"][120:240]))
    lines.append("def routeAxisRows : Array (Array (List Nat)) := " + arr(
        arr(lis(route["axes"]) for route in p["routes"][:4]) for p in geometry["ports"]))
    lines.append("""
def routeAxes (p : Port) (stage : Nat) : List Nat :=
  (routeAxisRows.getD p.val #[]).getD stage []

/-- The common lift is assembled from the literal stage-route exterior axes. -/
def exteriorAxes (p : Port) (stage : Nat) : List Nat :=
  (List.range (stage + 1)).flatMap (fun s => (routeAxes p s).drop 8)

structure Call where
  stage : Nat
  pair : Nat
  reverse : Bool
  ownerFamilies : Array Nat
  ownerRouteStages : Array Nat
  ownerRoutePorts : Array Nat
  deriving DecidableEq, Repr
""")
    lines.append("def literalCalls : Array Call := " + arr(
        "⟨" + ", ".join([str(c["stage"]), str(c["pair"]), boolean(c["orientation"] == "reverse"),
                           arr(o[0] for o in c["owners"][:240]),
                           arr(o[1][1] for o in c["owners"][:240]),
                           arr(o[1][2] for o in c["owners"][:240])]) + "⟩" for c in calls))
    lines.append("""
def call (c : Fin 4) : Call := literalCalls.getD c.val ⟨0, 0, false, #[], #[], #[]⟩

inductive Event where
  | local (stage pair : Nat) (reverse : Bool)
  | idle (idx pair rank source target : Nat)
  | bridge (dst src : Nat) (coefficient : Int)
  deriving DecidableEq, Repr
""")
    ev = []
    for e in prefix:
        if e["kind"] == "local_cover_sweep":
            ev.append(f'.local {e["stage"]} {e["pair"]} {boolean(e["reverse"])}')
        elif e["kind"] == "idle":
            ev.append(f'.idle {e["idx"]} {e["pair"]} {e["rank"]} {e["source_level"] + 1} {e["target_level"] + 1}')
        else:
            ev.append(f'.bridge {e["dst"]} {e["src"]} ({e["coefficient"]})')
    lines.append("/-- Literal schedule through the bridge immediately after child 2. Levels shifted by one. -/")
    lines.append("def schedulePrefix : List Event := [\n  " + ",\n  ".join(ev) + "]")
    lines.append("end PR442LevelModel\n")
    return "\n\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    path = HERE / "LevelSourceData.lean"
    if args.check:
        assert path.read_text() == expected, "LevelSourceData.lean differs from pinned source extraction"
        print("PASS: endpoint labels, all port routes, calls and schedule literals reproduce exactly")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
