TEST = Q(302153, 100000000)
LOG2 = Q(6931471803, 10**10), Q(6931471808, 10**10)


def lean(q):
    q = Q(q)
    return f'({q.numerator} / {q.denominator} : ℝ)'


def down(q, digits=12):
    return Q((q * 10**digits).__floor__(), 10**digits)


def up(q, digits=12):
    return Q((q * 10**digits).__ceil__(), 10**digits)


def log_interval(n):
    k = n.bit_length() - 1
    x = 1 - Q(2**k, n)
    s = sum((x**(i+1) / (i+1) for i in range(40)), Q(0))
    e = x**41 / (1-x)
    return down(k*LOG2[0]+s-e), up(k*LOG2[1]+s+e)


def exp_interval(x, terms):
    s = sum((x**i / factorial(i) for i in range(terms)), Q(0))
    e = abs(x)**terms * Q(terms+1, factorial(terms)*terms)
    return down(s-e, 15), up(s+e, 15)


def log_theorem(n):
    lo, hi = log_interval(n)
    k = n.bit_length()-1
    x = 1-Q(2**k,n)
    if x == 0:
        return f'''lemma log_{n} : {lean(lo)} ≤ Real.log {n} ∧ Real.log {n} ≤ {lean(hi)} := by
  have h := Real.log_pow (2 : ℝ) {k}
  norm_num at h
  constructor <;> linarith [Real.log_two_gt_d9, Real.log_two_lt_d9]

'''
    return f'''lemma log_{n} : {lean(lo)} ≤ Real.log {n} ∧ Real.log {n} ≤ {lean(hi)} := by
  have h := Real.abs_log_sub_add_sum_range_le (x := {lean(x)})
    (by apply abs_lt.mpr; constructor <;> norm_num) 40
  rw [show 1 - {lean(x)} = (2 : ℝ) ^ {k} / {n} by norm_num,
    Real.log_div (by norm_num) (by norm_num), Real.log_pow] at h
  norm_num [Finset.sum_range_succ, abs_of_nonneg (show 0 ≤ {lean(x)} by norm_num)] at h
  have h' := abs_le.mp h
  constructor <;> linarith [Real.log_two_gt_d9, Real.log_two_lt_d9]

'''


def power_theorem(n, exponent, label, near_one=True):
    ll, lu = log_interval(n)
    a = exponent-1 if near_one else exponent
    xl = down(a*(ll if a >= 0 else lu))
    xu = up(a*(lu if a >= 0 else ll))
    terms = 8 if abs(a) < Q(1,100) else 20
    el = exp_interval(xl,terms)[0]
    eu = exp_interval(xu,terms)[1]
    factor = n if near_one else 1
    lo,hi = factor*el,factor*eu
    abslo = f'abs_of_nonneg (show 0 ≤ {lean(xl)} by norm_num)' if xl >= 0 else f'abs_of_nonpos (show {lean(xl)} ≤ 0 by norm_num)'
    abshi = f'abs_of_nonneg (show 0 ≤ {lean(xu)} by norm_num)' if xu >= 0 else f'abs_of_nonpos (show {lean(xu)} ≤ 0 by norm_num)'
    result = f'''lemma {label}_{n} : {lean(lo)} ≤ ({n} : ℝ) ^ {lean(exponent)} ∧
    ({n} : ℝ) ^ {lean(exponent)} ≤ {lean(hi)} := by
  have hl := log_{n}
  have hxlo : {lean(xl)} ≤ {lean(a)} * Real.log {n} := by nlinarith [hl.1, hl.2]
  have hxhi : {lean(a)} * Real.log {n} ≤ {lean(xu)} := by nlinarith [hl.1, hl.2]
  have hel := Real.exp_bound (x := {lean(xl)}) (by apply abs_le.mpr; constructor <;> norm_num) (n := {terms}) (by norm_num)
  have heu := Real.exp_bound (x := {lean(xu)}) (by apply abs_le.mpr; constructor <;> norm_num) (n := {terms}) (by norm_num)
  have hel' := (abs_le.mp hel).1
  have heu' := (abs_le.mp heu).2
  have hexplo : {lean(el)} ≤ Real.exp {lean(xl)} := by
    rw [{abslo}] at hel'
    norm_num [Finset.sum_range_succ, Nat.factorial] at hel' ⊢
    linarith
  have hexphi : Real.exp {lean(xu)} ≤ {lean(eu)} := by
    rw [{abshi}] at heu'
    norm_num [Finset.sum_range_succ, Nat.factorial] at heu' ⊢
    linarith
  have hlo := hexplo.trans (Real.exp_le_exp.mpr hxlo)
  have hhi := (Real.exp_le_exp.mpr hxhi).trans hexphi
'''
    if near_one:
        result += f'''  have hr : ({n} : ℝ) ^ {lean(exponent)} = {n} * Real.exp ({lean(a)} * Real.log {n}) := by
    rw [Real.rpow_def_of_pos (by norm_num)]
    rw [show Real.log {n} * {lean(exponent)} = Real.log {n} + {lean(a)} * Real.log {n} by ring,
      Real.exp_add, Real.exp_log (by norm_num)]
  rw [hr]
  constructor <;> nlinarith

'''
    else:
        result += f'''  rw [Real.rpow_def_of_pos (by norm_num)]
  simpa only [mul_comm] using And.intro hlo hhi

'''
    return result, (lo,hi)


def polynomial(profile, arg='t'):
    return ' +\n    '.join(f'{v} * ({n} : ℝ) ^ {arg}' for n,v in sorted(profile.items()))


