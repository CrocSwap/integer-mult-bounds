# Bridge generator (our code): packed O-matrix / chart-id data for #7761 -> Bridge7761G1D.lean.  Reads the D2 Lean data.
import os as _os
_HERE=_os.path.dirname(_os.path.abspath(__file__))
# BRIDGE_OUT: a COPY of ../../Nov15 (read for inputs, overwritten with outputs); BRIDGE_GRAPH: final7761.json.gz from apply.py
OUTD=_os.environ['BRIDGE_OUT'].rstrip('/')+'/'
BG=_HERE+'/'
import re
from fractions import Fraction
src=open(OUTD+'Bridge7761D2.lean').read()
def lst(name):
    out=[]
    for part in re.findall(r'def %s\d+ : List [^\n]*? := \[([^\n]*)\]'%name,src):
        out+=[x.strip() for x in (re.split(r',\s*(?=\()',part) if '(' in part else part.split(','))]
    return out
def q(t):
    m=re.match(r'\((-?\d+)(?:/(\d+))? : ℚ\)',t); return Fraction(int(m.group(1)),int(m.group(2) or 1))
pi=[int(x) for x in lst('piL')]; fA=[int(x) for x in lst('fA')]; fB=[int(x) for x in lst('fB')]
od=[q(t) for t in lst('odL')]; op=[q(t) for t in lst('opL')]
src3=open(OUTD+'Bridge7761D3.lean').read()
def lst3(name):
    out=[]
    for part in re.findall(r'def %s\d+ : List [^\n]*? := \[([^\n]*)\]'%name,src3): out+=[int(x) for x in part.split(',')]
    return out
bS=lst3('bS'); bT=lst3('bT'); assert len(bS)==len(bT)==5746
n=1262; assert len(pi)==len(fA)==len(fB)==len(od)==len(op)==n
def pack(xs,w):
    v=0
    for x in reversed(xs): assert 0<=x<(1<<w); v=(v<<w)|x
    return v
def enc(c): assert abs(c.numerator)<32768 and c.denominator<65536; return (c.numerator+32768)|(c.denominator<<16)
out='-- generated by bridgegen/gen4.py packed field data of #7761 (pi, A/B chart ids base 2^11; O diag/partner entries base 2^32 as (num+2^15)|(den<<16))\nnamespace Bridge7761\n'
for nm,v in (('PIK',pack(pi,11)),('FAK',pack(fA,11)),('FBK',pack(fB,11)),('BSK',pack(bS,11)),('BTK',pack(bT,11)),('ODK',pack([enc(c) for c in od],32)),('OPK',pack([enc(c) for c in op],32))):
    out+='def %s : Nat := 0x%x\n'%(nm,v)
out+='end Bridge7761\n'
open(OUTD+'Bridge7761G1D.lean','w').write(out)
print('ok')
