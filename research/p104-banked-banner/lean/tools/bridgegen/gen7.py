def rd(f): return open(D+f).read()
def lstlst(s,name):
    body=re.search(r'def %s : List \(List ℕ\) := (.*)\n'%name,s).group(1)
    return [[int(x) for x in re.findall(r'\d+',r)] for r in re.findall(r'\[([^\[\]]*)\]',body[1:-1])]
def lstn(s,name):
    body=re.search(r'def %s : List ℕ := (.*)\n'%name,s).group(1); return [int(x) for x in re.findall(r'\d+',body)]
def lstq(s,name):
    body=re.search(r'def %s : List ℚ := (.*)\n'%name,s).group(1)
    return [Fraction(m) for m in re.findall(r'\(([-\d/]+) : ℚ\)',body)]
d1=rd('Bridge7761D1.lean'); d2=rd('Bridge7761D2.lean'); bf=rd('BankFlagB.lean')
B=lstlst(d1,'chBasis'); fA=lstn(d2,'fA0'); fB=lstn(d2,'fB0'); pi=lstn(d2,'piL0'); op=lstq(d2,'opL0')
