#!/usr/bin/env python3
"""Census of 4- to 7-subsets of P112 under verify.py's generators, with the transporters of COVER.bin.gz, and the
P105 unit list of UNITS.json.gz; verify.py rechecks everything it relies on (this file needs numpy; verify.py does
not).

    python3 -I -B research/complex-rank8-rigidity-p105/make_units.py --out-dir /new/dir [--pivots PIVOTS.json]

Method: as in the P106 package (PR1616's make_units.py), one level deeper and without sorting the orbit
representatives. H is generated by the 8 generators (172032 elements) in breadth-first order; verify.py rebuilds
the same order. A k-subset c gets the key (j, m): j is the least (k-1)-orbit label among its sub-(k-1)-subsets s,
and m is the least Stab(rep_j)-orbit point among the images g^-1(c \\ s) over the s with label j, where g carries
rep_j onto s. Two k-subsets are H-equivalent iff their keys agree; the canonical member of a key's orbit is the
unit. Orbit sizes are checked to sum to C(112, k).

Pivots: the first live frame, in verify.FRAMES order, that passes verify.criterion (exact). The optional --pivots
is a JSON list of frame indices per 7-orbit in this file's unit order (-1 for none) that skips the search for the
units it covers; PR1616's unregistered search_p105.py (float ranks) produced such a list. verify.py redoes every
criterion exactly either way.
"""
import argparse
import array
import gzip
import itertools
import json
import sys
from math import comb
from multiprocessing import Pool
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import verify as V  # noqa: E402

GA = np.array(V.G, dtype=np.int64)
FM = np.zeros((len(V.FRAMES), V.NL), dtype=bool)
for _n, _F in enumerate(V.FRAMES):
    FM[_n, list(_F)] = True


def closure(gens):
    gs = [np.array(g, dtype=np.uint8) for g in gens]
    e = np.arange(V.NL, dtype=np.uint8)
    seen, elems, frontier = {e.tobytes(): 0}, [e], [0]
    while frontier:
        nxt = []
        for n in frontier:
            for g in gs:
                q = g[elems[n]]  # apply elems[n], then g
                if q.tobytes() not in seen:
                    seen[q.tobytes()] = len(elems)
                    elems.append(q)
                    nxt.append(len(elems) - 1)
        frontier = nxt
    return np.array(elems)


_EP = None


def _init(EP):
    global _EP
    _EP = EP


def stabsize(R):
    R = np.array(R)
    cand = np.nonzero(np.isin(_EP[:, R[0]], R))[0]
    return int((np.sort(_EP[cand][:, R], axis=1) == np.sort(R)).all(axis=1).sum())


def search_pivot(X):
    """First live frame passing verify.criterion (exact), for units with no supplied pivot."""
    xm = V.F0MASK | sum(1 << i for i in X)
    for n, m in enumerate(V.FMASK):
        if not m & xm and V.criterion(X, V.FRAMES[n])[0] is None:
            return n
    return -1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-dir', required=True)
    ap.add_argument('--pivots')
    ap.add_argument('--jobs', type=int, default=8)
    args = ap.parse_args()
    out = Path(args.out_dir)
    for f in ('UNITS.json.gz', 'COVER.bin.gz'):
        if (out / f).exists():
            print(f'refusing to overwrite {out / f}')
            return 2
    gens = V.stabiliser(V.FRAME0)[::V.GEN_STEP]
    E = closure(gens)
    NH = len(E)
    pos = np.full(V.NL, -1)
    pos[V.P112] = np.arange(112)
    P112 = np.array(V.P112)
    EP = pos[E[:, V.P112]].astype(np.int16)  # H on positions 0..111 of P112
    INV = np.argsort(EP, axis=1).astype(np.int16)
    elem = {EP[n].tobytes(): n for n in range(NH)}
    assert len(elem) == NH == 172032
    INVIDX = np.array([elem[INV[n].tobytes()] for n in range(NH)])
    tab = np.array([[comb(x, j + 1) for j in range(7)] for x in range(112)], dtype=np.int64)

    def rank(a):
        a = np.sort(a, axis=1)
        return sum(tab[a[:, j], j] for j in range(a.shape[1]))

    subs4 = np.array(list(itertools.combinations(range(112), 4)), dtype=np.int64)
    byrank = np.empty(len(subs4), dtype=np.int64)
    byrank[rank(subs4)] = np.arange(len(subs4))
    lab = np.full(len(subs4), -1, dtype=np.int64)
    tr = np.full(len(subs4), -1, dtype=np.int64)
    reps4 = []
    while (lab < 0).any():
        q = subs4[byrank[np.nonzero(lab < 0)[0][0]]]
        rr = rank(EP[:, q].astype(np.int64))
        _, first = np.unique(rr, return_index=True)
        lab[rr[first]], tr[rr[first]] = len(reps4), first
        reps4.append(tuple(int(x) for x in np.sort(q)))

    def tables(reps):
        OM = np.zeros((len(reps), 112), np.int16)
        TO = np.zeros((len(reps), 112), np.int64)
        for j, R in enumerate(reps):
            R = np.array(R)
            cand = np.nonzero(np.isin(EP[:, R[0]], R))[0]
            ok = cand[(np.sort(EP[cand][:, R], axis=1) == np.sort(R)).all(axis=1)]
            sub = EP[ok]
            OM[j], TO[j] = sub.min(axis=0), ok[sub.argmin(axis=0)]
        return OM, TO

    def canon(C, lab_of, OM, TO):
        """Keys of the rows of C and, for each, an element index carrying the row onto its canonical member."""
        best = np.full(len(C), np.iinfo(np.int64).max)
        bg = np.zeros(len(C), np.int64)
        bs = np.zeros(len(C), np.int64)
        for r in range(C.shape[1]):
            j, g = lab_of(np.delete(C, r, axis=1))  # EP[g] carries rep_j onto the sub-subset
            y = INV[g, C[:, r]]
            key = j.astype(np.int64) * 112 + OM[j, y]
            better = key < best
            best[better], bg[better], bs[better] = key[better], g[better], TO[j, y][better]
        H = EP[bs[:, None], INV[bg]]
        return best, np.array([elem[h.tobytes()] for h in H])

    def lab4(S):
        k = rank(S)
        return lab[k], tr[k]

    covers = {}

    def level(cands, lab_of, OM, TO, k):
        keys = np.empty(len(cands), np.int64)
        hs = np.empty(len(cands), np.int64)
        for a in range(0, len(cands), 20000):
            keys[a:a + 20000], hs[a:a + 20000] = canon(cands[a:a + 20000], lab_of, OM, TO)
        uk, first = np.unique(keys, return_index=True)
        reps = [tuple(int(x) for x in np.sort(EP[hs[i]][cands[i]])) for i in first]
        # cover: candidate -> (unit index, element carrying the unit onto the candidate)
        uidx = np.searchsorted(uk, keys)
        g = INVIDX[hs]
        assert (np.sort(EP[g[:, None], np.array(reps)[uidx]], axis=1) == cands).all()
        covers[k] = (uidx, g)
        print(f'{len(cands)} candidates, {len(reps)} orbits of {k}-subsets', flush=True)
        return uk, reps

    def mk_lab(uk, lab_prev, OM, TO):
        def f(S):
            keys, h = canon(S, lab_prev, OM, TO)
            return np.searchsorted(uk, keys), INVIDX[h]
        return f

    OM4, TO4 = tables(reps4)
    cand5 = np.array(sorted({tuple(sorted(q + (x,))) for q in reps4 for x in range(112) if x not in q}))
    uk5, reps5 = level(cand5, lab4, OM4, TO4, 5)
    OM5, TO5 = tables(reps5)
    lab5 = mk_lab(uk5, lab4, OM4, TO4)
    cand6 = np.array(sorted({tuple(sorted(R + (x,))) for R in reps5 for x in range(112) if x not in R}))
    uk6, reps6 = level(cand6, lab5, OM5, TO5, 6)
    OM6, TO6 = tables(reps6)
    lab6 = mk_lab(uk6, lab5, OM5, TO5)
    cand7 = np.array(sorted({tuple(sorted(R + (x,))) for R in reps6 for x in range(112) if x not in R}))
    uk7, reps7 = level(cand7, lab6, OM6, TO6, 7)
    with Pool(args.jobs, initializer=_init, initargs=(EP,)) as pool:
        for k, reps in ((4, reps4), (5, reps5), (6, reps6), (7, reps7)):
            st = pool.map(stabsize, reps, chunksize=256)
            assert sum(NH // s for s in st) == comb(112, k), k
            print(f'{len(reps)} orbits of {k}-subsets; sizes sum to C(112,{k})', flush=True)
    # Level 4: triple-orbit representative + one line -> quadruple representative (verify.py's candidate order).
    c4 = sorted({tuple(sorted(o[0] + (x,))) for o in V.triple_orbits(gens) for x in V.P112 if x not in o[0]})
    k4 = rank(np.array([sorted(int(pos[x]) for x in c) for c in c4]))
    covers[4] = (lab[k4], tr[k4])
    L = lambda Y: [int(P112[x]) for x in Y]  # positions are increasing in line ID
    piv = json.loads(Path(args.pivots).read_text()) if args.pivots else [-1] * len(reps7)
    assert len(piv) == len(reps7)
    miss = [n for n, p in enumerate(piv) if p is None or p < 0]
    if miss:
        with Pool(args.jobs) as pool:
            for n, p in zip(miss, pool.map(search_pivot, [L(reps7[n]) for n in miss])):
                piv[n] = p
    if any(p < 0 for p in piv):
        raise SystemExit('a unit has no passing pivot')
    units = {'reps4': [L(r) for r in reps4], 'p107': [L(r) for r in reps5], 'p106': [L(r) for r in reps6],
             'p105': [L(r) + [int(p)] for r, p in zip(reps7, piv)]}
    (out / 'UNITS.json.gz').write_bytes(gzip.compress(json.dumps(units, separators=(',', ':')).encode(), mtime=0))
    # COVER.bin.gz: for k = 4..7 in turn, the candidate count, then the unit indices, then the element indices,
    # each as little-endian unsigned 32-bit integers.
    buf = array.array('I')
    for k in (4, 5, 6, 7):
        j, g = covers[k]
        buf.append(len(j))
        buf.extend(int(x) for x in j)
        buf.extend(int(x) for x in g)
    if sys.byteorder != 'little':
        buf.byteswap()
    (out / 'COVER.bin.gz').write_bytes(gzip.compress(buf.tobytes(), compresslevel=9, mtime=0))
    print(f'units {len(reps4)}/{len(reps5)}/{len(reps6)}/{len(reps7)}; cover '
          + '/'.join(str(len(covers[k][0])) for k in (4, 5, 6, 7)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
