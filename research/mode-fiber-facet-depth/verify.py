"""Exact checks: no facet of the mode zonotope has a depth gap (stdlib only).

Usage: verify.py facets|ridges. Prints PASS_MODE_FIBER_FACET_DEPTH <part> on success.
"""
import hashlib
import itertools
import json
import math
import pathlib
import sys
from fractions import Fraction

HERE = pathlib.Path(__file__).resolve().parent
NORMALIZERS = HERE.parent / "coded-native-caller" / "NORMALIZERS.json"
NORMALIZERS_SHA = "ae8aad06aa5d1811d725895b3ab5a4f4daa9dcdd88294aa0d5f723e78bb1e0da"
N, MODES = 112, 8
STD = [tuple(int(i == k) for i in range(MODES)) for k in range(MODES)]


def fail(msg):
    raise SystemExit("FAIL: " + msg)


def check(cond, msg):
    if not cond:
        fail(msg)


def dot(a, b):
    return (a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3]
            + a[4] * b[4] + a[5] * b[5] + a[6] * b[6] + a[7] * b[7])


def prim(v):
    g = math.gcd(*v)
    v = tuple(a // g for a in v)
    return v if next(a for a in v if a) > 0 else tuple(-a for a in v)


def load_rows():
    raw = NORMALIZERS.read_bytes()
    check(hashlib.sha256(raw).hexdigest() == NORMALIZERS_SHA, "NORMALIZERS.json hash")
    cols = json.loads(raw)["mode_columns"]
    check(len(cols) == MODES and all(len(c) == N for c in cols), "mode matrix shape")
    return [tuple(cols[j][i] for j in range(MODES)) for i in range(N)]


def symmetry(rows):
    """Coordinate permutations preserving the supports.

    Up to sign, the rows are all 8 sign classes on each of the 14 supports, so
    every signed permutation built from these permutations maps +-rows to +-rows.
    """
    supp = lambda m: frozenset(k for k in range(MODES) if m[k])
    supports = {supp(m) for m in rows}
    check(len(supports) == 14 and all(len(s) == 4 for s in supports), "14 weight-four supports")
    pm = set(rows) | {tuple(-x for x in m) for m in rows}
    for s in supports:
        cls = [m for m in pm if supp(m) == s]
        check(len(cls) == 16, "all sign patterns on each support, up to row sign")
    aut = [p for p in itertools.permutations(range(MODES))
           if {frozenset(p[k] for k in s) for s in supports} == supports]
    check(len(aut) == 1344, "|Aut(H8)| = 1344")
    for p in aut[:50]:
        for signs in ((1,) * 8, (1, -1, 1, -1, -1, 1, 1, -1)):
            img = {tuple(signs[p[k]] * m[p[k]] for k in range(MODES)) for m in pm}
            check(img == pm, "signed permutation preserves +-rows")
    return aut


def perp_cut(ns, e):
    """Integer basis of {v in span(ns) : v.e = 0}."""
    c = [dot(n, e) for n in ns]
    j = next((i for i, x in enumerate(c) if x), None)
    if j is None:
        return ns
    out = []
    for i in range(len(ns)):
        if i != j:
            v = tuple(c[j] * a - c[i] * b for a, b in zip(ns[i], ns[j]))
            if any(v):
                out.append(prim(v))
    return out


def facet_rows(rows, th):
    H = [i for i in range(N) if dot(th, rows[i]) == 0]
    ns = STD
    for i in H:
        ns = perp_cut(ns, rows[i])
    return H, len(ns)


def neighbours(rows, th):
    """All hyperplanes spanned by rows that contain a rank-6 flat of facet th."""
    H, _ = facet_rows(rows, th)
    level = {}
    for i in H:
        ns = perp_cut(STD, rows[i])
        F = frozenset(x for x in H if all(dot(n, rows[x]) == 0 for n in ns))
        level[F] = ns
    for _ in range(2, 7):
        nxt = {}
        for F, ns in level.items():
            covered = set()
            for e in H:
                if e in F or e in covered:
                    continue
                ns2 = perp_cut(ns, rows[e])
                G = frozenset(x for x in H if all(dot(n, rows[x]) == 0 for n in ns2))
                covered |= G
                nxt.setdefault(G, ns2)
        level = nxt
    out = set()
    for ns in level.values():
        check(len(ns) == 2, "rank-6 flat")
        for e in range(N):
            c = [dot(n, rows[e]) for n in ns]
            if c != [0, 0]:
                out.add(prim(tuple(c[1] * a - c[0] * b for a, b in zip(ns[0], ns[1]))))
    return out, level


def egcd(x, y):
    if y == 0:
        return x, 1, 0
    g, s, t = egcd(y, x % y)
    return g, t, s - (x // y) * t


def holes_2d(P):
    """Integer points strictly inside sum_i [0,1] p_i, in coordinates of the
    lattice generated by the p_i, that are not subset sums of the p_i."""
    B1, d = None, 0
    for v in P:
        if B1 is None:
            if v[0] == 0:
                d = math.gcd(d, v[1])
            else:
                B1 = list(v)
            continue
        g, s, t = egcd(B1[0], v[0])
        d = math.gcd(d, (v[0] // g) * B1[1] - (B1[0] // g) * v[1])
        B1 = [g, s * B1[1] + t * v[1]]
    check(B1 is not None and d != 0, "projection spans the plane")
    Q = []
    for v in P:
        x = Fraction(v[0], B1[0])
        y = (v[1] - x * B1[1]) / d
        check(x.denominator == 1 and y.denominator == 1, "lattice coordinates")
        Q.append((int(x), int(y)))
    xs, ys = [q[0] for q in Q], [q[1] for q in Q]
    xmin, xmax = sum(min(0, x) for x in xs), sum(max(0, x) for x in xs)
    ymin, ymax = sum(min(0, y) for y in ys), sum(max(0, y) for y in ys)
    width = xmax - xmin + 1
    reach = 1 << ((-xmin) + (-ymin) * width)
    for a, b in Q:  # partial sums stay in the box, so row shifts never wrap
        sh = a + b * width
        reach |= (reach << sh) if sh >= 0 else (reach >> (-sh))
    cons = []
    for u in {(-b // math.gcd(a, b), a // math.gcd(a, b)) for a, b in Q}:
        vals = [u[0] * a + u[1] * b for a, b in Q]
        cons.append((u, sum(min(0, x) for x in vals), sum(max(0, x) for x in vals)))
    holes = []
    for y in range(ymin, ymax + 1):
        lo, hi, ok = Fraction(xmin - 1), Fraction(xmax + 1), True
        for u, mn, mx in cons:
            if u[0] == 0:
                if not mn < u[1] * y < mx:
                    ok = False
                    break
            else:
                l, h = Fraction(mn - u[1] * y, u[0]), Fraction(mx - u[1] * y, u[0])
                if u[0] < 0:
                    l, h = h, l
                lo, hi = max(lo, l), min(hi, h)
        if ok:
            for x in range(math.floor(lo) + 1, math.ceil(hi)):
                if not (reach >> ((x - xmin) + (y - ymin) * width)) & 1:
                    holes.append((x, y))
    return holes, Q


def holes_2d_slow(Q):
    """Independent set-based recomputation on lattice coordinates Q."""
    sums = {(0, 0)}
    for a, b in Q:
        sums |= {(x + a, y + b) for x, y in sums}
    cons = []
    for a, b in Q:
        g = math.gcd(a, b)
        u = (-b // g, a // g)
        vals = [u[0] * p + u[1] * q for p, q in Q]
        cons.append((u, sum(min(0, v) for v in vals), sum(max(0, v) for v in vals)))
    xs, ys = [q[0] for q in Q], [q[1] for q in Q]
    return sorted((x, y)
                  for x in range(sum(min(0, v) for v in xs), sum(max(0, v) for v in xs) + 1)
                  for y in range(sum(min(0, v) for v in ys), sum(max(0, v) for v in ys) + 1)
                  if all(mn < u[0] * x + u[1] * y < mx for u, mn, mx in cons) and (x, y) not in sums)


def depth_profile(rows, th):
    """(g, sorted off-facet values / g, gap-free, greedy) for normal th."""
    nz = sorted(abs(dot(th, m)) for m in rows if dot(th, m))
    g = math.gcd(*nz)
    vals = [x // g for x in nz]
    total = sum(vals)
    reach = 1
    for v in vals:
        reach |= reach << v
    gap_free = reach == (1 << (total + 1)) - 1
    greedy, prefix = True, 0
    for v in vals:
        if v > prefix + 1:
            greedy = False
            break
        prefix += v
    return g, vals, gap_free, greedy


def main(part):
    check(part in ("facets", "ridges"), "part is facets or ridges")
    rows = load_rows()
    aut = symmetry(rows)
    data = json.loads((HERE / "ORBITS.json").read_text())
    reps = [tuple(o["abs_normal"]) for o in data["orbits"]]
    check(len(reps) == 41, "41 orbit representatives")
    canon = lambda a: min(tuple(a[p[k]] for k in range(MODES)) for p in aut)
    check(len({canon(r) for r in reps}) == 41, "representatives lie in distinct orbits")
    orbit_abs = {tuple(r[p[k]] for k in range(MODES)) for r in reps for p in aut}

    total_facets = 0
    for o, th in zip(data["orbits"], reps):
        check(math.gcd(*th) == 1, "primitive normal")
        H, corank = facet_rows(rows, th)
        check(corank == 1, "zero rows span a hyperplane (facet)")
        check(len(H) == o["rows_on_facet"], "rows on facet")
        g, vals, gap_free, greedy = depth_profile(rows, th)
        check(g == o["g"] and g in (1, 2), "gcd of off-facet values")
        check(vals[0] == 1, "smallest off-facet value equals g")
        check(gap_free and greedy, "subset sums of off-facet values have no gap")
        absimgs = {tuple(th[p[k]] for k in range(MODES)) for p in aut}
        total_facets += len(absimgs) * 2 ** sum(1 for x in th if x) // 2

    # closure: every ridge-neighbour of every representative lies in a listed orbit.
    # The facet-ridge graph of a polytope is connected, so the 41 orbits are all facets.
    last_nb = None
    ridges = {}
    for th in reps:
        nb, level = neighbours(rows, th)
        for F, ns in level.items():
            ridges.setdefault(F, ns)
        last_nb = nb
        for x in nb:
            check(tuple(abs(v) for v in x) in orbit_abs, "ridge neighbour outside listed orbits")
    check(total_facets == 422224, "total number of facet hyperplanes")

    if part == "facets":
        check(not depth_profile(rows, (5, 3, 0, 0, 0, 0, 0, 0))[2], "control: non-facet (5,3,0,...) has a projection gap")
        check(facet_rows(rows, (5, 3, 0, 0, 0, 0, 0, 0))[1] > 1, "control: (5,3,0,...) is not a facet")
        reduced = orbit_abs - {tuple(reps[-1][p[k]] for k in range(MODES)) for p in aut}
        check(any(tuple(abs(v) for v in x) not in reduced for x in last_nb), "control: dropping an orbit breaks closure")
        print("PASS_MODE_FIBER_FACET_DEPTH facets")
        return

    # ridges: every ridge of Z is a Gamma-image of a rank-6 flat of some representative
    check(len(ridges) == 21589, "rank-6 flats of the representatives")
    projections = []
    for F, (n1, n2) in ridges.items():
        P = [(dot(n1, rows[i]), dot(n2, rows[i])) for i in range(N) if i not in F]
        holes, Q = holes_2d(P)
        check(not holes, "ridge projection has no interior hole")
        projections.append(Q)
    for Q in projections[::4000]:
        check(holes_2d_slow(Q) == [], "set-based recomputation agrees")
    toy = [(1, -3), (1, -2), (1, 0)]
    check(sorted(holes_2d(toy)[0]) == [(1, -1), (2, -4)] == holes_2d_slow(holes_2d(toy)[1]),
          "control: toy zonogon with holes is detected")
    print("PASS_MODE_FIBER_FACET_DEPTH ridges")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "facets")
