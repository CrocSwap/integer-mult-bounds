#!/usr/bin/env python3
"""CARRYPOT z4pot.py (own code). Z/4 TORSION POTENTIAL for dyadic hosted toy runs (values in (1/2)Z^W).
State class [w] = 2w mod 4 in (Z/4)^W.  Chart lift: preimage C^ = {x in (Z/4)^n : x mod 2 in C}.
S(t) = sum over history of C^_r (x) [w_r]  in (Z/4)^n (x) (Z/4)^W ;  lam = Z/4-length.
Claims checked exactly, per step:
  ADD with 2-adically integral scalar, INIT, descent, discard : dlam = 0
  ascent (ANY register, integral OR half-valued)               : dlam <= climb
  halving ADD (scalar of valuation -1)                          : dlam <= n   (recorded as H)
 => R + H >= lam(S0+T) - lam(S0) - (public climbs)   (T = end states of publics).
Controls: (c1) halving charged 0 -> violations; (c2) cross-chart ADD -> violations."""
import random, sys
from fractions import Fraction as Fr
dot = lambda a, b: bin(a & b).count('1') & 1

def z4len(rows, N):
    """Z/4-length of the submodule of (Z/4)^N generated by rows (lists of ints mod 4): 2-adic Smith form mod 4."""
    M = [[x % 4 for x in r] for r in rows if any(x % 4 for x in r)]
    L = 0
    for want in (1, 2):                      # unit pivots first, then 2-pivots
        while True:
            piv = None
            for i, r in enumerate(M):
                for j, x in enumerate(r):
                    if (want == 1 and x % 2 == 1) or (want == 2 and x == 2):
                        piv = (i, j); break
                if piv: break
            if not piv: break
            i, j = piv; r = M[i]
            if want == 1:
                inv = 1 if r[j] == 1 else 3
                r = [(x * inv) % 4 for x in r]
                # clear column j from other rows, then row j via column ops (free: only length counted)
                NM = []
                for k, s in enumerate(M):
                    if k == i: continue
                    c = s[j]
                    s2 = [(a - c * b) % 4 for a, b in zip(s, r)]
                    NM.append(s2)
                # column ops: remove pivot column contributions -> rows already have 0 at j; the pivot row is split off
                L += 2; M = [s for s in NM if any(s)]
                # other rows unaffected by column clearing of pivot row (they have 0 in column j)
            else:
                NM = []
                for k, s in enumerate(M):
                    if k == i: continue
                    c = s[j] // 2          # s[j] in {0,2} here (all entries even)
                    NM.append([(a - c * b) % 4 for a, b in zip(s, r)])
                L += 1; M = [s for s in NM if any(s)]
    return L
# NB column clearing: after the unit pivot row is split off, the remaining rows have 0 in column j, and the
# module splits as Z/4*(pivot row) (+) span(rest) only after column ops on the pivot row; those ops do not touch
# the other rows (0 in column j) -- standard Smith step.  Same for 2-pivots inside the all-even remainder.

def subspaces(n):
    seen = {frozenset([0])}; fr = [frozenset([0])]
    while fr:
        nx = []
        for S in fr:
            for v in range(1 << n):
                if v not in S:
                    U = frozenset(S | {x ^ v for x in S})
                    if U not in seen: seen.add(U); nx.append(U)
        fr = nx
    return list(seen)
dimS = lambda S: len(S).bit_length() - 1
def basis(S):
    rows = []
    for v in sorted(S):
        for r in rows: v = min(v, v ^ r)
        if v: rows.append(v)
    return rows
def span(vs):
    S = {0}
    for v in vs:
        if v not in S: S |= {x ^ v for x in S}
    return frozenset(S)

def cls(w):   # [w] = 2w mod 4
    out = []
    for x in w:
        y = 2 * x; assert y.denominator == 1, 'den > 2'
        out.append(int(y) % 4)
    return out
def tens_pre(C, w, n):
    """generators of C^ (x) [w] in (Z/4)^(n*d)"""
    c = cls(w); d = len(c); gens = []
    if not any(c): return gens
    for b in basis(C):
        gens.append([((b >> i) & 1) * c[j] % 4 for i in range(n) for j in range(d)])
    for i in range(n):   # 2 e_i (x) [w]
        gens.append([(2 * c[j]) % 4 if ii == i else 0 for ii in range(n) for j in range(d)])
    return gens
def half(w): return any(x.denominator == 2 for x in w)

def run_one(rng, n, Q, nrel, steps, mode='honest'):
    k = len(Q); L = subspaces(n); V = frozenset(range(1 << n))
    perp = lambda q: frozenset(v for v in range(1 << n) if not dot(v, q))
    rel = []
    for j in range(nrel):
        while True:
            S, F = rng.choice(L), rng.choice(L)
            if S <= F: break
        rel.append((S, F))
    d = 2 * k + nrel; N = n * d
    e = lambda i: [Fr(1) if t == i else Fr(0) for t in range(d)]
    ch, val, pub = {}, {}, {}
    for p in range(k):
        ch['X%d' % p] = span([Q[p]]); val['X%d' % p] = e(p); pub['X%d' % p] = V
        ch['Y%d' % p] = frozenset([0]); val['Y%d' % p] = e(k + p); pub['Y%d' % p] = perp(Q[p])
    for j, (S, F) in enumerate(rel):
        ch['Z%d' % j] = S; val['Z%d' % j] = e(2 * k + j); pub['Z%d' % j] = F
    S0 = [g for r in ch for g in tens_pre(ch[r], val[r], n)]
    Sg = list(S0); lam = z4len(Sg, N); psi = lam - z4len([[2*x % 4 for x in g] for g in Sg], N); HP = 0; pviol = 0; R = 0; pubclimb = 0; H = 0; viol = 0; nhalf_asc = 0; nhalving = 0; maxhalv = 0
    nown = rng.randint(1, 3); SC = [Fr(1), Fr(-1), Fr(1, 2), Fr(-1, 2), Fr(3, 2), Fr(2)]
    for t in range(steps):
        regs = list(ch); typ = rng.random(); kind = None
        if typ < 0.45:                                    # ADD
            if mode == 'crossch':
                pairs = [(a, b) for a in regs for b in regs if a != b and ch[b] <= ch[a]]
            else:
                pairs = [(a, b) for a in regs for b in regs if a != b and ch[a] == ch[b]]
            if not pairs: continue
            a, b = rng.choice(pairs); lamb = rng.choice(SC)
            nv = [x + lamb * y for x, y in zip(val[a], val[b])]
            if any((2 * x).denominator != 1 for x in nv): continue          # den <= 2 kept
            if any(nv[p] != 0 and Q[p] not in ch[a] for p in range(k)): continue   # support rule
            if all(x == 0 for x in nv) and a[0] != 'O': continue
            ishalving = lamb.denominator == 2 and any(y != 0 for y in val[b])
            val[a] = nv; inc = 0; kind = 'halving' if ishalving else 'add'
        elif typ < 0.7:                                   # public ascent
            ps = [r for r in regs if r in pub and ch[r] != pub[r]]
            if not ps: continue
            r = rng.choice(ps); ups = [D for D in L if ch[r] < D <= pub[r] and dimS(D) == dimS(ch[r]) + 1]
            D = rng.choice(ups); inc = 1; pubclimb += 1; nhalf_asc += half(val[r]); ch[r] = D; kind = 'asc'
        else:                                             # owned
            os_ = [r for r in regs if r[0] == 'O']
            if len(os_) < nown and rng.random() < 0.5:
                nm = 'O%d' % t; ch[nm] = rng.choice([ch[x] for x in regs]) if rng.random() < 0.7 else rng.choice(L)
                val[nm] = [Fr(0)] * d; inc = 0; kind = 'init'
            elif os_ and rng.random() < 0.08:
                del ch[os_[0]]; del val[os_[0]]; continue
            elif os_:
                r = rng.choice(os_); D = rng.choice([ch[x] for x in regs if x != r] + L)
                if not (D <= ch[r] or ch[r] <= D): continue
                if any(val[r][p] != 0 and Q[p] not in D for p in range(k)): continue
                inc = max(0, dimS(D) - dimS(ch[r])); R += inc; nhalf_asc += (inc > 0 and half(val[r])); ch[r] = D; kind = 'asc'
            else: continue
        Sg += [g for r in ch for g in tens_pre(ch[r], val[r], n)]
        ln = z4len(Sg, N); dl = ln - lam
        ps = ln - z4len([[2*x % 4 for x in g] for g in Sg], N); dp = ps - psi; psi = ps
        if kind == 'halving': HP += dp
        elif dp > inc: pviol += 1
        if dp < 0: pviol += 1
        if kind == 'halving':
            nhalving += 1; maxhalv = max(maxhalv, dl)
            if mode == 'nohalfcharge':
                if dl > 0: viol += 1
            else:
                if dl > n: viol += 1
                H += dl
        elif dl > inc: viol += 1
        lam = ln
        Sg = compress(Sg, N)
    T = [g for r in ch if r in pub for g in tens_pre(ch[r], val[r], n)]
    bound = z4len(S0 + T, N) - z4len(S0, N) - pubclimb
    PS = lambda G: z4len(G, N) - z4len([[2*x % 4 for x in g] for g in G], N)
    pbound = PS(S0 + T) - PS(S0) - pubclimb
    return dict(pbound=pbound, R=R, HP=HP, pviol=pviol, H=H, bound=bound, viol=viol, nhalf_asc=nhalf_asc, nhalving=nhalving, maxhalv=maxhalv)

def compress(rows, N):
    """row-echelon over Z/4 with row ops only (same module)."""
    M = [[x % 4 for x in r] for r in rows if any(x % 4 for x in r)]; out = []
    for j in range(N):
        pi = next((i for i, r in enumerate(M) if r[j] % 2 == 1), None)
        if pi is None: pi = next((i for i, r in enumerate(M) if r[j] == 2), None)
        if pi is None: continue
        r = M.pop(pi)
        if r[j] % 2 == 1:
            inv = 1 if r[j] == 1 else 3; r = [(x * inv) % 4 for x in r]
            M = [[(a - s[j] * b) % 4 for a, b in zip(s, r)] for s in M]
            out.append(r); out.append([(2 * x) % 4 for x in r])   # keep 2r explicitly (harmless)
        else:
            M = [[(a - (s[j] // 2) * b) % 4 for a, b in zip(s, r)] if s[j] in (0, 2) else s for s in M]
            out.append(r)
        M = [s for s in M if any(s)]
    return [r for r in out if any(r)] + M

if __name__ == '__main__':
    mode = sys.argv[1] if len(sys.argv) > 1 else 'honest'
    nruns = int(sys.argv[2]) if len(sys.argv) > 2 else 600
    rng = random.Random(int(sys.argv[3]) if len(sys.argv) > 3 else 1)
    tot = viol = bad = 0; agg = dict(nhalf_asc=0, nhalving=0, H=0); maxh = 0; slack0 = 0
    for it in range(nruns):
        n = rng.choice([3, 3, 4]); odd = [v for v in range(1, 1 << n) if dot(v, v)]
        Q = rng.sample(odd, rng.randint(1, min(3, len(odd))))
        o = run_one(rng, n, Q, rng.randint(0, 2), rng.randint(10, 50), mode)
        tot += 1; viol += o['viol']; bad += (o['R'] + o['H'] < o['bound']); pv = locals().get('pv', 0) + o['pviol']; pbad = locals().get('pbad', 0) + (o['R'] + o['HP'] < o['pbound'] and mode == 'honest'); hp = locals().get('hp', 0) + o['HP']
        for kk in agg: agg[kk] += o[kk]
        maxh = max(maxh, o['maxhalv']); slack0 += (o['R'] + o['H'] == o['bound'])
    print('mode', mode, 'runs', tot, 'step violations', viol, 'R+H<bound', bad, '| half-valued ascents', agg['nhalf_asc'],
          'halvings', agg['nhalving'], 'sum H', agg['H'], 'max dlam at one halving', maxh, 'tight runs', slack0, '| PSI: step viol', pv, 'R+H_psi<bound', pbad, 'sum H_psi', hp)
