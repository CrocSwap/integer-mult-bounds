# DISCHARGE item 2: chunked molecule certificates PriceHK{h} for h=16..19.
# per-L pieces in separate modules (Nov15/PriceHK{h}_{g}.lean), final module PriceHK{h}.lean assembles md{h}.
import json, sys
ND='<research-tree>/lean/decoder-duality/Nov15/'
BUDGET=2500
def piece_src(h, Ls, mol):
    out=["""/-
PriceHK%d piece (lane DISCHARGE, Nov 20; GENERATED by discharge/genchunk.py from priceh/mol_h%d.json).  Per-L molecule checks for L in %s, decide+kernel.  Kernel only.
-/
import Nov15.PriceH

set_option maxRecDepth 100000
set_option linter.unusedVariables false

namespace PriceHK
open PriceH BankNC0
"""%(h,h,Ls)]
    for L in Ls:
        m=mol[str(L)]; D,E=m['D'],m['E']
        ents=['(%d, %d)'%(a,b) for a,b in m['W']]
        chunks=[ents[i:i+30] for i in range(0,len(ents),30)]
        for j,c in enumerate(chunks):
            out.append(f"def w{h}_{L}_{j} : List (ℕ × ℕ) := [{', '.join(c)}]")
        out.append(f"def w{h}_{L} : List (ℕ × ℕ) := " + ' ++ '.join(f'w{h}_{L}_{j}' for j in range(len(chunks))))
        for i in range(h+1):
            out.append(f"theorem hdec{h}_{L}_i{i} : ∀ j, j ≤ {h} →\n    decVal w{h}_{L} {i} j = {D} * min {L} (dh {i} j) + {E} * min 1 (dh {i} j) := by decide +kernel")
        if L<=h-2:
            out.append(f"theorem hsep{h}_{L} : {D} + {E} ≤ 2 * sepValH {h} w{h}_{L} := by decide +kernel")
    out.append("end PriceHK\n")
    return "\n".join(out)
def main(h):
    mol=json.load(open(f'../priceh/mol_h{h}.json'))['mol']
    groups=[];cur=[];sz=0
    for L in range(1,h):
        s=len(json.dumps(mol[str(L)]['W']))
        if cur and sz+s>BUDGET: groups.append(cur);cur=[];sz=0
        cur.append(L);sz+=s
    groups.append(cur)
    mods=[]
    for g,Ls in enumerate(groups):
        name=f'PriceHK{h}_{g}'; mods.append(name)
        open(ND+name+'.lean','w').write(piece_src(h,Ls,mol))
    Ds=[0]+[mol[str(L)]['D'] for L in range(1,h)]
    Es=[0]+[mol[str(L)]['E'] for L in range(1,h)]
    Wl=', '.join(['[]']+[f'w{h}_{L}' for L in range(1,h)])
    imps="\n".join(f'import Nov15.{m}' for m in mods)
    alt=", ".join(f"hdec{h}_{L}" for L in range(1,h))
    sepalt=", ".join(f"hsep{h}_{L}" for L in range(1,h-1))
    comb="\n".join(f"theorem hdec{h}_{L} : ∀ i, i ≤ {h} → ∀ j, j ≤ {h} →\n    decVal w{h}_{L} i j = {Ds[L]} * min {L} (dh i j) + {Es[L]} * min 1 (dh i j) := by\n  intro i hi\n  interval_cases i\n  exacts [" + ', '.join(f'hdec{h}_{L}_i{i}' for i in range(h+1)) + "]" for L in range(1,h))
    fin=f"""/-
PriceHK{h} (lane DISCHARGE, Nov 20; GENERATED by discharge/genchunk.py).  Molecule certificate md{h} : MolData {h} assembled from the chunked per-L modules {mods}.
Replaces the over-budget PriceHI{h}.  Kernel only.
-/
import Mathlib.Tactic.IntervalCases
{imps}

set_option maxRecDepth 100000
set_option linter.unusedVariables false

namespace PriceHK
open PriceH BankNC0

def molD{h} : ℕ → ℕ := fun L => ({Ds}:List ℕ).getD L 0
def molE{h} : ℕ → ℕ := fun L => ({Es}:List ℕ).getD L 0
def molW{h} : ℕ → List (ℕ × ℕ) := fun L => ([{Wl}] : List (List (ℕ × ℕ))).getD L []
{comb}
theorem hD{h} : ∀ L, L ≤ {h} - 1 → 1 ≤ L → 0 < molD{h} L := by decide +kernel
theorem hdec{h} : ∀ L, L ≤ {h} - 1 → 1 ≤ L → ∀ i, i ≤ {h} → ∀ j, j ≤ {h} →
    decVal (molW{h} L) i j = molD{h} L * min L (dh i j) + molE{h} L * min 1 (dh i j) := by
  intro L h2 h1
  have h2' : L ≤ {h-1} := h2
  interval_cases L
  exacts [{alt}]
theorem hsep{h} : ∀ L, L ≤ {h} - 2 → 1 ≤ L → molD{h} L + molE{h} L ≤ 2 * sepValH {h} (molW{h} L) := by
  intro L h2 h1
  have h2' : L ≤ {h-2} := h2
  interval_cases L
  exacts [{sepalt}]
/-- the molecule certificate at label rank {h} -/
def md{h} : MolData {h} :=
  ⟨molD{h}, molE{h}, molW{h}, hD{h}, hdec{h}, hsep{h}, by decide +kernel, by decide +kernel⟩

end PriceHK

#print axioms PriceHK.md{h}
"""
    open(ND+f'PriceHK{h}.lean','w').write(fin)
    print(h,mods)
for h in map(int,sys.argv[1:]): main(h)
