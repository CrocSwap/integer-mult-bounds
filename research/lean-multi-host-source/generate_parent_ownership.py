def tree(xs,default=0):
 n=1
 while n<len(xs):n*=2
 xs=list(xs)+[default]*(n-len(xs))
 def rec(v):
  if all(x==v[0]for x in v):return f'(.leaf {v[0]})'
  return f'(.node {rec(v[::2])} {rec(v[1::2])})'
 return rec(xs)
