#!/usr/bin/env python3
"""Generate the literal dyadic port-basis certificate from pinned GEOMETRY.json.

Parsing and code generation are untrusted; Lean checks the emitted finite
orthogonality proposition. Source SHA-256 and exact entry reconstruction are
recorded here to make the source-to-literal boundary reproducible.
"""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path


def tree(values):
    size = 1
    while size < len(values):
        size *= 2
    values = list(values) + [0] * (size - len(values))
    def go(xs):
        if all(x == xs[0] for x in xs):
            return f"(.leaf ({xs[0]}))"
        return f"(.node {go(xs[::2])} {go(xs[1::2])})"
    return go(values)


def render(path: Path) -> str:
    raw = path.read_bytes()
    geometry = json.loads(raw)
    ports = geometry["ports"]
    assert len(ports) == 120
    matrices, routes = [], []
    for index, port in enumerate(ports):
        assert port["port"] == index
        assert len(port["q"]) == 8
        assert len(port["complement_columns"]) == 8
        rows = []
        for q, complement in zip(port["q"], port["complement_columns"]):
            assert len(complement) == 7
            row = [Fraction(q)] + [2 * Fraction(x) for x in complement]
            assert all(x.denominator == 1 for x in row)
            rows.append([x.numerator for x in row])
        matrices.append(rows)
        assert len(port["rho15"]) == 15
        route = []
        for row in port["rho15"]:
            assert len(row) == 15
            row = [4 * Fraction(x) for x in row]
            assert all(x.denominator == 1 for x in row)
            route.append([x.numerator for x in row])
        routes.append(route)
        stage2 = next(route for route in port["routes"] if route["stage"] == 2)
        assert stage2["axes"] == list(range(8)) + list(range(15, 22))
    # Informative generator check; the generated Lean theorem independently
    # checks the complete same integer identities in the kernel.
    for matrix in matrices:
        for i in range(8):
            for j in range(8):
                assert sum(matrix[k][i] * matrix[k][j] for k in range(8)) == (4 if i == j else 0)
                assert sum(matrix[i][k] * matrix[j][k] for k in range(8)) == (4 if i == j else 0)
    for basis, route in zip(matrices, routes):
        for i in range(15):
            for j in range(15):
                if i < 8 and j < 8:
                    expected = basis[i][0] * basis[j][0]
                elif i < 8:
                    expected = 2 * basis[i][j - 7]
                elif j < 8:
                    expected = 2 * basis[j][i - 7]
                else:
                    expected = 0
                assert route[i][j] == expected
    header = f'''import Std

/-!
Literal port charts and rho15 matrices from PR442's inherited GEOMETRY.json.
Apache-2.0. Prepared with substantial OpenAI Codex assistance.
Generated by generate_port_data.py; its JSON parser is not kernel verified.
Source SHA-256: {hashlib.sha256(raw).hexdigest()}
Each basis is exactly 2 B_q = [q | 2 complement_columns]; each route is 4 rho15.
Every port carries small kernel-checked column, row and route certificates.
Balanced lookup selects certified records, avoiding one large normalizer cache.
-/
namespace PortGeometry
set_option maxHeartbeats 0
set_option maxRecDepth 100000

inductive IntLookup where
  | leaf : Int → IntLookup
  | node : IntLookup → IntLookup → IntLookup

def intLookup : IntLookup → Nat → Int
  | .leaf n, _ => n
  | .node l r, i => if i % 2 == 0 then intLookup l (i / 2) else intLookup r (i / 2)

def columnDot (b : Fin 8 → Fin 8 → Int) (i j : Fin 8) : Int :=
  b 0 i * b 0 j + (b 1 i * b 1 j + (b 2 i * b 2 j + (b 3 i * b 3 j +
  (b 4 i * b 4 j + (b 5 i * b 5 j + (b 6 i * b 6 j + (b 7 i * b 7 j + 0)))))))

def rowDot (b : Fin 8 → Fin 8 → Int) (i j : Fin 8) : Int :=
  b i 0 * b j 0 + (b i 1 * b j 1 + (b i 2 * b j 2 + (b i 3 * b j 3 +
  (b i 4 * b j 4 + (b i 5 * b j 5 + (b i 6 * b j 6 + (b i 7 * b j 7 + 0)))))))

def routeExpected (b : Fin 8 → Fin 8 → Int) (i j : Fin 15) : Int :=
  if hi : i.val < 8 then
    if hj : j.val < 8 then b ⟨i.val, hi⟩ 0 * b ⟨j.val, hj⟩ 0
    else 2 * b ⟨i.val, hi⟩ ⟨j.val - 7, by omega⟩
  else if hj : j.val < 8 then 2 * b ⟨j.val, hj⟩ ⟨i.val - 7, by omega⟩
  else 0

structure CertifiedPort where
  basis : Fin 8 → Fin 8 → Int
  route : Fin 15 → Fin 15 → Int
  column_correct : ∀ i j, columnDot basis i j = if i = j then 4 else 0
  row_correct : ∀ i j, rowDot basis i j = if i = j then 4 else 0
  route_correct : ∀ i j, route i j = routeExpected basis i j

'''
    lines = [header]
    for index, (b, r) in enumerate(zip(matrices, routes)):
        btree = tree([x for row in b for x in row])
        rtree = tree([r[i][j] if i < 15 and j < 15 else 0
                      for i in range(16) for j in range(16)])
        lines.append(f"def certified{index} : CertifiedPort where\n"
                     f"  basis := fun i j => intLookup {btree} (8 * i.val + j.val)\n"
                     f"  route := fun i j => intLookup {rtree} (16 * i.val + j.val)\n"
                     "  column_correct := by decide +kernel\n  row_correct := by decide +kernel\n"
                     "  route_correct := by decide +kernel\n\n")
    lines.append('''inductive PortLookup where
  | leaf : CertifiedPort → PortLookup
  | node : PortLookup → PortLookup → PortLookup

def lookupPort : PortLookup → Nat → CertifiedPort
  | .leaf p, _ => p
  | .node l r, i => if i % 2 == 0 then lookupPort l (i / 2) else lookupPort r (i / 2)

''')
    names = [f'certified{i}' for i in range(120)] + ['certified0'] * 8
    lines.append('def certifiedTable : PortLookup := ' + tree(names) + '\n\n')
    lines.append('''def portData (port : Fin 120) : CertifiedPort := lookupPort certifiedTable port.val

def doubledBasis (port : Fin 120) : Fin 8 → Fin 8 → Int := (portData port).basis

def quarteredRoute (port : Fin 120) : Fin 15 → Fin 15 → Int := (portData port).route

def expectedQuarteredRoute (port : Fin 120) (i j : Fin 15) : Int :=
  routeExpected (doubledBasis port) i j

def doubledDot (port : Fin 120) (i j : Fin 8) : Int := columnDot (doubledBasis port) i j

theorem doubled_orthogonal_entries (port : Fin 120) (i j : Fin 8) :
    doubledDot port i j = if i = j then 4 else 0 :=
  (portData port).column_correct i j

theorem quarteredRoute_exact (port : Fin 120) (i j : Fin 15) :
    quarteredRoute port i j = expectedQuarteredRoute port i j :=
  (portData port).route_correct i j

end PortGeometry
#print axioms PortGeometry.doubled_orthogonal_entries
#print axioms PortGeometry.quarteredRoute_exact
''')
    return ''.join(lines)


ROW_CERTIFICATE = '''import PortData

/-! Reverse orthogonality extracted from the checked exact source table.
Apache-2.0. Prepared with substantial OpenAI Codex assistance. -/
namespace PortGeometry

def doubledRowDot (port : Fin 120) (i j : Fin 8) : Int := rowDot (doubledBasis port) i j

theorem doubled_row_orthogonal_entries (port : Fin 120) (i j : Fin 8) :
    doubledRowDot port i j = if i = j then 4 else 0 :=
  (portData port).row_correct i j

end PortGeometry
#print axioms PortGeometry.doubled_row_orthogonal_entries
'''


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("geometry", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("PortData.lean"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(args.geometry)
    if args.check:
        assert args.output.read_text() == expected, "PortData.lean does not match supplied source"
        assert args.output.with_name("PortRowData.lean").read_text() == ROW_CERTIFICATE
    else:
        args.output.write_text(expected)
        args.output.with_name("PortRowData.lean").write_text(ROW_CERTIFICATE)


if __name__ == "__main__":
    main()
