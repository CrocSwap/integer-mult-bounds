"""Transport an explicit BORROW-WORD to the native canonical frame-id form, with warps, and replay it exactly.

Anticipatory dirty borrowing is the construction of PR2226 (Cinna Davis, @1337isnot1337, with OpenAI Codex
assistance; Apache-2.0): a retiring helper's register is lent to a later helper through a monomial Clifford
logical reference change K_G ("warp"), the retired field's value being replaced by K_G z. The explicit
chronological BORROW-WORD (canonical coordinates, literal frames, warps, cold restoration, inverse cleanup
with private zero buffers) is the builder output of the Borrow campaign (P1/P2).  This script is the
transport stage of the native chain (the analogue of hpe_audit_and_transport.py): it never trusts the builder.
It replays the program in the free operator algebra generated by the warps over every arbitrary input,
in BOTH orientations (forward and inverse-transpose), checks every frame chain and the paid profile, compacts
the helper registers to R' = R - k, and writes the native CANONICAL-WORD.

usage: bw_transport.py BORROW-WORD.json[.gz] OUT_DIR
"""
if not __debug__:
    raise RuntimeError('assertions must remain enabled')   # every check of this stage is an assert
import argparse
import copy
import gzip
import hashlib
import json
import sys
import time
from collections import Counter
from fractions import Fraction as Q
from pathlib import Path


def read(path):
    data = path.read_bytes()
    return json.loads(gzip.decompress(data) if path.suffix == '.gz' else data)


def basis(vs):
    pivots = {}
    for x in vs:
        for k in sorted(pivots, reverse=True):
            if x >> k & 1:
                x ^= pivots[k]
        if x:
            k = x.bit_length() - 1
            for j in pivots:
                if pivots[j] >> k & 1:
                    pivots[j] ^= x
            pivots[k] = x
    return tuple(pivots[k] for k in sorted(pivots, reverse=True))


def span(b):
    s = {0}
    for x in b:
        s |= {t ^ x for t in s}
    return frozenset(s)


def rank_of(vs):
    return len(basis(vs))


def solve_G(cols, h):
    """G given as images of e_i; returns (invertible?, image-of-subspace function)."""
    def lin(x):
        out = 0
        for i, c in enumerate(cols):
            if x >> i & 1:
                out ^= c
        return out
    return lin, rank_of(cols) == h


# ---- free operator algebra over the warps ------------------------------------------------------------------
def add_row(dst, src, c):
    for key, value in list(src.items()):
        z = dst.get(key, Q(0)) + c * value
        if z:
            dst[key] = z
        elif key in dst:
            del dst[key]


def warp_row(row, op):
    out = {}
    for (var, word), value in row.items():
        word = word[1:] if word and word[0] == -op else (op,) + word
        out[var, word] = value
    return out


def is_dyadic(q):
    return q.denominator & (q.denominator - 1) == 0


def gate_regs(e):
    if e[0] == 'add':
        return [e[1], e[2]]
    if e[0] == 'scale':
        return [e[1]]
    raise AssertionError(e[0])


def dual(e):
    e = list(e)
    if e[0] == 'add':
        e[1], e[2] = e[2], e[1]
        e[3] = -e[3]
    elif e[0] == 'scale':
        e[2], e[3] = e[3], e[2]
    return e


def apply_gate(e, rows, back):
    if back:
        e = dual(e)
    if e[0] == 'scale':
        q = Q(e[2], e[3])
        assert q
        rows[e[1]] = {j: q * x for j, x in rows[e[1]].items()}
    else:
        assert e[1] != e[2]
        add_row(rows[e[1]], rows[e[2]], Q(e[3], e[4]))


def run(word_path, out):
    t0 = time.monotonic()
    word = read(word_path)
    assert word['kind'] == 'BORROW-WORD'
    v, h, R0 = word['report']['v'], word['report']['h'], word['report']['R']
    assert h == 9 and v == 112
    n0 = 2 * v + R0
    removed = sorted(word['removed'])
    assert all(2 * v <= r < n0 for r in removed) and len(set(removed)) == len(removed)
    k = len(removed)
    kept = [r for r in range(n0) if r not in set(removed)]
    newid = {r: i for i, r in enumerate(kept)}
    n = len(kept)
    R = R0 - k
    assert n == 2 * v + R
    Zbase = n0                                       # builder convention: zero buffer of restored c is register n0 + c
    ports = word['ports']
    assert len(set(ports)) == v
    full = tuple(1 << i for i in range(h - 1, -1, -1))
    frames, frame_ids = [(), full], {(): 0, full: 1}

    def fid(vectors):
        frame = basis(vectors)
        if frame not in frame_ids:
            frame_ids[frame] = len(frames)
            frames.append(frame)
        return frame_ids[frame]

    def R_(r):                                       # register -> new register (int) or ['Z', c]
        if isinstance(r, list):
            return r
        if r >= Zbase:
            return ['Z', newid[r - Zbase]]
        return newid[r]

    start = [fid([p]) for p in ports] + [0] * (v + R)
    for r, frame in word['start_extra'].items():
        assert 2 * v <= int(r) < n0 and int(r) not in set(removed)
        start[newid[int(r)]] = fid(frame)
    final = [1] * v + [fid(x for x in range(1, 1 << h) if (x & p).bit_count() % 2 == 0) for p in ports] + [1] * R
    helper_final = {}
    for r, frame in word['helper_final'].items():
        assert 2 * v <= int(r) < n0 and int(r) not in set(removed)
        helper_final[newid[int(r)]] = fid(frame)
        final[newid[int(r)]] = helper_final[newid[int(r)]]
    zero_buffers = sorted(helper_final)              # every restored (hyperplane-ended) helper is replaced by a private zero buffer in the FULL cleanup

    def gate(e):
        e = copy.deepcopy(e)
        # Seed39: literal A-phase warp after entry adapters. All inherited
        # free-algebra, frame-image, profile and phase checks remain active.
        if e[0] == 'warp':
            assert len(e) == 5
            return ['warp', R_(e[1]), e[2], fid(e[3]), fid(e[4])]
        if e[0] == 'add':
            e[1], e[2] = R_(e[1]), R_(e[2])
        else:
            e[1] = R_(e[1])
        e[-1] = None if e[-1] is None else fid(e[-1])
        return e

    # warps: operator table; op id = position + 1; G given by images of the basis vectors
    warps = []
    for i, (pos, lender, G, frm, to) in enumerate(word['warps']):
        warps.append({'op': i + 1, 'B_pos': pos, 'lender': newid[lender], 'G_columns': list(G),
                      'from_frame': fid(frm), 'to_frame': fid(to)})
    byp = {}
    for w_ in warps:
        byp.setdefault(w_['B_pos'], []).append(w_)

    def warp_event(r, op, f0, f1):
        return ['warp', r, op, f0, f1]

    # compensation (zero frame): initial corrections first, as twisted additions  t += c * W(s)
    pre = []
    for term in word['initial_corrections']:
        q = Q(term['coefficient'])
        pre.append(['tadd', newid[term['target']], newid[term['source']], list(term['operator_word']),
                    q.numerator, q.denominator, 0])
    precondition = pre + [gate(e) for e in word['precondition']]       # the formal initial corrections come first (PR2226 order)
    compensation = [gate(e) for e in word['compensation']]
    A = [gate(e) for e in word['A']]
    cut = [gate(e) for e in word['cut']]
    B = []
    for p in range(len(word['B']) + 1):
        for w_ in sorted(byp.get(p, []), key=lambda x: x['op']):
            B.append(warp_event(w_['lender'], w_['op'], w_['from_frame'], w_['to_frame']))
        if p < len(word['B']):
            B.append(gate(word['B'][p]))
    assert sum(1 for e in B if e[0] == 'warp') == len(warps)
    tail = [gate(e) for e in word['restore']]
    cleanup = []
    for e in word['cleanup']:
        if e[0] == 'warp':
            cleanup.append(warp_event(R_(e[1]), e[2], 1, 1))
            assert basis(e[3]) == full
        else:
            cleanup.append(gate(e))
    centers = [newid[r] for r in word['centers']]
    center_frames = [fid(f) for f in word['center_frames']]
    levels = {str(t): fid(f) for t, f in word['target_levels'].items()}

    canonical = dict(h=h, v=v, R=R, ports=ports, frames=frames, start=start, final=final,
                     precondition=precondition, compensation=compensation, A=A, cut=cut, B=B, tail=tail,
                     cleanup=cleanup, centers=centers, center_frames=center_frames, target_levels=levels,
                     warps=warps, zero_buffers=zero_buffers, removed=removed, helper_origin=kept[2 * v:],
                     borrow=dict(k=k, base=word.get('base'), original_helpers=R0))
    # ---- exact scalar replay in the free algebra over the warps (both orientations) -----------------------------------
    nz = len(zero_buffers)

    def regkey(r):
        return tuple(r) if isinstance(r, list) else ('L', r)

    def expand_tadd(e):
        _, t, s, wordops, a, b, f = e
        ev = [warp_event(s, op, 0, 0) for op in reversed(wordops)]
        ev.append(['add', t, s, a, b, 0])
        ev += [warp_event(s, -op, 0, 0) for op in wordops]
        return ev

    def program():
        yield 'pre', [x for e in precondition + compensation for x in (expand_tadd(e) if e[0] == 'tadd' else [e])]
        yield 'A', A
        yield 'A', cut
        yield 'B', B
        yield 'tail', tail
        yield 'cleanup', cleanup

    def fullprog():
        return [(part, e) for part, es in program() for e in es]
    prog = fullprog()
    for back in (False, True):
        rows = {regkey(r): {(r, ()): Q(1)} for r in range(n)}
        for c in zero_buffers:
            rows[('Z', c)] = {}
        for part, e in prog:
            if e[0] == 'warp':
                key = ('L', e[1]) if not isinstance(e[1], list) else tuple(e[1])
                rows[key] = warp_row(rows[key], e[2])
            else:
                if e[0] == 'add':
                    src, dst = regkey(e[2]), regkey(e[1])
                    a, b = e[3], e[4]
                    if back:
                        src, dst, a = dst, src, -a
                    assert src != dst
                    add_row(rows[dst], rows[src], Q(a, b))
                else:
                    key = regkey(e[1])
                    a, b = (e[3], e[2]) if back else (e[2], e[3])
                    q = Q(a, b)
                    assert q
                    rows[key] = {j: q * x for j, x in rows[key].items()}
        expected = {regkey(r): {(r, ()): Q(1)} for r in range(n)}
        for t in range(v):
            if back:
                expected[('L', t)][(v + t, ())] = Q(-1)
            else:
                expected[('L', v + t)][(t, ())] = Q(1)
        for c in zero_buffers:
            expected[('Z', c)] = {}
        bad = [key for key in expected if rows[key] != expected[key]]
        assert not bad, ('arbitrary-input endpoint (free warp algebra)', back, bad[:8])
    # dyadic primitives
    for part, e in prog:
        if e[0] == 'add':
            assert is_dyadic(Q(e[3], e[4]))
        elif e[0] == 'scale':
            q = Q(e[2], e[3])
            a = abs(q.numerator)
            assert is_dyadic(q) and a and a & (a - 1) == 0

    wrapped_regs = {r for r in range(2 * v, n) if start[r] != 0 or final[r] != 1}   # entering or hyperplane-ended helpers carry wrappers
    # ---- frame chains, paid profile, edges, warps -------------------------------------------------------------------
    contains = lambda a, b: basis(frames[a] + frames[b]) == tuple(frames[b])
    cur = start.copy()
    paid, edges = Counter(), set()
    wsum = {w_['op']: w_ for w_ in warps}
    G_of = {}
    for w_ in warps:
        lin, inv_ = solve_G(w_['G_columns'], h)
        assert inv_, ('non-invertible G', w_['op'])
        img = basis([lin(x) for x in frames[w_['from_frame']]])
        assert img == tuple(frames[w_['to_frame']]), ('G does not map the from frame onto the to frame', w_['op'])
        assert len(frames[w_['from_frame']]) == len(frames[w_['to_frame']])
        G_of[w_['op']] = lin
    warp_edges = set()

    def regs_of(e):
        return [r for r in gate_regs(e) if not isinstance(r, list)]

    def climb(r, f):
        old = cur[r]
        assert contains(old, f), ('nonmonotone', r, old, f)
        if old != f:
            degree = len(frames[f]) - len(frames[old])
            paid[degree] += 1
            edges.add((old, f))
            cur[r] = f

    def do_warp(e):
        _, r, op, f0, f1 = e
        if isinstance(r, list):
            assert r[0] == 'Z'
            assert f0 == f1 == 1
            return
        assert cur[r] == f0, ('warp frame mismatch', r, op, cur[r], f0)
        a = abs(op)
        lin = G_of[a]
        if op > 0:
            ok = basis([lin(x) for x in frames[f0]]) == tuple(frames[f1])
        else:
            ok = basis([lin(x) for x in frames[f1]]) == tuple(frames[f0])
        assert ok, ('warp G does not carry the frame', op, f0, f1)
        cur[r] = f1
        warp_edges.add((1 if op > 0 else -1, a, f0, f1))

    # zero-frame phase
    for e in precondition + compensation:
        if e[0] == 'tadd':
            assert start[e[2]] == 0 and start[e[1]] == 0 and e[-1] == 0 and e[2] not in set(wrapped_regs) and all(op != 0 for op in e[3])
            for ev in expand_tadd(e):
                if ev[0] == 'warp':
                    do_warp(ev)                      # frame 0 -> 0: K_G itself is the physical operator
            continue
        for r in regs_of(e):
            assert start[r] == 0 and e[-1] == 0, ('zero-frame precondition on a nonzero entrance', e)
    for part in ('A', 'B'):
        if part == 'B':
            assert all(cur[r] == f for r, f in zip(centers, center_frames))
            assert all(cur[v + t] == levels.get(str(t), 0) for t in range(v))
            for r, frame in zip(centers, center_frames):
                served = {levels.get(str(e[1] - v), 0) for e in cut if e[2] == r}
                old = frame
                for f in sorted(served, key=lambda f: -len(frames[f])):
                    assert contains(f, old)
                    if old != f:
                        paid[len(frames[old]) - len(frames[f])] += 1
                        edges.add((old, f))
                        edges.add((f, old))
                        old = f
        for e in (A if part == 'A' else B):
            if e[0] == 'warp':
                do_warp(e)
            else:
                for r in regs_of(e):
                    climb(r, e[-1])
    for e in tail:
        for r in regs_of(e):
            climb(r, e[-1])
    for r, f in enumerate(final):
        climb(r, f)
    for e in cleanup:
        if e[0] == 'warp':
            do_warp(e)
            continue
        for r in gate_regs(e):
            if isinstance(r, list):
                assert r[0] == 'Z' and r[1] in set(zero_buffers) and e[-1] == 1
            else:
                assert final[r] == 1 and e[-1] == 1, ('cleanup on a non-FULL end', e)
    assert all(len(frames[final[r]]) < h for r in zero_buffers)
    assert set(zero_buffers) == set(helper_final)
    rep = word['report']
    assert dict(paid) == {int(r): c for r, c in rep['local_profile'].items()}, ('paid profile differs', dict(paid), rep['local_profile'])
    canonical['local_profile'] = dict(sorted(paid.items()))
    canonical['edges'] = sorted(edges)
    canonical['warp_edges'] = sorted(warp_edges)
    out.mkdir(parents=True, exist_ok=False)
    payload = json.dumps(canonical, sort_keys=True, separators=(',', ':')).encode()
    (out / 'CANONICAL-WORD.json.gz').write_bytes(gzip.compress(payload, mtime=0))
    raw = word_path.read_bytes()
    (out / 'FULL-WORD.json.gz').write_bytes(gzip.compress(gzip.decompress(raw) if word_path.suffix == '.gz' else raw, mtime=0))
    receipt = dict(status='PASS_BORROW_WORD_FREE_ALGEBRA_ALL_COLUMNS_AND_NATIVE_FRAMES',
                   input_content_sha256=hashlib.sha256(gzip.decompress(raw) if word_path.suffix == '.gz' else raw).hexdigest(),
                   canonical_content_sha256=hashlib.sha256(payload).hexdigest(),
                   live_columns_each_orientation=n, helpers=R, original_helpers=R0, removed_helpers=k,
                   zero_buffers=nz, warps=len(warps), warp_events=sum(e[0] == 'warp' for part, e in prog),
                   initial_corrections=len(word['initial_corrections']),
                   scalar_operations=len([1 for p, e in prog if e[0] != 'warp']),
                   local_profile=dict(sorted(paid.items())), local_rank_mass=sum(r * z for r, z in paid.items()),
                   widths=[len(frames[final[r]]) - len(frames[start[r]]) for r in range(2 * v, n)],
                   frames=len(frames), directed_edges=len(edges), warp_edge_classes=len(warp_edges),
                   seconds=time.monotonic() - t0,
                   scope='Fresh exact forward and inverse-transpose replay over a free noncommutative warp algebra on every arbitrary input, native frame chains, dyadic primitives, zero buffers returned to zero. Physical Clifford exactness of every warp is checked by the local replay and the phase recipes.')
    (out / 'SCALAR-FRAME-AUDIT.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps({k_: x for k_, x in receipt.items() if k_ != 'widths'}, indent=2), flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('word', type=Path)
    ap.add_argument('out', type=Path)
    a = ap.parse_args()
    run(a.word, a.out)
