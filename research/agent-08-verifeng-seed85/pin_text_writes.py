#!/usr/bin/env python3
"""Pin text-write codecs and newlines in the ``scripts/`` generator surface.

Text-mode writes without an explicit ``encoding=``/``newline=`` are platform
dependent: the codec is the locale's (cp1252 on many Windows hosts) and
``'\\n'`` is translated to ``os.linesep`` (CRLF on Windows).  Both diverge from
the repository's UTF-8/LF reference bytes, so a regenerated certificate or
patch is byte-different on such hosts even when its content is equal.

This tool is both the mechanical fixer and the regression lint used by
``tests/test_locale_reproducibility.py``:

    python3 -B research/agent-08-verifeng-seed85/pin_text_writes.py --check
    python3 -B research/agent-08-verifeng-seed85/pin_text_writes.py --fix

``--check`` exits nonzero while any text write in ``scripts/`` still lacks
``encoding='utf-8', newline='\\n'``.  ``--fix`` inserts exactly those missing
keyword arguments (nothing else changes).  Binary writes and reads are out of
scope.
"""
import argparse
import ast
import json
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SURFACE = ROOT / 'scripts'
PIN = "encoding='utf-8', newline='\\n'"


def frozen_scripts():
    """Scripts whose bytes are frozen by review evidence.

    Frozen by path: named in the selected record, a checkpoint, or the
    selected source manifest.  Frozen by digest: their sha256 appears in a
    frozen receipt under docs/research (for example the followup arithmetic
    receipt pins the bytes of its independent arithmetic source).  This tool
    must not touch either kind: the pinned hashes live in evidence that is not
    regenerated by the checks themselves.
    """
    def refs(obj, out):
        if isinstance(obj, dict):
            for k, v in obj.items():
                if isinstance(k, str) and k.startswith('scripts/'):
                    out.add(k)
                refs(v, out)
        elif isinstance(obj, list):
            for v in obj:
                refs(v, out)
        elif isinstance(obj, str) and obj.startswith('scripts/'):
            out.add(obj)

    out = set()
    pins = [ROOT / 'certificates/selected-result.json',
            ROOT / 'research/community-frontier799-audit/SELECTED-SOURCE.json']
    pins += sorted((ROOT / 'certificates/checkpoints').glob('*.json'))
    for pin in pins:
        if pin.exists():
            refs(json.loads(pin.read_text(encoding='utf-8')), out)

    import re
    digest_re = re.compile(r'\b[0-9a-f]{64}\b')
    frozen_digests = set()
    for receipt in sorted((ROOT / 'docs/research').glob('*.json')):
        frozen_digests.update(digest_re.findall(receipt.read_text(encoding='utf-8')))
    for path in SURFACE.rglob('*.py'):
        if '__pycache__' in path.parts:
            continue
        if sha256(path.read_bytes()).hexdigest() in frozen_digests:
            out.add(path.relative_to(ROOT).as_posix())
    return out


def is_write_call(node):
    """(kind, mode) for text-write calls: write_text, or open()/Path.open()."""
    func = node.func
    if isinstance(func, ast.Attribute) and func.attr == 'write_text':
        return 'write_text', None
    if isinstance(func, ast.Name) and func.id == 'open':
        owner = 'open'
    elif isinstance(func, ast.Attribute) and func.attr == 'open':
        owner = 'open'
    else:
        return None, None
    mode = None
    if len(node.args) >= 2 and isinstance(node.args[1], ast.Constant) \
            and isinstance(node.args[1].value, str):
        mode = node.args[1].value
    for kw in node.keywords:
        if kw.arg == 'mode' and isinstance(kw.value, ast.Constant) \
                and isinstance(kw.value.value, str):
            mode = kw.value.value
    if mode is None:
        return 'open-unknown-mode', None
    if 'b' in mode:
        return None, None
    if any(c in mode for c in 'wax'):
        return 'open', mode
    return None, None


def scan(path):
    """Return (fixable, unknown) call records for one file."""
    raw = path.read_bytes()
    tree = ast.parse(raw, filename=str(path))
    fixable, unknown = [], []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        kind, _mode = is_write_call(node)
        if kind is None:
            continue
        if kind == 'open-unknown-mode':
            unknown.append(node)
            continue
        keywords = {kw.arg for kw in node.keywords}
        missing = [part for part, name in (("encoding='utf-8'", 'encoding'),
                                           ("newline='\\n'", 'newline'))
                   if name not in keywords]
        if missing:
            fixable.append((node, missing))
    return raw, fixable, unknown


def call_insert_offset(raw, node):
    """Byte offset of the closing parenthesis of the call."""
    lines = raw.splitlines(keepends=True)
    offset = sum(len(line) for line in lines[:node.end_lineno - 1])
    return offset + node.end_col_offset - 1


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    p.add_argument('--fix', action='store_true')
    a = p.parse_args()
    if not (a.check or a.fix):
        p.error('choose --check or --fix')
    total, unknown_total, changed, frozen_hits = 0, 0, 0, []
    frozen = frozen_scripts()
    for path in sorted(SURFACE.rglob('*.py')):
        if '__pycache__' in path.parts:
            continue
        rel = path.relative_to(ROOT).as_posix()
        if rel in frozen:
            frozen_hits.append(rel)
            continue
        raw, fixable, unknown = scan(path)
        unknown_total += len(unknown)
        if not fixable:
            continue
        total += len(fixable)
        if a.fix:
            text = raw
            for node, missing in sorted(fixable, key=lambda item: item[0].lineno,
                                        reverse=True):
                at = call_insert_offset(raw, node)
                insert = (', ' + ', '.join(missing)).encode('ascii')
                text = text[:at] + insert + text[at:]
            path.write_bytes(text)
            changed += 1
        else:
            for node, missing in fixable:
                print(f'{path.relative_to(ROOT).as_posix()}:{node.lineno}: '
                      f'missing {", ".join(missing)}')
    verb = 'pinned' if a.fix else 'unpinned'
    print(f'{total} {verb} text writes in scripts/ '
          f'({unknown_total} open() calls with non-literal mode left alone, '
          f'{len(frozen_hits)} frontier-frozen scripts skipped)')
    if a.check and total:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
