"""Compose the R822 K3 bit supplier with a freshly verified complex supplier.

Prepared with OpenAI Codex assistance; Apache-2.0. The finite supplier inputs
must be independently regenerated by the calling verifier. This refines the
assembly parameters; it does not strengthen the complex supplier theorem.
The caller must freshly replay the complex supplier under its own source-pinned
checker and moment model. This module validates their common interface and
recorded strict moment bounds; it does not certify the complex supplier anew.

Usage: compose_suppliers.py PARENT BIT_JSON FINITE_JSON SUPPLIER_JSON OUTPUT_JSON
"""
from fractions import Fraction as Q
from pathlib import Path
import hashlib
import importlib.util
import json
import sys

def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module

def encode(x):
    if isinstance(x, Q): return str(x)
    if isinstance(x, dict): return {str(k): encode(v) for k,v in x.items()}
    if isinstance(x, (list,tuple)): return [encode(v) for v in x]
    return x

def run(parent, priced, finite, supplier):
    pricing = Path(parent)/'code/pricing'
    moment = load('e8_assembly_moment', pricing/'moment.py')
    other = load('e8_assembly_base_two', pricing/'base_two_moment.py')
    outer = load('e8_assembly_outer', pricing/'outer.py')
    fk = load('e8_assembly_finite', Path(parent)/'code/bit/checkers/finite_k.py')
    H = {int(k):v for k,v in priced['normalized_histogram'].items()}
    m, stock = priced['m'], priced['W']
    c = Q(priced['bit_coarse'])
    assert supplier['status'] == 'PASS_FRESH_NINE_STAGE_COMPLEX_INTERFACE'
    b = Q(supplier['b'])
    assert priced['K']==3 and priced['stages']==7 and m==56 and priced['T']==7
    depth=priced.get('halving_degree',1)
    assert depth in (1,2) and 0<max(H)<m
    least=1
    while m**least<=2*max(H)**least:least+=1
    assert depth==least
    assert finite['row_reserve'].get('halving_degree',1)==depth
    assert finite['row_reserve']['internal_coefficient']==depth*(m*m+1)
    assert finite['row_reserve']['external_complex_coefficient']==20161
    assert sum(H.values())==finite['positive_rank_children']
    assert sum(r*n for r,n in H.items())==finite['rank_mass']
    grid = 10**27
    eta, beta = Q(1,10**24), Q(1,10**9)
    cap=(1-beta)*b
    ticks=(cap-Q(1,grid))*grid
    selected=min(c,Q(ticks.numerator//ticks.denominator,grid))
    assert 0 < selected <= c < 1 and selected < cap
    binding = 'bit' if selected == c else 'complex'
    if binding == 'complex': assert 0 < cap-selected <= Q(2,grid)
    interval=moment.moment(H,m,stock,selected,True)
    assert interval[1]<1
    _, upper=other.moment(m,stock,list(H.items()),selected)
    fallback=32*m*m*sum(H.values())
    _, bad=other.moment(m,stock,[(1,fallback)],selected)
    assert upper+Q(1,10**16)*bad<1
    coefficient=finite['coefficient']
    assert 1<=coefficient<2**80
    chain=[Q(384599,10**10)]; cutoffs=[]
    for index in range(8):
        old=chain[-1]
        new=(1-selected)*selected+selected*old
        assert old<new<selected<1-new
        gaps=dict(atom=selected-new,borrowing=1-new-selected,
                  remainder=1-new-selected*(1-old),stock=1-selected)
        delta=min(gaps.values()); assert delta>0
        cutoff=fk.cutoff_log2(delta,coefficient)
        assert Q(cutoff)*delta**2>=36
        assert Q(cutoff)*delta>=2*(4+(coefficient-1).bit_length())
        cutoffs.append(dict(stage=index+1,gaps=gaps,minimum_gap=delta,
                            cutoff_log2=cutoff,charged_coefficient=coefficient))
        chain.append(new)
    bridge=dict(proof='PROOF.md',representation='Exact powers with source-bound finite overcharges',
                semantic=dict(G=dict(base=2,exponent=30000),E=dict(base=2,exponent=100000),
                              B_upper=dict(base=2,exponent=100001),C0=dict(base=2,exponent=210000),
                              C1=1,strict_literal_gap=1,induction_gap_lower=1),
                rows=dict(coefficient=20161,degree=10**6,suffix_slope=4*10**6,
                          degree_gap=Q(10**6)-Q(51*20161,25)))
    bit=chain[-1];q=bit*(1-2*eta);minimum=(1-eta)*q/(1+q)
    ticks=minimum*grid;kappa=Q((ticks.numerator-1)//ticks.denominator,grid)
    assembly=outer.assembly(bit,b,bridge,kappa,eta=eta,beta=beta)
    assert len(assembly['strict_constraints'])==47
    assert min(assembly['strict_constraints'].values())>0
    try: outer.assembly(bit,b,bridge,kappa+Q(1,grid),eta=eta,beta=beta)
    except AssertionError: pass
    else: raise AssertionError('adjacent assembly grid point admitted')
    try: outer.assembly(cap,b,bridge,kappa,eta=eta,beta=beta)
    except AssertionError as err: assert 'leaf_saving_above_bit' in str(err)
    else: raise AssertionError('complex leaf cap admitted')
    return encode(dict(status='PASS_EXACT_E8_FRESH_SUPPLIER_COMPOSITION',eta=eta,beta=beta,
                       grid_denominator=grid,bootstrap_steps=8,bit_coarse=c,complex_coarse=b,
                       selected_saving=selected,selected_moment_interval=interval,
                       independent_moment_upper=upper+Q(1,10**16)*bad,chain=chain,
                       finite_cutoffs=cutoffs,assembly=assembly,kappa=kappa,
                       binding=binding, bit_halving_degree=depth,
                       internal_restored_row_coefficient=depth*(m*m+1),
                       complex_interface=supplier,
                       adjacent_grid_rejected=True,complex_leaf_cap_rejected=True))

if __name__=='__main__':
    parent,priced,finite,supplier,out=map(Path,sys.argv[1:])
    result=run(parent,json.loads(priced.read_text()),json.loads(finite.read_text()),
               json.loads(supplier.read_text()))
    result['input_sha256']={name:hashlib.sha256(path.read_bytes()).hexdigest()
                           for name,path in [('bit',priced),('finite',finite),('complex_supplier',supplier)]}
    out.write_text(json.dumps(result,indent=2,sort_keys=True)+'\n')
    print(result['status'],result['binding'],result['kappa'],float(Q(result['kappa'])))
