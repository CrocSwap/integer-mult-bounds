#!/usr/bin/env python3
"""Emit the literal PR442 bit schedule and exterior route blocks for PendingDerivation.lean.

Offline provenance bridge, not a kernel-verified JSON parser. The Lean modules
derive the pending coordinates from these literals; nothing here computes a
pending set. Douglas Colkitt, with Claude (Anthropic) assistance. Apache-2.0.

usage: generate_pending_schedule.py [--check]
"""
import argparse, gzip, hashlib, json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent / 'lean-multi-host-source'   # PR540's pinned inputs
OUT = HERE / 'PendingScheduleData.lean'


def load(name):
    versions = json.loads((ROOT / 'source-versions.json').read_text())['inputs'][name]
    blob = (ROOT / 'inputs' / name).read_bytes()
    assert hashlib.sha256(blob).hexdigest() == versions['sha256_compressed'], name
    raw = gzip.decompress(blob)
    assert hashlib.sha256(raw).hexdigest() == versions['sha256_uncompressed'], name
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def render():
    t, t_sha = load('hosted-template.json.gz')
    g, g_sha = load('geometry.json.gz')
    assert t['geometry_sha256'] == g_sha and (t['m'], t['h']) == (64, 8) == (g['m'], g['h'])
    events = []
    for e in t['schedule']:
        k = e['kind']
        if k == 'local_cover_sweep':
            events.append(f'.local {e["stage"]} {e["pair"]}')
        elif k == 'bridge':
            events.append(f'.bridge {e["dst"]} {e["src"]}')
        elif k == 'idle':
            # levels are stored shifted by one so that source level -1 is 0
            events.append(f'.idle {e["idx"]} {e["pair"]} {e["rank"]} {e["source_level"] + 1} {e["target_level"] + 1}')
        else:
            assert k == 'exchange'
            events.append('.exchange')
    blocks = {}
    for port in g['ports']:
        for r in port['routes']:
            ax = r['axes']
            assert ax[:8] == list(range(8))
            if r['stage'] == 0:
                assert ax == list(range(8)) and r.get('identity')
            else:
                assert blocks.setdefault(r['stage'], ax[8:]) == ax[8:], 'ports disagree'
    assert len(g['ports']) == 120 and sorted(blocks) == list(range(1, 9))
    calls = [c for c in t['calls'] if c['stage'] == 2 and c['replica'] == 0]
    assert len(calls) == 1 and calls[0]['pair'] == 0 and calls[0]['orientation'] == 'forward'
    lst = lambda xs, ind: '[\n' + ',\n'.join(ind + x for x in xs) + ']'
    return f'''import Std

/-! Literal PR442 hosted bit schedule and PR434 exterior route blocks.
Generated by generate_pending_schedule.py from ../lean-multi-host-source/inputs/hosted-template.json.gz
(uncompressed sha256 {t_sha}) and inputs/geometry.json.gz
(uncompressed sha256 {g_sha}). The extractor is not kernel verified; every
port's routes agree on the exterior blocks. Idle levels are shifted by one.
Apache-2.0. Douglas Colkitt, with Claude (Anthropic) assistance. -/
namespace PendingSchedule

inductive Event where
  | local (stage pair : Nat)
  | bridge (dst src : Nat)
  /-- `idle idx pair rank (sourceLevel + 1) (targetLevel + 1)` -/
  | idle (idx pair rank source target : Nat)
  | exchange
  deriving DecidableEq, Repr

def schedule : List Event := {lst(events, '  ')}

/-- Exterior axes of the stage-s route (s = 1..8), identical for all 120 ports. -/
def exteriorBlocks : List (List Nat) := {lst([json.dumps(blocks[s]).replace(' ', '') .replace(',', ', ') for s in range(1, 9)], '  ')}

/-- The selected invocation of PR540: stage 2, replica 0, pair 0, forward. -/
def selectedStage : Nat := 2
def selectedPair : Nat := 0

end PendingSchedule
'''


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true'); a = ap.parse_args()
    text = render()
    if a.check:
        assert OUT.read_text() == text, 'PendingScheduleData.lean differs from the pinned inputs'
        print('PASS: PendingScheduleData.lean matches the pinned schedule and geometry')
    else:
        OUT.write_text(text); print('wrote', OUT.name)


if __name__ == '__main__':
    main()
