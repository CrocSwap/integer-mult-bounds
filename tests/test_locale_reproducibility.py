#!/usr/bin/env python3
"""Cross-platform byte/codec reproducibility guards for the verification suite.

Three properties are pinned here, all derived from concrete failures observed
on a Windows/cp1252 host at base commit 91a2094f:

1. Locale independence of the offline checks.  ``ranked-pair-check`` and
   ``machine-transfer-check`` decode UTF-8 Lean sources; without an explicit
   codec (or UTF-8 mode) they crash under any non-UTF-8 locale.
2. Byte-stable generator output.  A certificate regenerated by a ``scripts/``
   generator must equal the tracked bytes exactly, not merely its JSON value:
   default text writes translate ``'\\n'`` to ``os.linesep`` (CRLF on Windows),
   so every regenerated certificate came out byte-different on Windows.
3. Static pinning of generator text writes to ``encoding='utf-8'``,
   ``newline='\\n'`` so property 2 cannot silently regress.

Run standalone:
    python3 -B -m unittest discover -s tests -p 'test_locale_reproducibility.py' -v
"""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]


def hostile_env():
    """An environment whose text codec is not UTF-8 where the platform allows.

    On Windows the ANSI code page (cp1252 here) is already non-UTF-8.  On
    POSIX, LC_ALL=C plus PYTHONCOERCECLOCALE=0 forces the ASCII codec.  Any
    UTF-8-mode switch is removed so the run cannot quietly rely on it.
    """
    env = dict(os.environ)
    for key in ('PYTHONUTF8', 'PYTHONIOENCODING', 'PYTHONCOERCECLOCALE'):
        env.pop(key, None)
    env['PYTHONCOERCECLOCALE'] = '0'
    env['LC_ALL'] = 'C'
    env['LANG'] = 'C'
    return env


def run_py(args, env=None):
    return subprocess.run([sys.executable, '-B'] + args, cwd=ROOT, env=env,
                          capture_output=True, text=True, encoding='utf-8',
                          errors='replace')


class LocaleIndependenceTest(unittest.TestCase):
    def test_ranked_pair_check_passes_under_hostile_locale(self):
        proc = run_py(['research/ranked-pair-verification/verify.py'], hostile_env())
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn('PASS ranked pair', proc.stdout)

    def test_machine_transfer_check_passes_the_way_make_runs_it(self):
        # make's machine-transfer-check pins UTF-8 mode because the package's
        # publication manifest freezes its checker sources byte for byte.
        makefile = (ROOT / 'Makefile').read_text(encoding='utf-8')
        self.assertRegex(makefile, r'PYTHONUTF8=1',
                         'Makefile must pin UTF-8 mode for the frozen packages')
        env = hostile_env()
        env['PYTHONUTF8'] = '1'
        proc = run_py(['research/machine-transfer-verification/verify.py'], env)
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn('PASS machine-transfer offline checkpoint', proc.stdout)


class ByteStableGenerationTest(unittest.TestCase):
    def test_regenerated_certificate_is_byte_identical(self):
        # audit_cube_cores is a cheap real generator from `make verify-research`.
        certificate = ROOT / 'certificates/cube-core-family.json'
        before = certificate.read_bytes()
        try:
            proc = run_py(['scripts/audit_cube_cores.py'], hostile_env())
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            after = certificate.read_bytes()
            self.assertEqual(before, after,
                             'regenerated certificate is not byte-identical to '
                             'the tracked bytes (newline/codec translation?)')
        finally:
            certificate.write_bytes(before)

    def test_generator_text_writes_pin_encoding_and_newline(self):
        proc = run_py(['research/agent-08-verifeng-seed85/pin_text_writes.py', '--check'])
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        self.assertIn('0 unpinned text writes', proc.stdout)


if __name__ == '__main__':
    unittest.main()
